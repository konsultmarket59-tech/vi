def mm(plan):
    k, (ox, oy) = plan['k'], plan['o']
    X = lambda v: int(round((v - ox) * k / 10.0) * 10)
    Y = lambda v: int(round((v - oy) * k / 10.0) * 10)
    R = lambda r: [X(r[0]), Y(r[1]), X(r[2]), Y(r[3])]
    out = {
        'id': plan['id'], 'area': plan['area'], 'note': plan['note'], 'link': plan['link'],
        'walls': [R(r) for r in plan['walls']],
        'windows': [R(r) for r in plan['windows']],
        'doors': [{**d, 'r': R(d['r'])} for d in plan['doors']],
        'rooms': [{'n': r['n'], 'a': r['a'], 'k': r['k'], 'r': [R(x) for x in r['r']]} for r in plan['rooms']],
        'zones': [R(z) for z in plan.get('zones', [])],
        'decks': [{'k': d['k'], 'r': R(d['r'])} for d in plan['decks']],
        'posts': [[X(p[0]), Y(p[1])] for p in plan['posts']],
        'roof': [R(r) for r in plan['roof']],
        'fixed': [{'type': f['t'], 'x': X(f['x']), 'y': Y(f['y']), 'rot': f['rot'], 'w': f['w'], 'd': f['d']} for f in plan.get('fixed', [])],
    }
    xs = [v for r in out['walls'] for v in (r[0], r[2])]
    ys = [v for r in out['walls'] for v in (r[1], r[3])]
    out['box'] = [min(xs), min(ys), max(xs), max(ys)]
    return out


def plans_json():
    # 'hidden': True — план есть в данных, но в блоке не показывается
    return json.dumps([mm(p) for p in PLANS if not p.get('hidden')], ensure_ascii=False, separators=(',', ':'))


