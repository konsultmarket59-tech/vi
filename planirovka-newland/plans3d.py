def moved(items, dx=0, dy=0):
    """Тот же набор мебели, сдвинутый на dx, dy (в единицах чертежа)."""
    out = []
    for f in items:
        f = dict(f)
        if 'r' in f:
            f['r'] = [f['r'][0] + dx, f['r'][1] + dy, f['r'][2] + dx, f['r'][3] + dy]
        else:
            f['c'] = [f['c'][0] + dx, f['c'][1] + dy]
        out.append(f)
    return out


