BACK = {N: 0, E: 90, S: 180, W: 270}


def load_geo(plan):
    """Стены, окна и двери из geo/<имя>.json (их сохраняет pdf_plan.py), уже в мм."""
    if 'geo' not in plan:
        return plan
    g = json.loads((Path(__file__).parent / 'geo' / (plan['geo'] + '.json')).read_text(encoding='utf-8'))
    out = {'k': 1, 'o': (0, 0), 'decks': [], 'posts': [], **plan}
    out['walls'] = g['walls'] + plan.get('walls_add', [])
    out['windows'] = g['windows'] + plan.get('windows_add', [])
    # правки дверей поверх снятых скриптом: doors_set {номер: дверь или None}, doors_add [двери]
    fix = plan.get('doors_set', {})
    out['doors'] = [fix.get(i, d) for i, d in enumerate(g['doors']) if fix.get(i, d) is not None] + plan.get('doors_add', [])
    return out


def mm(plan):
    plan = load_geo(plan)
    k, (ox, oy) = plan['k'], plan['o']
    X = lambda v: int(round((v - ox) * k / 10.0) * 10)
    Y = lambda v: int(round((v - oy) * k / 10.0) * 10)
    R = lambda r: [X(r[0]), Y(r[1]), X(r[2]), Y(r[3])]
    furn = []
    for f in plan['furn']:
        o = {'type': f['t']}
        if 'r' in f:
            x1, y1, x2, y2 = R(f['r'])
            rot = BACK[f['b']] if isinstance(f['b'], str) else f['b']
            o.update(x=(x1 + x2) / 2, y=(y1 + y2) / 2, rot=rot)
            o['w'], o['d'] = (x2 - x1, y2 - y1) if rot % 180 == 0 else (y2 - y1, x2 - x1)
            if 'w' in f:
                o['w'] = f['w']
        else:
            o.update(x=X(f['c'][0]), y=Y(f['c'][1]), w=f['w'], d=f['d'], rot=f['rot'])
        for key in ('h', 'mir'):
            if key in f:
                o[key] = f[key]
        if 'c' in f and isinstance(f['c'], str):
            o['color'] = f['c']
        o['x'], o['y'] = round(o['x']), round(o['y'])
        furn.append(o)
    rooms = []
    for r in plan['rooms']:
        o = {'n': r['n'], 'a': r['a'], 'k': r['k'], 'r': [R(x) for x in r['r']]}
        if 'lp' in r:
            o['lp'] = [X(r['lp'][0]), Y(r['lp'][1])]
        rooms.append(o)
    out = {
        'id': plan['id'], 'title': plan['title'], 'note': plan['note'],
        'walls': [R(r) for r in plan['walls']],
        'windows': [R(r) for r in plan['windows']],
        'doors': [{**d, 'r': R(d['r'])} for d in plan['doors']],
        'rooms': rooms,
        'decks': [R(r) for r in plan['decks']],
        'posts': [[X(p[0]), Y(p[1])] for p in plan['posts']],
        'furn': furn,
    }
    xs = [v for r in out['walls'] for v in (r[0], r[2])]
    ys = [v for r in out['walls'] for v in (r[1], r[3])]
    out['box'] = [min(xs), min(ys), max(xs), max(ys)]
    return out


