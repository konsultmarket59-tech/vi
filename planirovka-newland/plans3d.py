"""Планировки и мебель из ветки planirovki-3d (planirovki-3d/plans.py), скопировано без изменений.
Отсюда берутся рекомендованная расстановка для домов КЛАССИК и все дома СМАРТ.

Планировки домов для 3D-просмотра: стены, проёмы, помещения и мебель.

Координаты сняты с чертежей в пикселях и переводятся в миллиметры:
(px - начало) * масштаб. Начало — наружный левый верхний угол коробки дома,
масштаб — миллиметров в одном пикселе чертежа. Прямоугольник — [x1, y1, x2, y2].

Стены дома 60, 85, 100 и 120 м² взяты из «Примерки планировки»
(ветка claude/sharp-knuth-h7v5wu, planirovka-newland/plans.py).

Двери: r — проём в стене; hinge 'a' — петли у меньшей координаты проёма, 'b' — у большей;
side -1/1 — полотно открывается в сторону меньшей/большей координаты поперёк стены;
ext — наружная дверь (в 3D закрыта).

Помещения: n — назначение, a — площадь по чертежу, k — тип пола и цвета
(living, kitchen, bed, wet, hall, tech, terrace), r — один или несколько прямоугольников.
Терраса и крыльцо — тоже помещения с k='terrace': у них будет подпись с площадью.

Для планов из PDF (поле geo) стены, окна и двери берутся из geo/<имя>.json; поправить их можно
полями walls_add, windows_add, doors_add и doors_set {номер двери: новая дверь или None — убрать}.

Мебель стоит как на чертежах:
  F(тип, x1, y1, x2, y2, спинка) — предмет вписан в прямоугольник чертежа.
      Спинка — сторона, к которой предмет стоит задом: 'n' вверх по чертежу, 'e' вправо,
      's' вниз, 'w' влево. У кровати спинка — изголовье, у шкафа и кухни — стена за ними.
  C(тип, x, y, ширина_мм, глубина_мм, поворот) — предмет по центру в пикселях и размеру в мм,
      поворот в градусах по часовой: 0 — спинкой вверх, 90 — вправо, 180 — вниз, 270 — влево.
  Необязательно: h — высота в мм, c — цвет, mir=True — зеркально (угловой диван).
Список типов — в CAT внутри template.html.
"""
import json
import math
from pathlib import Path

N, E, S, W = 'n', 'e', 's', 'w'


def F(t, x1, y1, x2, y2, back=N, **kw):
    return {'t': t, 'r': [x1, y1, x2, y2], 'b': back, **kw}


def C(t, x, y, w, d, rot=0, **kw):
    return {'t': t, 'c': [x, y], 'w': w, 'd': d, 'rot': rot, **kw}


def ring(t, cx, cy, rad, angles, w=450, d=480):
    """Стулья вокруг круглого стола: угол 0 — справа от стола, по часовой."""
    out = []
    for a in angles:
        r = math.radians(a)
        # спинка смотрит от стола
        out.append(C(t, cx + rad * math.cos(r), cy + rad * math.sin(r), w, d, (a + 90) % 360))
    return out


