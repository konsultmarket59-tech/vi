DK.cityMatch = function (cities, city) {
  const n = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/\b(г|д|пос|с)\.\s*/g, '').trim();
  const c = n(city); if (!c) return true;
  return (cities || []).some(x => {
    const v = n(x); if (!v) return false;
    if (v === 'вся россия' || c.includes(v) || v.includes(c.split(',')[0].trim())) return true;
    const reg = DK.REGIONS[v.replace(/ё/g, 'е')]; return !!(reg && reg.some(t => c.includes(t)));
  });
};
