// Сводный план посёлка: очередь бригад и поставки по улицам.
//
// Отдельный экран нужен потому, что главные деньги теряются не внутри дома, а
// между домами. График каждого дома в отдельности показывает красивый срок; в
// сумме одна бригада каменщиков стоит в очереди на пяти объектах, а пять домов
// одной улицы заказывают блоки в разные дни и оплачивают пять рейсов вместо
// двух.
//
// Экономия показана цифрой — «рейсов было / стало». Объединение поставок без
// этой цифры остаётся мнением, а с ней это разговор про деньги.

import { useCallback, useEffect, useState } from "react";
import type { ПланПосёлка, Посёлок, ПредложениеЛогистики, Роль } from "../lib/types";
import { дата, рубли, число } from "../lib/types";

interface Свойства {
  посёлок: Посёлок | null;
  роль: Роль;
  наДом(папка: string): void;
  наОшибку(текст: string): void;
}

export default function СводныйПлан(п: Свойства) {
  const [план, setПлан] = useState<ПланПосёлка | null>(null);
  const [вкладка, setВкладка] = useState<"поставки" | "бригады" | "сроки">("поставки");
  const [совет, setСовет] = useState<{ предложения: ПредложениеЛогистики[]; риски: { что: string; когда: string; "кого касается": string }[]; вывод: string } | null>(null);
  const [занято, setЗанято] = useState(false);

  const загрузить = useCallback(() => {
    if (!п.посёлок) return;
    window.стройка
      .планПосёлка(п.посёлок.папка)
      .then(setПлан)
      .catch((e) => п.наОшибку(String(e.message || e)));
  }, [п]);

  useEffect(загрузить, [загрузить]);

  if (!п.посёлок) return <div className="view"><div className="пусто">Выберите посёлок.</div></div>;
  if (!план) return <div className="загрузка">Считаем сводный план…</div>;
  if (план.пусто) {
    return (
      <div className="view">
        <div className="пусто">
          В посёлке нет строящихся домов. Сводный план считается по домам со статусом «план» и
          «стройка».
        </div>
      </div>
    );
  }

  const поставки = план.поставки!;

  return (
    <div className="view">
      <div className="ряд-между" style={{ marginBottom: 10 }}>
        <div className="ряд">
          <span className="метка охра">{план.домов} дом(ов)</span>
          <span className="метка">поставок {поставки.поставки.length}</span>
          <span className="метка зелёная">
            рейсов {поставки.рейсовБезОбъединения} → {поставки.рейсовСОбъединением}
          </span>
          <span className="метка зелёная">экономия доставки {рубли(поставки.экономияДоставки)}</span>
          {(план.срыв?.length ?? 0) > 0 && <span className="метка красная">срыв сроков: {план.срыв!.length}</span>}
        </div>
        <button
          className="кн"
          disabled={занято}
          onClick={async () => {
            setЗанято(true);
            try {
              const ответ = await window.стройка.логистикаАгентом(п.посёлок!.папка);
              if (!ответ.ok) throw new Error(ответ.ошибка || "Агент не ответил");
              setСовет(ответ);
            } catch (e) {
              п.наОшибку(e instanceof Error ? e.message : String(e));
            } finally {
              setЗанято(false);
            }
          }}
        >
          {занято ? "Агент смотрит план…" : "Спросить агента, что переставить"}
        </button>
      </div>

      {(план.срыв?.length ?? 0) > 0 && (
        <div className="ошибка">
          <b>Не укладываемся в договорные сроки:</b>
          {план.срыв!.map((с) => (
            <div key={с.дом}>
              {с.дом}: по договору {дата(с.договор)}, получается {дата(с.получается)} — опоздание {с.опоздание} дн.
            </div>
          ))}
          Очередь бригад раздаётся по договорному сроку: первым считается дом, который сдавать
          раньше. Если сроки всё равно не сходятся, нужна ещё одна бригада — это видно во вкладке
          «Бригады».
        </div>
      )}

      {совет && (
        <div className="панель">
          <h2>Что предлагает агент</h2>
          <p className="подпись">
            Агент смотрит на уже построенный план и ищет то, чего не видят правила. Ни одной даты он
            не двигает — решает человек.
          </p>
          {совет.вывод && <p>{совет.вывод}</p>}
          {совет.предложения.map((пр, i) => (
            <div key={i} style={{ borderTop: "1px solid var(--bg-active)", padding: "8px 0" }}>
              <div className="ряд">
                <span className="метка охра">{пр.вид}</span>
                <b>{пр.что}</b>
              </div>
              <div className="подпись мелко">
                зачем: {пр.зачем}
                {пр.риск ? ` · риск: ${пр.риск}` : ""}
                {пр.экономия && пр.экономия !== "—" ? ` · экономия: ${пр.экономия}` : ""}
              </div>
              {пр.поставки?.length > 0 && <div className="подпись мелко">касается: {пр.поставки.join("; ")}</div>}
            </div>
          ))}
          {совет.риски.length > 0 && (
            <div style={{ marginTop: 8 }}>
              <b>Риски</b>
              {совет.риски.map((р, i) => (
                <div key={i} className="подпись мелко">
                  {р.когда}: {р.что} → {р["кого касается"]}
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      <div className="вкладки" style={{ padding: 0, marginBottom: 10, background: "transparent", borderBottom: "1px solid var(--border)" }}>
        <button className={`вкладка ${вкладка === "поставки" ? "on" : ""}`} onClick={() => setВкладка("поставки")}>
          График поставок
        </button>
        <button className={`вкладка ${вкладка === "бригады" ? "on" : ""}`} onClick={() => setВкладка("бригады")}>
          Загрузка бригад
        </button>
        <button className={`вкладка ${вкладка === "сроки" ? "on" : ""}`} onClick={() => setВкладка("сроки")}>
          Сроки по домам
        </button>
      </div>

      {вкладка === "поставки" && (
        <>
          {поставки.вРаспутицу > 0 && (
            <div className="внимание">
              Тяжёлых поставок, попавших в весенние ограничения нагрузки на ось: {поставки.вРаспутицу}.
              Такие поставки сдвинуты автоматически — либо завозятся заранее, либо после снятия
              ограничений. Даты ограничений можно поправить в настройках.
            </div>
          )}

          <div className="панель" style={{ padding: 0 }}>
            <div className="прокрутка">
              <table className="таблица">
                <thead>
                  <tr>
                    <th style={{ width: 88 }}>Дата</th>
                    <th style={{ width: 110 }}>Улица</th>
                    <th>Материал</th>
                    <th className="ч" style={{ width: 96 }}>Кол-во</th>
                    <th className="ч" style={{ width: 62 }}>Домов</th>
                    <th style={{ width: 128 }}>Транспорт</th>
                    <th className="ч" style={{ width: 104 }}>Сумма</th>
                  </tr>
                </thead>
                <tbody>
                  {поставки.поставки.map((пост) => (
                    <tr key={пост.id}>
                      <td>
                        {дата(пост.дата)}
                        {пост.хранениеДней > 0 && <div className="подпись мелко">лежит {пост.хранениеДней} дн.</div>}
                      </td>
                      <td>{пост.улица}</td>
                      <td>
                        {пост.наименование}
                        {пост.замечания.map((з, i) => (
                          <div key={i} className="подпись мелко">
                            {з}
                          </div>
                        ))}
                      </td>
                      <td className="ч">
                        {число(пост.количество, 1)} {пост.единица}
                      </td>
                      <td className="ч">
                        {пост.домов > 1 ? <span className="метка зелёная">{пост.домов}</span> : пост.домов}
                      </td>
                      <td className="мелко">
                        {пост.транспортНазвание}
                        <div className="подпись мелко">
                          {пост.рейсов} рейс · {число(пост.тонн, 1)} т
                        </div>
                      </td>
                      <td className="ч">{рубли(пост.сумма, false)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          <div className="панель">
            <h2>Деньги на материалы по месяцам</h2>
            <table className="таблица">
              <thead>
                <tr>
                  <th style={{ width: 110 }}>Месяц</th>
                  <th className="ч">Поставок</th>
                  <th className="ч">Рейсов</th>
                  <th className="ч">Доставка</th>
                  <th className="ч">Материалы</th>
                </tr>
              </thead>
              <tbody>
                {поставки.поМесяцам.map((м) => (
                  <tr key={м.месяц}>
                    <td>{м.месяц}</td>
                    <td className="ч">{м.поставок}</td>
                    <td className="ч">{м.рейсов}</td>
                    <td className="ч">{рубли(м.доставка, false)}</td>
                    <td className="ч">{рубли(м.сумма, false)}</td>
                  </tr>
                ))}
              </tbody>
              <tfoot>
                <tr>
                  <td>Всего</td>
                  <td className="ч">{поставки.поставки.length}</td>
                  <td className="ч">{поставки.рейсовСОбъединением}</td>
                  <td className="ч">{рубли(поставки.поМесяцам.reduce((s, м) => s + м.доставка, 0), false)}</td>
                  <td className="ч">{рубли(поставки.сумма, false)}</td>
                </tr>
              </tfoot>
            </table>
          </div>
        </>
      )}

      {вкладка === "бригады" && (
        <>
          <div className="панель">
            <h2>Загрузка бригад по месяцам</h2>
            <p className="подпись">
              В сменах, а не в процентах: норма рабочих дней у каждого своя (5/2, 6/1, вахта), и спор
              о знаменателе съедает разговор о самой загрузке. Ожиданий бригады в плане:{" "}
              {план.ожидание}.
            </p>
            <table className="таблица">
              <thead>
                <tr>
                  <th style={{ width: 110 }}>Месяц</th>
                  <th>Бригада</th>
                  <th className="ч" style={{ width: 90 }}>Смен</th>
                  <th className="ч" style={{ width: 100 }}>Объектов</th>
                </tr>
              </thead>
              <tbody>
                {план.загрузка!.map((з) => (
                  <tr key={`${з.бригада}-${з.месяц}`}>
                    <td>{з.месяц}</td>
                    <td>{з.бригада}</td>
                    <td className="ч">{з.смен}</td>
                    <td className="ч">{з.объектов}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <div className="панель" style={{ padding: 0 }}>
            <div className="прокрутка">
              <table className="таблица">
                <thead>
                  <tr>
                    <th style={{ width: 90 }}>Начало</th>
                    <th style={{ width: 90 }}>Конец</th>
                    <th style={{ width: 130 }}>Бригада</th>
                    <th style={{ width: 140 }}>Дом</th>
                    <th>Этап</th>
                    <th className="ч" style={{ width: 62 }}>Смен</th>
                  </tr>
                </thead>
                <tbody>
                  {план.очередь!.map((о, i) => (
                    <tr key={i}>
                      <td>{дата(о.начало)}</td>
                      <td>{дата(о.конец)}</td>
                      <td>{о.бригада}</td>
                      <td>{о.дом}</td>
                      <td>
                        {о.этап}
                        {о.ждала && <div className="подпись мелко">{о.ждала}</div>}
                      </td>
                      <td className="ч">{о.смен}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </>
      )}

      {вкладка === "сроки" && (
        <div className="панель">
          <h2>Сроки по домам</h2>
          <table className="таблица">
            <thead>
              <tr>
                <th>Дом</th>
                <th style={{ width: 96 }}>Начало</th>
                <th style={{ width: 96 }}>Сдача</th>
                <th style={{ width: 110 }}>По договору</th>
                <th className="ч" style={{ width: 80 }}>Этапов</th>
                <th style={{ width: 90 }} />
              </tr>
            </thead>
            <tbody>
              {план.сдачи!.map((с) => {
                const опоздание = с.договор && с.сдача > с.договор;
                return (
                  <tr key={с.ключ}>
                    <td>{с.дом}</td>
                    <td>{дата(с.начало)}</td>
                    <td className={опоздание ? "перерасход" : ""}>{дата(с.сдача)}</td>
                    <td>{с.договор ? дата(с.договор) : "—"}</td>
                    <td className="ч">{с.этапов}</td>
                    <td>
                      <button className="ссылка" onClick={() => п.наДом(с.папка)}>
                        открыть
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
