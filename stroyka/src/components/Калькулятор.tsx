// Калькулятор: ввели размеры — получили объёмы, материалы и деньги.
//
// Пересчёт идёт на каждый ввод, а не по кнопке «рассчитать»: человек подбирает
// толщину стены и смотрит, как меняется итог, — при кнопке этот подбор
// превращается в двадцать нажатий.
//
// И при этом «Применить в смету» — отдельное осознанное действие. Пока его не
// нажали, в смете не прибавилось ни строки: расчёт лежит отдельным документом.
// Это написано прямо под кнопкой, потому что иначе смета за неделю зарастает
// пробными вариантами одной стены.

import { useCallback, useEffect, useState } from "react";
import type { Настройки, Расчёт, Роль, Справочники, ВидРабот } from "../lib/types";
import { рубли, число } from "../lib/types";

interface Свойства {
  посёлок: string;
  дом: string;
  ключ: string;
  роль: Роль;
  справочники: Справочники;
  площадь: number;
  настройки: Настройки;
  наОшибку(текст: string): void;
}

export default function Калькулятор(п: Свойства) {
  const [вид, setВид] = useState<ВидРабот | null>(п.справочники.видыРабот[2] || п.справочники.видыРабот[0] || null);
  const [параметры, setПараметры] = useState<Record<string, number>>({});
  const [расчёт, setРасчёт] = useState<Расчёт | null>(null);
  const [применено, setПрименено] = useState(0);
  const [считаем, setСчитаем] = useState(false);
  const [прикидка, setПрикидка] = useState<{ расчёты: Расчёт[]; итого: number; итогРабот: number; итогМатериалов: number } | null>(null);

  useEffect(() => {
    if (!вид) return;
    setПараметры(Object.fromEntries(вид.параметры.map((пар) => [пар.ключ, пар.поумолчанию])));
    setПрименено(0);
  }, [вид]);

  const посчитать = useCallback(
    async (текущие: Record<string, number>) => {
      if (!вид) return;
      setСчитаем(true);
      try {
        setРасчёт(await window.стройка.посчитать(вид.id, текущие, п.ключ));
      } catch (e) {
        п.наОшибку(e instanceof Error ? e.message : String(e));
      } finally {
        setСчитаем(false);
      }
    },
    [вид, п]
  );

  useEffect(() => {
    if (вид && Object.keys(параметры).length) посчитать(параметры);
  }, [вид, параметры, посчитать]);

  const регион = п.справочники.регионы.find((р) => р.id === п.настройки.регион);
  const сложность = п.справочники.сложность.find((с) => с.id === п.настройки.сложность);

  return (
    <>
      <div className="ряд-между" style={{ marginBottom: 10 }}>
        <div className="ряд">
          <label className="поле">
            Вид работ
            <select
              value={вид?.id || ""}
              onChange={(e) => setВид(п.справочники.видыРабот.find((в) => в.id === e.target.value) || null)}
            >
              {п.справочники.видыРабот.map((в) => (
                <option key={в.id} value={в.id}>
                  {в.название}
                </option>
              ))}
            </select>
          </label>
          {вид?.сезон?.запрет?.length ? (
            <span className="метка жёлтая" title={вид.сезон.причина}>
              сезон: нельзя в {вид.сезон.запрет.map((м) => МЕСЯЦЫ[м - 1]).join(", ")}
            </span>
          ) : null}
        </div>
        <button
          className="кн"
          onClick={async () => {
            try {
              setПрикидка(await window.стройка.прикидка(п.площадь || 100, п.ключ));
            } catch (e) {
              п.наОшибку(e instanceof Error ? e.message : String(e));
            }
          }}
        >
          Прикинуть весь дом по площади
        </button>
      </div>

      {вид && (
        <div className="панель">
          <div className="поля">
            {вид.параметры.map((пар) => (
              <label className="поле" key={пар.ключ}>
                {пар.название}
                {пар.единица ? `, ${пар.единица}` : ""}
                <input
                  value={параметры[пар.ключ] ?? пар.поумолчанию}
                  inputMode="decimal"
                  onChange={(e) => setПараметры({ ...параметры, [пар.ключ]: Number(e.target.value) || 0 })}
                />
              </label>
            ))}
          </div>
          <div className="ряд" style={{ marginTop: 10 }}>
            <span className="метка синяя">
              {регион?.название || "регион"} ×{регион?.коэффициент ?? 1}
            </span>
            <span className="метка синяя">
              {сложность?.название || "сложность"} ×{сложность?.коэффициент ?? 1}
            </span>
            <span className="подпись мелко">
              к материалам коэффициенты не применяются: материал стоит столько, сколько просит
              поставщик
            </span>
          </div>
        </div>
      )}

      {расчёт && (
        <div className="панель" style={{ padding: 0 }}>
          <table className="таблица">
            <thead>
              <tr>
                <th>Ресурс</th>
                <th style={{ width: 60 }}>Ед.</th>
                <th className="ч" style={{ width: 90 }}>Кол-во</th>
                <th className="ч" style={{ width: 90 }}>Цена</th>
                <th className="ч" style={{ width: 110 }}>Сумма</th>
              </tr>
            </thead>
            <tbody>
              {расчёт.ресурсы.map((р) => (
                <tr key={р.наименование}>
                  <td>
                    {р.наименование}
                    <div className="подпись мелко">
                      {р.вид}
                      {р.коэффициент !== 1 && ` · коэффициент ×${р.коэффициент}`}
                      {р.запас > 0 && ` · запас ${Math.round(р.запас * 100)}% (в объём работ не входит)`}
                      {р.источникЦены && ` · ${р.источникЦены}`}
                      {!р.источникЦены && р.цена == null && " · цены в прайсе нет"}
                    </div>
                  </td>
                  <td>{р.единица}</td>
                  <td className="ч">{число(р.количество, 2)}</td>
                  <td className="ч">{р.цена == null ? "—" : рубли(р.цена, false)}</td>
                  <td className="ч">{р.сумма == null ? "—" : рубли(р.сумма, false)}</td>
                </tr>
              ))}
            </tbody>
            <tfoot>
              <tr>
                <td colSpan={2}>
                  Итого по расчёту
                  <div className="подпись мелко">
                    объём {число(расчёт.объём, 2)} {расчёт.единица} · {расчёт.сменБригады} смен бригады
                  </div>
                </td>
                <td className="ч подпись мелко">работы</td>
                <td className="ч">{рубли(расчёт.итогРабот, false)}</td>
                <td className="ч">{рубли(расчёт.итого, false)}</td>
              </tr>
            </tfoot>
          </table>
        </div>
      )}

      {расчёт?.замечания.length ? (
        <div className="внимание">
          {расчёт.замечания.map((з, i) => (
            <div key={i}>{з}</div>
          ))}
        </div>
      ) : null}

      {расчёт && п.роль.действия.includes("правитьСмету") && (
        <div className="ряд">
          <button
            className="кн главная"
            disabled={считаем}
            onClick={async () => {
              try {
                await window.стройка.применитьРасчёт(п.посёлок, п.дом, расчёт);
                setПрименено(расчёт.ресурсы.length);
              } catch (e) {
                п.наОшибку(e instanceof Error ? e.message : String(e));
              }
            }}
          >
            Применить в смету
          </button>
          <span className="подпись">
            {применено > 0
              ? `Добавлено ${применено} позиций в смету дома.`
              : `Добавит ${расчёт.ресурсы.length} позиций в смету. Пока кнопку не нажали — в смете 0 новых позиций.`}
          </span>
        </div>
      )}

      {прикидка && (
        <div className="панель" style={{ marginTop: 14 }}>
          <h2>Прикидка по площади — {число(п.площадь || 100, 0)} м²</h2>
          <p className="подпись">
            Это стартовая точка, а не расчёт по чертежам: параметры взяты из площади дома. Годится,
            чтобы назвать порядок цифр сегодня, пока проекта ещё нет.
          </p>
          <table className="таблица">
            <thead>
              <tr>
                <th>Этап</th>
                <th>Работа</th>
                <th className="ч">Объём</th>
                <th className="ч">Смен</th>
                <th className="ч">Сумма</th>
              </tr>
            </thead>
            <tbody>
              {прикидка.расчёты.map((р) => (
                <tr key={р.вид}>
                  <td>{р.этап}</td>
                  <td>{р.название}</td>
                  <td className="ч">
                    {число(р.объём, 1)} {р.единица}
                  </td>
                  <td className="ч">{р.сменБригады}</td>
                  <td className="ч">{р.итого ? рубли(р.итого, false) : "—"}</td>
                </tr>
              ))}
            </tbody>
            <tfoot>
              <tr>
                <td colSpan={3}>Всего</td>
                <td className="ч">{прикидка.расчёты.reduce((s, р) => s + р.сменБригады, 0)}</td>
                <td className="ч">{рубли(прикидка.итого, false)}</td>
              </tr>
            </tfoot>
          </table>
        </div>
      )}
    </>
  );
}

const МЕСЯЦЫ = ["янв", "фев", "мар", "апр", "май", "июн", "июл", "авг", "сен", "окт", "ноя", "дек"];
