// Смета: план и факт в одной строке.
//
// Колонки приходят с той стороны уже отфильтрованными по роли — здесь мы
// показываем то, что дали, и не решаем заново, кому что видно. Поэтому таблица
// строится по фактическому набору полей позиции, а не по списку «как надо»:
// если у роли нет закупочной цены, её нет и в данных.

import { useCallback, useEffect, useState } from "react";
import type { ПозицияСметы, Роль, Смета as ТипСметы, Справочники } from "../lib/types";
import { дата, датаВремя, рубли, число } from "../lib/types";

interface Свойства {
  посёлок: string;
  дом: string;
  ключ: string;
  роль: Роль;
  справочники: Справочники;
  наОшибку(текст: string): void;
}

const ЗАГОЛОВКИ: Record<string, string> = {
  ценаЗакупки: "Закупка",
  ценаЗаказчику: "Цена",
  суммаЗакупки: "Себест.",
  суммаЗаказчику: "Сумма",
  количествоФакт: "Факт",
  суммаФакт: "Сумма факт",
  отклонение: "Откл.",
  маржа: "Маржа",
};

export default function Смета(п: Свойства) {
  const [смета, setСмета] = useState<ТипСметы | null>(null);
  const [журнал, setЖурнал] = useState(false);
  const [добавление, setДобавление] = useState(false);
  const [занято, setЗанято] = useState(false);
  const [сообщение, setСообщение] = useState("");

  const загрузить = useCallback(() => {
    window.стройка
      .смета(п.посёлок, п.дом)
      .then(setСмета)
      .catch((e) => п.наОшибку(String(e.message || e)));
  }, [п]);

  useEffect(загрузить, [загрузить]);

  async function действие(что: () => Promise<ТипСметы>) {
    setЗанято(true);
    try {
      setСмета(await что());
      setСообщение("");
    } catch (e) {
      п.наОшибку(e instanceof Error ? e.message : String(e));
    } finally {
      setЗанято(false);
    }
  }

  if (!смета) return <div className="загрузка">Читаем смету…</div>;

  const позиции = смета.позиции;
  const естьКолонка = (ключ: keyof ПозицияСметы) => позиции.some((поз) => поз[ключ] !== undefined);
  const колонки = (Object.keys(ЗАГОЛОВКИ) as (keyof ПозицияСметы)[]).filter(естьКолонка);
  const можноПравить = п.роль.действия.includes("правитьСмету");
  const можноФакт = п.роль.действия.includes("правитьФакт");
  const можноСогласовать = п.роль.действия.includes("согласоватьСмету");

  return (
    <>
      <div className="ряд-между" style={{ marginBottom: 10 }}>
        <div className="ряд">
          <МеткаСтатуса статус={смета.статус} />
          <span className="подпись">
            позиций {смета.итог.позиций} · с внесённым фактом {смета.итог.сФактом}
            {смета.итог.безЦены > 0 && ` · без цены ${смета.итог.безЦены}`}
          </span>
        </div>
        <div className="ряд">
          <button className="ссылка" onClick={() => setЖурнал(!журнал)}>
            {журнал ? "скрыть журнал" : `журнал изменений (${смета.журнал.length})`}
          </button>
          {можноПравить && (
            <button className="кн" onClick={() => setДобавление(!добавление)}>
              Добавить позицию
            </button>
          )}
          {можноСогласовать && (
            <button
              className="кн главная"
              disabled={занято || !позиции.length}
              onClick={() => {
                const комментарий = prompt("Комментарий к согласованию (например, номер договора):") ?? "";
                действие(() => window.стройка.согласоватьСмету(п.посёлок, п.дом, комментарий));
              }}
            >
              Согласовать смету
            </button>
          )}
        </div>
      </div>

      {смета.статус === "изменена после согласования" && (
        <ИзмененияПослеСогласования посёлок={п.посёлок} дом={п.дом} />
      )}
      {сообщение && <div className="успех">{сообщение}</div>}

      {добавление && (
        <ФормаПозиции
          справочники={п.справочники}
          наГотово={async (данные) => {
            await действие(() => window.стройка.добавитьПозицию(п.посёлок, п.дом, данные));
            setДобавление(false);
          }}
        />
      )}

      {позиции.length === 0 ? (
        <div className="пусто">
          В смете пока пусто. Посчитайте объёмы в «Калькуляторе» и нажмите там «Применить в смету» —
          позиции появятся здесь вместе с параметрами, по которым их посчитали.
        </div>
      ) : (
        <div className="панель" style={{ padding: 0 }}>
          <div className="прокрутка">
            <table className="таблица">
              <thead>
                <tr>
                  <th style={{ width: 44 }}>№</th>
                  <th>Наименование</th>
                  <th style={{ width: 52 }}>Ед.</th>
                  <th className="ч" style={{ width: 78 }}>Кол-во</th>
                  {колонки.map((к) => (
                    <th key={String(к)} className="ч" style={{ width: 92 }}>
                      {ЗАГОЛОВКИ[String(к)]}
                    </th>
                  ))}
                  {можноПравить && <th style={{ width: 30 }} />}
                </tr>
              </thead>
              <tbody>
                {позиции.map((поз) => (
                  <tr key={поз.id}>
                    <td className="подпись мелко">{поз.номер}</td>
                    <td>
                      {поз.наименование}
                      <div className="подпись мелко">
                        {поз.этап} · {поз.вид}
                        {поз.примечание ? ` · ${поз.примечание}` : ""}
                      </div>
                    </td>
                    <td>{поз.единица}</td>
                    <td className="ч">
                      {можноПравить ? (
                        <input
                          className="ч"
                          defaultValue={поз.количество}
                          onBlur={(e) => {
                            const значение = Number(e.target.value);
                            if (значение !== поз.количество && Number.isFinite(значение)) {
                              действие(() => window.стройка.правитьПозицию(п.посёлок, п.дом, поз.id, { количество: значение }));
                            }
                          }}
                        />
                      ) : (
                        число(поз.количество, 2)
                      )}
                    </td>
                    {колонки.map((к) => (
                      <td key={String(к)} className="ч">
                        <Ячейка поз={поз} колонка={к} можноФакт={можноФакт} можноПравить={можноПравить}
                          наИзменение={(значение) =>
                            к === "количествоФакт"
                              ? действие(() => window.стройка.внестиФакт(п.посёлок, п.дом, поз.id, значение, "внесено в смете"))
                              : действие(() => window.стройка.правитьПозицию(п.посёлок, п.дом, поз.id, { [к]: значение }))
                          }
                        />
                      </td>
                    ))}
                    {можноПравить && (
                      <td>
                        <button
                          className="ссылка"
                          title="удалить позицию"
                          onClick={() => действие(() => window.стройка.удалитьПозицию(п.посёлок, п.дом, поз.id))}
                        >
                          ×
                        </button>
                      </td>
                    )}
                  </tr>
                ))}
              </tbody>
              <tfoot>
                <tr>
                  <td colSpan={4}>Итого</td>
                  {колонки.map((к) => (
                    <td key={String(к)} className="ч">
                      {к === "суммаЗаказчику" && рубли(смета.итог.заказчику)}
                      {к === "суммаЗакупки" && рубли(смета.итог.закупка)}
                      {к === "суммаФакт" && рубли(смета.итог.факт)}
                      {к === "маржа" && рубли(смета.итог.маржа)}
                    </td>
                  ))}
                  {можноПравить && <td />}
                </tr>
              </tfoot>
            </table>
          </div>
        </div>
      )}

      {смета.итог.рентабельность !== undefined && (
        <div className="панель">
          <div className="ряд" style={{ gap: 24 }}>
            <Цифра что="Себестоимость" значение={рубли(смета.итог.закупка)} />
            <Цифра что="Заказчику" значение={рубли(смета.итог.заказчику)} />
            <Цифра что="Маржа" значение={рубли(смета.итог.маржа)} />
            <Цифра что="Рентабельность" значение={`${смета.итог.рентабельность}%`} />
          </div>
        </div>
      )}

      {журнал && (
        <div className="панель">
          <h2>Журнал изменений</h2>
          <p className="подпись">
            Через месяц вопрос «откуда взялась эта цифра» задают обязательно. Здесь ответ: кто, когда,
            что было и что стало.
          </p>
          <div className="прокрутка">
            <table className="таблица">
              <thead>
                <tr>
                  <th style={{ width: 120 }}>Когда</th>
                  <th style={{ width: 150 }}>Кто</th>
                  <th>Что</th>
                  <th style={{ width: 190 }}>Было → стало</th>
                </tr>
              </thead>
              <tbody>
                {смета.журнал.map((з) => (
                  <tr key={з.id}>
                    <td className="подпись мелко">{датаВремя(з.когда)}</td>
                    <td>
                      {з.кто}
                      <div className="подпись мелко">{з.роль}</div>
                    </td>
                    <td>
                      {з.что}
                      {з.наименование ? ` · ${з.наименование}` : ""}
                      {з.основание ? ` · ${з.основание}` : ""}
                    </td>
                    <td className="мелко">
                      {з.было !== undefined || з.стало !== undefined
                        ? `${з.было ?? "—"} → ${з.стало ?? "—"}`
                        : ""}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {смета.версии.length > 0 && (
        <div className="панель">
          <h2>Согласованные версии</h2>
          <table className="таблица">
            <tbody>
              {смета.версии.map((в) => (
                <tr key={в.id}>
                  <td style={{ width: 130 }}>{датаВремя(в.когда)}</td>
                  <td>
                    {в.кто}
                    <div className="подпись мелко">{в.комментарий}</div>
                  </td>
                  <td className="ч">{рубли(в.итог.заказчику)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </>
  );
}

function Ячейка({
  поз,
  колонка,
  можноФакт,
  можноПравить,
  наИзменение,
}: {
  поз: ПозицияСметы;
  колонка: keyof ПозицияСметы;
  можноФакт: boolean;
  можноПравить: boolean;
  наИзменение(значение: number): void;
}) {
  const значение = поз[колонка] as number | null | undefined;

  if (колонка === "количествоФакт") {
    if (!можноФакт) return <>{значение == null ? "—" : число(значение, 2)}</>;
    return (
      <input
        className="ч"
        defaultValue={значение ?? ""}
        placeholder="—"
        onBlur={(e) => {
          const n = e.target.value === "" ? null : Number(e.target.value);
          if (n !== значение && (n === null || Number.isFinite(n))) наИзменение(n as number);
        }}
      />
    );
  }

  if (колонка === "отклонение") {
    if (значение == null) return <>—</>;
    // Перерасход красным, экономия зелёной. Больше цвета в таблице нет, поэтому
    // одна красная цифра в списке из двухсот видна сразу.
    const класс = значение > 0 ? "перерасход" : значение < 0 ? "экономия" : "";
    return (
      <span className={класс}>
        {значение > 0 ? "+" : ""}
        {число(значение, 2)}
        {поз.отклонениеПроцент != null && <span className="подпись мелко"> ({поз.отклонениеПроцент}%)</span>}
      </span>
    );
  }

  if ((колонка === "ценаЗакупки" || колонка === "ценаЗаказчику") && можноПравить) {
    return (
      <input
        className="ч"
        defaultValue={значение ?? 0}
        onBlur={(e) => {
          const n = Number(e.target.value);
          if (n !== значение && Number.isFinite(n)) наИзменение(n);
        }}
      />
    );
  }

  return <>{рубли(значение, false)}</>;
}

function Цифра({ что, значение }: { что: string; значение: string }) {
  return (
    <div>
      <div className="подпись мелко">{что}</div>
      <div style={{ fontSize: 17, fontWeight: 700, fontVariantNumeric: "tabular-nums" }}>{значение}</div>
    </div>
  );
}

function МеткаСтатуса({ статус }: { статус: string }) {
  const класс =
    статус === "согласована" ? "зелёная" : статус === "изменена после согласования" ? "жёлтая" : статус === "на согласовании" ? "синяя" : "";
  return <span className={`метка ${класс}`}>{статус}</span>;
}

function ИзмененияПослеСогласования({ посёлок, дом }: { посёлок: string; дом: string }) {
  const [данные, setДанные] = useState<Awaited<ReturnType<Window["стройка"]["измененияСметы"]>>>(null);
  useEffect(() => {
    window.стройка.измененияСметы(посёлок, дом).then(setДанные).catch(() => setДанные(null));
  }, [посёлок, дом]);
  if (!данные || !данные.строки.length) return null;
  return (
    <div className="внимание">
      <b>Смета изменилась после согласования.</b> Было {рубли(данные.итогТогда)}, стало{" "}
      {рубли(данные.итогСейчас)} — разница {рубли(данные.разница)}. Строк изменилось:{" "}
      {данные.строки.length} (
      {данные.строки
        .slice(0, 3)
        .map((с) => `${с.вид} «${с.наименование}»`)
        .join(", ")}
      {данные.строки.length > 3 ? " и другие" : ""}).
    </div>
  );
}

function ФормаПозиции({ справочники, наГотово }: { справочники: Справочники; наГотово(данные: Partial<ПозицияСметы>): Promise<void> }) {
  const этапы = [...new Set(справочники.видыРабот.map((в) => в.этап))];
  const [данные, setДанные] = useState<Partial<ПозицияСметы>>({
    наименование: "",
    единица: "м²",
    количество: 0,
    ценаЗакупки: 0,
    вид: "работа",
    этап: этапы[0] || "Прочее",
  });
  return (
    <div className="панель">
      <div className="поля" style={{ alignItems: "end" }}>
        <label className="поле" style={{ gridColumn: "span 2" }}>
          Наименование
          <input value={данные.наименование} onChange={(e) => setДанные({ ...данные, наименование: e.target.value })} />
        </label>
        <label className="поле">
          Единица
          <input value={данные.единица} onChange={(e) => setДанные({ ...данные, единица: e.target.value })} />
        </label>
        <label className="поле">
          Количество
          <input value={String(данные.количество)} onChange={(e) => setДанные({ ...данные, количество: Number(e.target.value) || 0 })} />
        </label>
        <label className="поле">
          Цена закупки
          <input value={String(данные.ценаЗакупки)} onChange={(e) => setДанные({ ...данные, ценаЗакупки: Number(e.target.value) || 0 })} />
        </label>
        <label className="поле">
          Вид
          <select value={данные.вид} onChange={(e) => setДанные({ ...данные, вид: e.target.value as "работа" | "материал" })}>
            <option value="работа">работа</option>
            <option value="материал">материал</option>
          </select>
        </label>
        <label className="поле">
          Этап
          <select value={данные.этап} onChange={(e) => setДанные({ ...данные, этап: e.target.value })}>
            {этапы.map((э) => (
              <option key={э}>{э}</option>
            ))}
          </select>
        </label>
        <div>
          <button className="кн главная" disabled={!данные.наименование?.trim()} onClick={() => наГотово(данные)}>
            Добавить
          </button>
        </div>
      </div>
      <p className="подпись мелко" style={{ marginTop: 8 }}>
        Позиция попадёт в журнал с пометкой «внесено руками» — так потом видно, что она не из расчёта
        и не из проекта. Дата: {дата(new Date().toISOString())}.
      </p>
    </div>
  );
}
