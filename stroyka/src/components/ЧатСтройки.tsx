// Чат стройки: отчёты прораба, разбор агентом, отклонения и отчёт заказчику.
//
// Порядок здесь такой и другим быть не может:
//
//   прораб написал и приложил фото
//     → агент разобрал: этап, готовность, отклонения
//       → руководитель ПРИНЯЛ разбор (или поправил его)
//         → готовность уехала в график, отклонения ушли по ролям
//
// Третий шаг нельзя пропустить. Готовность этапа двигает график, график двигает
// поставки, поставки двигают деньги — цепочка, запущенная тем, что модель
// неправильно поняла фразу «закончили первый этаж», обходится дороже одного
// нажатия кнопки.
//
// Отчёт заказчику идёт тем же путём: агент пишет, руководитель правит и
// одобряет, и только одобренный отчёт становится файлом в папке заказчика.

import { useCallback, useEffect, useState } from "react";
import type { Чат, ОтчётКлиенту, Роль, Сообщение, Справочники } from "../lib/types";
import { дата, датаВремя } from "../lib/types";

interface Свойства {
  посёлок: string;
  дом: string;
  ключ: string;
  роль: Роль;
  справочники: Справочники;
  наОшибку(текст: string): void;
  наОбновление?(): void;
}

export default function ЧатСтройки(п: Свойства) {
  const [чат, setЧат] = useState<Чат | null>(null);
  const [текст, setТекст] = useState("");
  const [фото, setФото] = useState<string[]>([]);
  const [занято, setЗанято] = useState("");
  const [отчёт, setОтчёт] = useState<ОтчётКлиенту | null>(null);

  const загрузить = useCallback(() => {
    window.стройка
      .чат(п.посёлок, п.дом)
      .then((данные) => {
        setЧат(данные);
        п.наОбновление?.();
      })
      .catch((e) => п.наОшибку(String(e.message || e)));
  }, [п]);

  useEffect(загрузить, [загрузить]);

  if (!чат) return <div className="загрузка">Читаем ленту…</div>;

  const можноОтчитаться = п.роль.действия.includes("отчитатьсяОРаботах") || п.роль.действия.includes("видетьВсеОбъекты");
  const можноПринимать = п.роль.действия.includes("правитьГрафик") || п.роль.действия.includes("приниматьРаботы");
  const можноОдобрять = п.роль.действия.includes("одобритьОтчётКлиенту");

  return (
    <div className="колонки" style={{ gridTemplateColumns: "minmax(420px, 2fr) minmax(280px, 1fr)" }}>
      <div>
        {можноОтчитаться && (
          <div className="панель">
            <h2>Отчёт с объекта</h2>
            <textarea
              value={текст}
              onChange={(e) => setТекст(e.target.value)}
              placeholder="Что сделали за день, какие объёмы, что мешает. Обычными словами — разбирать будет агент."
            />
            <div className="ряд" style={{ marginTop: 8 }}>
              <button
                className="кн"
                onClick={async () => {
                  try {
                    const пути = await window.стройка.выбратьФото();
                    setФото([...фото, ...пути]);
                  } catch (e) {
                    п.наОшибку(e instanceof Error ? e.message : String(e));
                  }
                }}
              >
                Приложить фото
              </button>
              <button
                className="кн главная"
                disabled={!текст.trim() || занято === "пишем"}
                onClick={async () => {
                  setЗанято("пишем");
                  try {
                    await window.стройка.написать(п.посёлок, п.дом, { текст: текст.trim(), фото });
                    setТекст("");
                    setФото([]);
                    загрузить();
                  } catch (e) {
                    п.наОшибку(e instanceof Error ? e.message : String(e));
                  } finally {
                    setЗанято("");
                  }
                }}
              >
                Отправить
              </button>
              {фото.length > 0 && <span className="подпись мелко">фотографий: {фото.length}</span>}
            </div>
            {фото.length > 0 && (
              <div className="фото-строка">
                {фото.map((ф) => (
                  <span className="фото-путь" key={ф} title={ф}>
                    {ф.split(/[\\/]/).pop()}
                  </span>
                ))}
              </div>
            )}
            <p className="подпись мелко" style={{ marginTop: 6 }}>
              Фотографии остаются на диске — в программу сохраняются только пути к ним.
            </p>
          </div>
        )}

        {чат.сообщения.length === 0 ? (
          <div className="пусто">В ленте пусто. Первый отчёт с объекта появится здесь.</div>
        ) : (
          <div className="лента">
            {чат.сообщения.map((с) => (
              <КарточкаСообщения
                key={с.id}
                сообщение={с}
                можноПринимать={можноПринимать}
                занято={занято}
                наРазбор={async () => {
                  setЗанято(с.id);
                  try {
                    await window.стройка.разобратьОтчёт(п.посёлок, п.дом, с.id);
                    загрузить();
                  } catch (e) {
                    п.наОшибку(e instanceof Error ? e.message : String(e));
                  } finally {
                    setЗанято("");
                  }
                }}
                наПринять={async (правки) => {
                  setЗанято(с.id);
                  try {
                    await window.стройка.принятьРазбор(п.посёлок, п.дом, с.id, правки);
                    загрузить();
                  } catch (e) {
                    п.наОшибку(e instanceof Error ? e.message : String(e));
                  } finally {
                    setЗанято("");
                  }
                }}
              />
            ))}
          </div>
        )}
      </div>

      <div>
        <div className="панель">
          <h2>Отклонения</h2>
          {чат.отклонения.length === 0 ? (
            <p className="подпись">Открытых отклонений нет.</p>
          ) : (
            чат.отклонения.map((о) => (
              <div key={о.id} style={{ borderBottom: "1px solid var(--bg-active)", padding: "8px 0" }}>
                <div className="ряд">
                  <span className={`метка ${о.статус === "открыто" ? "красная" : "зелёная"}`}>{о.вид}</span>
                  <span className="подпись мелко">{дата(о.дата)}</span>
                </div>
                <div style={{ marginTop: 3 }}>{о.суть}</div>
                <div className="подпись мелко">
                  {о.этап}
                  {о.насколько ? ` · ${о.насколько}` : ""} · сообщено: {о.кому.join(", ")}
                </div>
                {о.обоснование && <div className="подпись мелко">основание: {о.обоснование}</div>}
                {о.статус === "открыто" && можноПринимать && (
                  <button
                    className="ссылка"
                    onClick={async () => {
                      const комментарий = prompt("Что сделано по отклонению?") ?? "";
                      try {
                        await window.стройка.закрытьОтклонение(п.посёлок, п.дом, о.id, комментарий);
                        загрузить();
                      } catch (e) {
                        п.наОшибку(e instanceof Error ? e.message : String(e));
                      }
                    }}
                  >
                    закрыть отклонение
                  </button>
                )}
              </div>
            ))
          )}
        </div>

        {чат.уведомления.length > 0 && (
          <div className="панель">
            <h2>Мне ({п.роль.название})</h2>
            {чат.уведомления.slice(0, 12).map((у) => (
              <div key={у.id} style={{ padding: "6px 0", borderBottom: "1px solid var(--bg-active)", opacity: у.прочитано ? 0.55 : 1 }}>
                <b>{у.заголовок}</b>
                <div className="подпись мелко">{у.текст}</div>
                <div className="подпись мелко">{датаВремя(у.когда)}</div>
              </div>
            ))}
          </div>
        )}

        <div className="панель">
          <div className="ряд-между">
            <h2>Отчёты заказчику</h2>
            {можноОдобрять && (
              <button
                className="кн"
                disabled={занято === "отчёт"}
                onClick={async () => {
                  setЗанято("отчёт");
                  try {
                    const новый = await window.стройка.отчётКлиенту(п.посёлок, п.дом, { до: new Date().toISOString().slice(0, 10) });
                    setОтчёт(новый);
                    загрузить();
                  } catch (e) {
                    п.наОшибку(e instanceof Error ? e.message : String(e));
                  } finally {
                    setЗанято("");
                  }
                }}
              >
                {занято === "отчёт" ? "Готовим…" : "Подготовить отчёт"}
              </button>
            )}
          </div>

          {чат.отчёты.length === 0 && !отчёт && (
            <p className="подпись">
              Отчёт готовит агент по графику и отчётам с объекта. Руководитель правит его и одобряет —
              и только после этого отчёт уходит заказчику.
            </p>
          )}

          {(отчёт ? [отчёт, ...чат.отчёты.filter((о) => о.id !== отчёт.id)] : чат.отчёты).map((о) => (
            <КарточкаОтчёта
              key={о.id}
              отчёт={о}
              можноОдобрять={можноОдобрять}
              наПравку={async (текстОтчёта) => {
                try {
                  await window.стройка.правитьОтчёт(п.посёлок, п.дом, о.id, текстОтчёта);
                  setОтчёт(null);
                  загрузить();
                } catch (e) {
                  п.наОшибку(e instanceof Error ? e.message : String(e));
                }
              }}
              наОдобрение={async () => {
                try {
                  await window.стройка.одобритьОтчёт(п.посёлок, п.дом, о.id);
                  setОтчёт(null);
                  загрузить();
                } catch (e) {
                  п.наОшибку(e instanceof Error ? e.message : String(e));
                }
              }}
              наОтправку={async () => {
                try {
                  const итог = await window.стройка.отправитьОтчёт(п.посёлок, п.дом, о.id);
                  setОтчёт(null);
                  загрузить();
                  alert(
                    `Отчёт записан файлом:\n${итог.файл}` +
                      (итог.вПапкуЗаказчика ? `\n\nВ папку заказчика: ${итог.вПапкуЗаказчика}` : "")
                  );
                } catch (e) {
                  п.наОшибку(e instanceof Error ? e.message : String(e));
                }
              }}
            />
          ))}
        </div>
      </div>
    </div>
  );
}

function КарточкаСообщения({
  сообщение,
  можноПринимать,
  занято,
  наРазбор,
  наПринять,
}: {
  сообщение: Сообщение;
  можноПринимать: boolean;
  занято: string;
  наРазбор(): void;
  наПринять(правки: Record<string, unknown>): void;
}) {
  const [готовность, setГотовность] = useState<number | null>(null);
  const разбор = сообщение.разбор;

  return (
    <div className="сообщение">
      <div className="шапка">
        <span className="автор">{сообщение.автор}</span>
        <span className="метка">{сообщение.роль}</span>
        <span className="подпись мелко">{датаВремя(сообщение.когда)}</span>
        {сообщение.этап && <span className="метка синяя">{сообщение.этап}</span>}
        {сообщение.дляЗаказчика && <span className="метка зелёная">отправлено заказчику</span>}
      </div>
      <div className="текст">{сообщение.текст}</div>

      {сообщение.фото.length > 0 && (
        <div className="фото-строка">
          {сообщение.фото.map((ф) => (
            <span className="фото-путь" key={ф} title={ф}>
              {ф.split(/[\\/]/).pop()}
            </span>
          ))}
        </div>
      )}

      {!разбор && !сообщение.дляЗаказчика && (
        <div className="ряд" style={{ marginTop: 8 }}>
          <button className="кн" disabled={занято === сообщение.id} onClick={наРазбор}>
            {занято === сообщение.id ? "Агент читает…" : "Разобрать агентом"}
          </button>
          <span className="подпись мелко">сверит с графиком и назовёт расхождения; ничего не применит сам</span>
        </div>
      )}

      {разбор && (
        <div className="разбор">
          <h4>Разбор агента {сообщение.разборПринят && "· принят"}</h4>
          {разбор.поФото && (
            <div>
              <b>По фото:</b> {разбор.поФото}
            </div>
          )}
          {разбор.этап && (
            <div>
              <b>Этап:</b> {разбор.этап}
              {разбор.готовность != null && ` · готовность ${разбор.готовность}%`}
            </div>
          )}
          {разбор.выполнено.length > 0 && (
            <div>
              <b>Выполнено:</b> {разбор.выполнено.map((в) => `${в.работа} ${в.объём}`).join("; ")}
            </div>
          )}
          {разбор.отклонения.length > 0 ? (
            <div style={{ marginTop: 4 }}>
              <b>Отклонения:</b>
              {разбор.отклонения.map((о, i) => (
                <div key={i}>
                  <span className="метка красная">{о.вид}</span> {о.суть} {о.насколько && `(${о.насколько})`}
                  {о.обоснование && <div className="подпись мелко">основание: {о.обоснование}</div>}
                </div>
              ))}
            </div>
          ) : (
            <div className="подпись">Расхождений с графиком не нашлось.</div>
          )}
          {разбор.вопросы.length > 0 && (
            <div className="подпись мелко" style={{ marginTop: 4 }}>
              Уточнить у прораба: {разбор.вопросы.join("; ")}
            </div>
          )}

          {!сообщение.разборПринят && можноПринимать && (
            <div className="ряд" style={{ marginTop: 8 }}>
              <label className="поле">
                Готовность этапа, %
                <input
                  style={{ width: 80 }}
                  value={готовность ?? разбор.готовность ?? ""}
                  onChange={(e) => setГотовность(Number(e.target.value))}
                />
              </label>
              <button
                className="кн главная"
                disabled={занято === сообщение.id}
                onClick={() => наПринять({ готовность: готовность ?? разбор.готовность })}
              >
                Принять разбор
              </button>
              <span className="подпись мелко">
                готовность уедет в график, отклонения — по ролям
              </span>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

function КарточкаОтчёта({
  отчёт,
  можноОдобрять,
  наПравку,
  наОдобрение,
  наОтправку,
}: {
  отчёт: ОтчётКлиенту;
  можноОдобрять: boolean;
  наПравку(текст: string): void;
  наОдобрение(): void;
  наОтправку(): void;
}) {
  const [правка, setПравка] = useState(false);
  const [черновик, setЧерновик] = useState(отчёт.текст);

  return (
    <div style={{ borderTop: "1px solid var(--bg-active)", paddingTop: 10, marginTop: 10 }}>
      <div className="ряд-между">
        <div>
          <b>{отчёт.период || дата(отчёт.когда)}</b>
          <div className="подпись мелко">{отчёт.автор}</div>
        </div>
        <span
          className={`метка ${отчёт.статус === "отправлен" ? "зелёная" : отчёт.статус === "одобрен" ? "синяя" : "жёлтая"}`}
        >
          {отчёт.статус}
        </span>
      </div>

      {правка ? (
        <>
          <textarea value={черновик} onChange={(e) => setЧерновик(e.target.value)} style={{ minHeight: 220, marginTop: 8 }} />
          <div className="ряд" style={{ marginTop: 6 }}>
            <button
              className="кн главная"
              onClick={() => {
                наПравку(черновик);
                setПравка(false);
              }}
            >
              Сохранить правку
            </button>
            <button className="кн" onClick={() => setПравка(false)}>
              Отменить
            </button>
          </div>
        </>
      ) : (
        <div className="отчёт-текст" style={{ marginTop: 8 }}>
          {отчёт.текст}
        </div>
      )}

      {можноОдобрять && отчёт.статус !== "отправлен" && !правка && (
        <div className="ряд" style={{ marginTop: 8 }}>
          <button
            className="кн"
            onClick={() => {
              setЧерновик(отчёт.текст);
              setПравка(true);
            }}
          >
            Править
          </button>
          {отчёт.статус !== "одобрен" && (
            <button className="кн" onClick={наОдобрение}>
              Одобрить
            </button>
          )}
          {отчёт.статус === "одобрен" && (
            <button className="кн главная" onClick={наОтправку}>
              Отправить заказчику
            </button>
          )}
        </div>
      )}

      {отчёт.статус === "отправлен" && отчёт.файл && (
        <div className="подпись мелко" style={{ marginTop: 6 }}>
          Файл: {отчёт.файл}
        </div>
      )}
    </div>
  );
}
