// Исполнительная документация: комплект из данных дома.
//
// Формы у каждой компании свои, поэтому программа сначала ищет шаблон в папке,
// на которую указал руководитель, и подставляет в него значения по меткам
// {{...}}. Своя встроенная форма — только страховка от неполного комплекта, и в
// таблице видно, что откуда взялось.
//
// Незаполненные метки выносятся отдельным списком. Метка «{{подрядчик.инн}}»,
// оставшаяся в акте, который ушёл заказчику, выглядит хуже пустого места, и
// увидеть такое надо здесь, а не после подписи.

import { useCallback, useEffect, useState } from "react";
import type { КомплектИД, Роль, Справочники } from "../lib/types";
import { дата } from "../lib/types";

interface Свойства {
  посёлок: string;
  дом: string;
  ключ: string;
  роль: Роль;
  справочники: Справочники;
  наОшибку(текст: string): void;
}

export default function Документация(п: Свойства) {
  const [шаблоны, setШаблоны] = useState<{ папка: string; шаблоны: { имя: string; путь: string; вид: string; расширение: string }[] } | null>(null);
  const [комплект, setКомплект] = useState<КомплектИД | null>(null);
  const [занято, setЗанято] = useState(false);
  const [период, setПериод] = useState("");

  const загрузить = useCallback(() => {
    window.стройка
      .шаблоныИД(п.ключ)
      .then(setШаблоны)
      .catch((e) => п.наОшибку(String(e.message || e)));
  }, [п]);

  useEffect(загрузить, [загрузить]);

  const можноСобрать = п.роль.действия.includes("собратьДокументацию");

  return (
    <div className="view-narrow">
      <div className="панель">
        <h2>Шаблоны форм</h2>
        {!шаблоны?.папка && (
          <div className="внимание">
            Папка с шаблонами не указана. Комплект соберётся по встроенным формам — это рабочий
            вариант, но формы вашей компании лучше: путь к папке указывает руководитель в разделе
            «Источники данных».
          </div>
        )}
        {шаблоны?.папка && (
          <>
            <div className="путь">{шаблоны.папка}</div>
            {шаблоны.шаблоны.length === 0 ? (
              <p className="подпись">В папке нет файлов .docx и .xlsx — комплект соберётся по встроенным формам.</p>
            ) : (
              <table className="таблица" style={{ marginTop: 8 }}>
                <thead>
                  <tr>
                    <th>Файл</th>
                    <th style={{ width: 260 }}>Под какой документ подошёл</th>
                  </tr>
                </thead>
                <tbody>
                  {шаблоны.шаблоны.map((ш) => (
                    <tr key={ш.путь}>
                      <td>{ш.имя}</td>
                      <td>
                        {ш.вид ? (
                          <span className="метка зелёная">{п.справочники.документы.find((д) => д.id === ш.вид)?.название || ш.вид}</span>
                        ) : (
                          <span className="подпись мелко">не опознан по имени — не будет использован</span>
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
          </>
        )}
        <p className="подпись мелко" style={{ marginTop: 8 }}>
          В шаблоне пишите метки в двойных фигурных скобках: {"{{объект}}"}, {"{{дата}}"},{" "}
          {"{{заказчик}}"}, {"{{подрядчик}}"}, {"{{работы}}"}, {"{{этап}}"}, {"{{проект}}"},{" "}
          {"{{договор}}"}, {"{{прораб}}"}. В таблицах Excel строка с меткой {"{{строки}}"}{" "}
          размножится по позициям акта.
        </p>
      </div>

      <div className="панель">
        <h2>Что войдёт в комплект</h2>
        <table className="таблица">
          <thead>
            <tr>
              <th>Документ</th>
              <th style={{ width: 150 }}>На каждый</th>
              <th style={{ width: 210 }}>Основание формы</th>
            </tr>
          </thead>
          <tbody>
            {п.справочники.документы.map((д) => (
              <tr key={д.id}>
                <td>{д.название}</td>
                <td className="подпись мелко">{д.наКаждую}</td>
                <td className="подпись мелко">{д.основание}</td>
              </tr>
            ))}
          </tbody>
        </table>

        {можноСобрать && (
          <div className="ряд" style={{ marginTop: 12 }}>
            <label className="поле">
              Отчётный период для КС-2/КС-3
              <input value={период} onChange={(e) => setПериод(e.target.value)} placeholder="апрель 2026" />
            </label>
            <button
              className="кн главная"
              disabled={занято}
              onClick={async () => {
                setЗанято(true);
                try {
                  setКомплект(await window.стройка.собратьИД(п.посёлок, п.дом, { период }));
                } catch (e) {
                  п.наОшибку(e instanceof Error ? e.message : String(e));
                } finally {
                  setЗанято(false);
                }
              }}
            >
              {занято ? "Собираем…" : "Собрать комплект"}
            </button>
            <button className="кн" onClick={() => window.стройка.открытьПапкуИД(п.посёлок, п.дом).catch((e) => п.наОшибку(String(e.message || e)))}>
              Открыть папку с документами
            </button>
          </div>
        )}
        {!можноСобрать && <p className="подпись">Комплект собирает руководитель по стройке или директор.</p>}
      </div>

      {комплект && (
        <div className="панель">
          <div className="ряд-между">
            <h2>Собрано документов: {комплект.созданные.length}</h2>
            <span className="подпись мелко">
              шаблонов компании использовано: {комплект.шаблоновНайдено}
            </span>
          </div>

          {комплект.требуютВнимания.length > 0 && (
            <div className="внимание">
              <b>Не хватило данных для меток</b> — эти документы придётся дозаполнить руками:
              {комплект.требуютВнимания.map((т) => (
                <div key={т.файл}>
                  {т.файл}: {т.метки.join(", ")}
                </div>
              ))}
            </div>
          )}
          {комплект.пропущено.length > 0 && (
            <div className="ошибка">
              Не собрались:
              {комплект.пропущено.map((пр, i) => (
                <div key={i}>
                  {пр.вид}: {пр.причина}
                </div>
              ))}
            </div>
          )}

          <div className="прокрутка">
            <table className="таблица">
              <thead>
                <tr>
                  <th>Документ</th>
                  <th style={{ width: 96 }}>Дата</th>
                  <th style={{ width: 180 }}>Откуда форма</th>
                  <th>Файл</th>
                </tr>
              </thead>
              <tbody>
                {комплект.созданные.map((д) => (
                  <tr key={д.файл}>
                    <td>{д.название}</td>
                    <td>{дата(д.дата)}</td>
                    <td>
                      <span className={`метка ${д.источник.startsWith("шаблон") ? "зелёная" : ""}`}>{д.источник}</span>
                    </td>
                    <td className="путь">{д.файл.split(/[\\/]/).pop()}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="подпись мелко" style={{ marginTop: 8 }}>
            Документы лежат в папке дома: {комплект.папка}
          </p>
        </div>
      )}
    </div>
  );
}
