// График работ и приёмка.
//
// Диаграмма показывает не только полосы, но и ПОЧЕМУ этап стоит именно здесь:
// «Фундамент + выдержка 7 дн.», «бригада занята на другом объекте», «сезонное
// ограничение». Без этого график выглядит как чьё-то произвольное решение, и
// первый же разговор о сроках упирается в «а почему нельзя раньше».
//
// Отставание делится надвое: съедает запас или двигает сдачу. Это разные вещи,
// и на планёрке их путают чаще всего.

import { useCallback, useEffect, useState } from "react";
import type { График, Приёмка, Роль, Справочники } from "../lib/types";
import { дата } from "../lib/types";

interface Свойства {
  посёлок: string;
  дом: string;
  ключ: string;
  роль: Роль;
  справочники: Справочники;
  наОшибку(текст: string): void;
}

export default function ГрафикРабот(п: Свойства) {
  const [график, setГрафик] = useState<График | null>(null);
  const [приёмки, setПриёмки] = useState<Приёмка[]>([]);
  const [занято, setЗанято] = useState(false);

  const загрузить = useCallback(() => {
    Promise.all([window.стройка.график(п.посёлок, п.дом), window.стройка.приёмка(п.посёлок, п.дом)])
      .then(([г, пр]) => {
        setГрафик(г);
        setПриёмки(пр.приёмки || []);
      })
      .catch((e) => п.наОшибку(String(e.message || e)));
  }, [п]);

  useEffect(загрузить, [загрузить]);

  if (!график) return <div className="загрузка">Считаем график…</div>;

  const можноПравить = п.роль.действия.includes("правитьГрафик");
  const можноПринимать = п.роль.действия.includes("приниматьРаботы");
  const начало = new Date(график.начало).getTime();
  const конец = new Date(график.сдача).getTime();
  const всего = Math.max(1, конец - начало);
  const доля = (д: string) => ((new Date(д).getTime() - начало) / всего) * 100;
  const сегодняДоля = график.сегодня ? доля(график.сегодня) : -1;

  return (
    <>
      <div className="ряд-между" style={{ marginBottom: 10 }}>
        <div className="ряд">
          <span className="метка охра">срок {график.срокДней} дней</span>
          <span className="метка">
            {дата(график.начало)} → {дата(график.сдача)}
          </span>
          {график.готовность !== undefined && <span className="метка синяя">готовность {график.готовность}%</span>}
          {(график.сдвигСдачи ?? 0) > 0 && (
            <span className="метка красная">
              сдача сдвигается на {график.сдвигСдачи} дн. → {дата(график.прогнозСдачи)}
            </span>
          )}
          {(график.отстают ?? 0) > 0 && (график.сдвигСдачи ?? 0) === 0 && (
            <span className="метка жёлтая">отстают этапов: {график.отстают} — но запас есть</span>
          )}
        </div>
        {можноПравить && (
          <button
            className="кн главная"
            disabled={занято}
            onClick={async () => {
              setЗанято(true);
              try {
                setГрафик(await window.стройка.построитьГрафик(п.посёлок, п.дом));
                const пр = await window.стройка.построитьПриёмку(п.посёлок, п.дом);
                setПриёмки(пр.приёмки);
              } catch (e) {
                п.наОшибку(e instanceof Error ? e.message : String(e));
              } finally {
                setЗанято(false);
              }
            }}
          >
            {график.сохранён ? "Пересчитать график" : "Построить и сохранить график"}
          </button>
        )}
      </div>

      {график.поПрикидке && (
        <div className="внимание">
          Сметы ещё нет, поэтому срок посчитан по прикидке от площади дома. Как только в смете
          появятся объёмы, пересчитайте — сроки изменятся.
        </div>
      )}
      {!график.сохранён && !график.поПрикидке && (
        <div className="внимание">
          График пока не сохранён: показан расчёт по текущей смете. Сохранённый график не двигается
          сам при каждой правке сметы — по нему работают и планируют поставки.
        </div>
      )}

      <div className="панель">
        <div className="гант">
          {график.этапы.map((э) => {
            const ширина = Math.max(1.2, доля(э.конец) - доля(э.начало));
            const класс = э.статус === "выполнен" ? "выполнен" : (э.отставание ?? 0) > 0 ? "отстаёт" : э.ограничитель.includes("занята") ? "ждёт" : "";
            return (
              <Строка
                key={э.id}
                этап={э}
                левый={доля(э.начало)}
                ширина={ширина}
                класс={класс}
                сегодняДоля={сегодняДоля}
                можноПравить={можноПравить || п.роль.действия.includes("правитьФакт")}
                наОтметку={async (правка) => {
                  try {
                    setГрафик(await window.стройка.отметитьЭтап(п.посёлок, п.дом, э.id, правка));
                  } catch (e) {
                    п.наОшибку(e instanceof Error ? e.message : String(e));
                  }
                }}
              />
            );
          })}
        </div>
      </div>

      <div className="панель">
        <h2>Почему этапы стоят именно так</h2>
        <table className="таблица">
          <thead>
            <tr>
              <th>Этап</th>
              <th style={{ width: 90 }}>Начало</th>
              <th style={{ width: 90 }}>Конец</th>
              <th className="ч" style={{ width: 60 }}>Смен</th>
              <th>Что определило старт</th>
            </tr>
          </thead>
          <tbody>
            {график.этапы.map((э) => (
              <tr key={э.id}>
                <td className={э.критический ? "гант-имя критический" : ""}>
                  {э.название}
                  {э.критический && <span className="подпись мелко"> · критический путь</span>}
                </td>
                <td>{дата(э.начало)}</td>
                <td>{дата(э.конец)}</td>
                <td className="ч">{э.смен}</td>
                <td className="мелко">
                  {э.ограничитель}
                  {э.поясВыдержки && <div className="подпись мелко">{э.поясВыдержки}</div>}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      <div className="панель">
        <div className="ряд-между">
          <h2>График приёмки работ</h2>
          <span className="подпись мелко">
            скрытые работы освидетельствуются до того, как их закроет следующая работа
          </span>
        </div>
        {приёмки.length === 0 ? (
          <div className="пусто">Приёмки появятся, когда будет построен график работ.</div>
        ) : (
          <div className="прокрутка">
            <table className="таблица">
              <thead>
                <tr>
                  <th style={{ width: 92 }}>Дата</th>
                  <th style={{ width: 130 }}>Этап</th>
                  <th>Что принимаем</th>
                  <th style={{ width: 90 }}>Документ</th>
                  <th style={{ width: 160 }}>Участники</th>
                  <th style={{ width: 120 }}>Статус</th>
                </tr>
              </thead>
              <tbody>
                {приёмки.map((пр) => (
                  <tr key={пр.id}>
                    <td>{дата(пр.дата)}</td>
                    <td>{пр.этап}</td>
                    <td>
                      {пр.работа}
                      {пр.вид === "скрытые работы" && <span className="подпись мелко"> · скрытые работы</span>}
                    </td>
                    <td>
                      <span className="метка">{пр.документ}</span>
                    </td>
                    <td className="мелко подпись">{пр.участники.join(", ")}</td>
                    <td>
                      {можноПринимать ? (
                        <select
                          value={пр.статус}
                          onChange={async (e) => {
                            try {
                              const итог = await window.стройка.отметитьПриёмку(п.посёлок, п.дом, пр.id, { статус: e.target.value });
                              setПриёмки(итог.приёмки);
                            } catch (err) {
                              п.наОшибку(err instanceof Error ? err.message : String(err));
                            }
                          }}
                        >
                          <option value="запланирована">запланирована</option>
                          <option value="принята">принята</option>
                          <option value="с замечаниями">с замечаниями</option>
                          <option value="перенесена">перенесена</option>
                        </select>
                      ) : (
                        <span className={`метка ${пр.статус === "принята" ? "зелёная" : пр.статус === "с замечаниями" ? "красная" : ""}`}>
                          {пр.статус}
                        </span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}

function Строка({
  этап,
  левый,
  ширина,
  класс,
  сегодняДоля,
  можноПравить,
  наОтметку,
}: {
  этап: График["этапы"][number];
  левый: number;
  ширина: number;
  класс: string;
  сегодняДоля: number;
  можноПравить: boolean;
  наОтметку(правка: Record<string, unknown>): void;
}) {
  return (
    <>
      <div className={`гант-имя ${этап.критический ? "критический" : ""}`} title={этап.ограничитель}>
        {этап.название}
        {(этап.отставание ?? 0) > 0 && (
          <span className={этап.двигаетСдачу ? "перерасход" : ""}> +{этап.отставание}д</span>
        )}
      </div>
      <div className="гант-дорожка">
        <div className={`гант-полоса ${класс}`} style={{ left: `${левый}%`, width: `${ширина}%` }} title={`${этап.начало} — ${этап.конец}`}>
          {этап.готовность > 0 && этап.готовность < 100 && (
            <div className="гант-готовность" style={{ width: `${100 - этап.готовность}%`, right: 0, left: "auto" }} />
          )}
        </div>
        {сегодняДоля >= 0 && сегодняДоля <= 100 && <div className="гант-сегодня" style={{ left: `${сегодняДоля}%` }} />}
      </div>
      {/* Готовность — отдельной колонкой, а не поверх дорожки: ползунок,
          лежащий на диаграмме, читается как часть графика и врёт про сроки. */}
      <div className="гант-готовность-колонка">
        {можноПравить ? (
          <input
            type="range"
            min={0}
            max={100}
            step={5}
            value={этап.готовность}
            title={`готовность ${этап.готовность}%`}
            onChange={(e) => наОтметку({ готовность: Number(e.target.value), статус: Number(e.target.value) >= 100 ? "выполнен" : "идёт" })}
          />
        ) : null}
        <span className="гант-процент">{этап.готовность}%</span>
      </div>
    </>
  );
}
