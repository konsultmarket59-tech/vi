// Карточка дома: всё об объекте на одном экране, но глазами своей роли.
//
// Вкладки не прячутся «серым», а не создаются вовсе: раздел, которого у роли
// нет, не должен маячить перед глазами и провоцировать вопрос «а почему мне
// нельзя». Прораб видит пять вкладок, директор — десять, и обоим интерфейс
// кажется своим, а не урезанным.

import { useCallback, useEffect, useState } from "react";
import type { Дом, Настройки, Посёлок, Роль, Справочники } from "../lib/types";
import { дата } from "../lib/types";
import Смета from "./Смета";
import Калькулятор from "./Калькулятор";
import ГрафикРабот from "./ГрафикРабот";
import Снабжение from "./Снабжение";
import ЧатСтройки from "./ЧатСтройки";
import Документация from "./Документация";
import ОбзорДома from "./ОбзорДома";

type Вкладка = { id: string; название: string; раздел: string };

const ВКЛАДКИ: Вкладка[] = [
  { id: "обзор", название: "Дом", раздел: "дом" },
  { id: "смета", название: "Смета", раздел: "смета" },
  { id: "калькулятор", название: "Калькулятор", раздел: "калькулятор" },
  { id: "график", название: "График и приёмка", раздел: "график" },
  { id: "снабжение", название: "Снабжение и поставки", раздел: "снабжение" },
  { id: "чат", название: "Чат и отчёты", раздел: "чат" },
  { id: "документация", название: "Исполнительная", раздел: "документация" },
];

interface Свойства {
  дом: Дом;
  посёлок: Посёлок | null;
  роль: Роль;
  справочники: Справочники;
  настройки: Настройки;
  обновитьДома(): Promise<Дом[]>;
  наОшибку(текст: string): void;
}

export default function КарточкаДома(п: Свойства) {
  const доступные = ВКЛАДКИ.filter((в) => п.роль.разделы.includes(в.раздел));
  const [вкладка, setВкладка] = useState(доступные[0]?.id || "обзор");
  const [открытых, setОткрытых] = useState(0);
  const ключ = `${п.дом.посёлокПапка}/${п.дом.папка}`;

  useEffect(() => {
    if (!доступные.some((в) => в.id === вкладка)) setВкладка(доступные[0]?.id || "обзор");
  }, [доступные, вкладка]);

  // Число открытых отклонений висит на вкладке чата: это единственная цифра,
  // ради которой человек на стройке открывает программу вне своей задачи.
  const обновитьОтклонения = useCallback(() => {
    window.стройка
      .чат(п.дом.посёлокПапка, п.дом.папка)
      .then((чат) => setОткрытых(чат.сводка?.открытых || 0))
      .catch(() => setОткрытых(0));
  }, [п.дом.посёлокПапка, п.дом.папка]);

  useEffect(обновитьОтклонения, [обновитьОтклонения]);

  const общие = {
    посёлок: п.дом.посёлокПапка,
    дом: п.дом.папка,
    ключ,
    роль: п.роль,
    справочники: п.справочники,
    наОшибку: п.наОшибку,
  };

  return (
    <>
      <div className="вкладки">
        {доступные.map((в) => (
          <button key={в.id} className={`вкладка ${вкладка === в.id ? "on" : ""}`} onClick={() => setВкладка(в.id)}>
            {в.название}
            {в.id === "чат" && открытых > 0 && <span className="точка"> ●</span>}
          </button>
        ))}
        <span className="растяжка" />
        <span className="подпись мелко" style={{ alignSelf: "center", paddingRight: 8 }}>
          {п.дом.датаНачала ? `начало ${дата(п.дом.датаНачала)}` : "начало не задано"}
          {п.дом.датаСдачи ? ` · сдача ${дата(п.дом.датаСдачи)}` : ""}
        </span>
      </div>

      <div className="view">
        {вкладка === "обзор" && (
          <ОбзорДома
            дом={п.дом}
            посёлок={п.посёлок}
            роль={п.роль}
            обновитьДома={п.обновитьДома}
            наОшибку={п.наОшибку}
            наВкладку={setВкладка}
          />
        )}
        {вкладка === "смета" && <Смета {...общие} />}
        {вкладка === "калькулятор" && <Калькулятор {...общие} площадь={п.дом.площадь} настройки={п.настройки} />}
        {вкладка === "график" && <ГрафикРабот {...общие} />}
        {вкладка === "снабжение" && <Снабжение {...общие} />}
        {вкладка === "чат" && <ЧатСтройки {...общие} наОбновление={обновитьОтклонения} />}
        {вкладка === "документация" && <Документация {...общие} />}
      </div>
    </>
  );
}
