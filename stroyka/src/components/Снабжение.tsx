// Снабжение: заявки по порогу одобрения и график поставок этого дома.
//
// Заявка всегда говорит, ЧЬЕГО решения ждёт: «в пределах лимита снабженца» или
// «выше лимита — решает руководитель». Без этой строки заявка лежит неделю, и
// каждый уверен, что решает другой.
//
// «Заказать до» — не то же самое, что «нужно к дате»: между ними срок поставки
// поставщика. Просроченная по дате заказа заявка вынесена наверх отдельно,
// потому что это уже не бумага, а остановленная через неделю бригада.

import { useCallback, useEffect, useState } from "react";
import type { ГрафикПоставок, Роль, Снабжение as ТипСнабжения, Справочники, Заявка } from "../lib/types";
import { дата, рубли, число } from "../lib/types";

interface Свойства {
  посёлок: string;
  дом: string;
  ключ: string;
  роль: Роль;
  справочники: Справочники;
  наОшибку(текст: string): void;
}

export default function Снабжение(п: Свойства) {
  const [снабжение, setСнабжение] = useState<ТипСнабжения | null>(null);
  const [поставки, setПоставки] = useState<ГрафикПоставок | null>(null);
  const [занято, setЗанято] = useState(false);
  const [сообщение, setСообщение] = useState("");

  const загрузить = useCallback(() => {
    Promise.all([window.стройка.снабжение(п.посёлок, п.дом), window.стройка.планДома(п.посёлок, п.дом)])
      .then(([с, пост]) => {
        setСнабжение(с);
        setПоставки(пост);
      })
      .catch((e) => п.наОшибку(String(e.message || e)));
  }, [п]);

  useEffect(загрузить, [загрузить]);

  async function действие(что: () => Promise<ТипСнабжения>) {
    setЗанято(true);
    try {
      setСнабжение(await что());
    } catch (e) {
      п.наОшибку(e instanceof Error ? e.message : String(e));
    } finally {
      setЗанято(false);
    }
  }

  if (!снабжение) return <div className="загрузка">Читаем заявки…</div>;

  const сводка = снабжение.сводка;
  const можноСоздать = п.роль.действия.includes("создатьЗаявку");

  return (
    <>
      <div className="ряд-между" style={{ marginBottom: 10 }}>
        <div className="ряд">
          <span className="метка">активных заявок {сводка.активных}</span>
          <span className="метка охра">на {рубли(сводка.сумма)}</span>
          {сводка.ждутРуководителя > 0 && <span className="метка жёлтая">{сводка.ждутРуководителя} ждёт руководителя</span>}
          {сводка.ждутОплаты > 0 && <span className="метка синяя">{сводка.ждутОплаты} ждёт оплаты</span>}
        </div>
        {можноСоздать && (
          <button
            className="кн главная"
            disabled={занято}
            onClick={async () => {
              setЗанято(true);
              try {
                const итог = await window.стройка.заявкиИзГрафика(п.посёлок, п.дом);
                setСнабжение(итог);
                setСообщение(
                  итог.создано
                    ? `Создано заявок: ${итог.создано}. Дата заказа посчитана от срока поставки — раньше неё заказывать поздно.`
                    : "Новых заявок нет: на все поставки из графика заявки уже созданы."
                );
              } catch (e) {
                п.наОшибку(e instanceof Error ? e.message : String(e));
              } finally {
                setЗанято(false);
              }
            }}
          >
            Создать заявки из графика поставок
          </button>
        )}
      </div>

      {сообщение && <div className="успех">{сообщение}</div>}

      {сводка.просрочено.length > 0 && (
        <div className="ошибка">
          <b>Просрочена дата заказа — {сводка.просрочено.length} шт.</b>
          {сводка.просрочено.slice(0, 4).map((з) => (
            <div key={з.номер}>
              №{з.номер} {з.наименование}: заказать надо было до {дата(з.заказатьДо)} (опоздание {з.опоздание} дн.), нужно на объекте {дата(з.нужноКДате)}.
            </div>
          ))}
        </div>
      )}

      {снабжение.заявки.length === 0 ? (
        <div className="пусто">
          Заявок нет. Если график работ построен, заявки можно создать из графика поставок одной
          кнопкой — с датами, к которым материал нужен на объекте.
        </div>
      ) : (
        <div className="лента">
          {снабжение.заявки.map((з) => (
            <КарточкаЗаявки
              key={з.id}
              заявка={з}
              роль={п.роль}
              маршрут={п.справочники.маршрутЗаявки}
              занято={занято}
              наШаг={(шаг) => действие(() => window.стройка.продвинутьЗаявку(п.посёлок, п.дом, з.id, шаг))}
              наОтказ={(причина) => действие(() => window.стройка.отклонитьЗаявку(п.посёлок, п.дом, з.id, причина))}
            />
          ))}
        </div>
      )}

      {поставки && !поставки.нетГрафика && поставки.поставки.length > 0 && (
        <div className="панель" style={{ marginTop: 14 }}>
          <div className="ряд-между">
            <h2>График поставок этого дома</h2>
            <span className="подпись мелко">
              рейсов {поставки.рейсовСОбъединением} · доставка {рубли(поставки.поставки.reduce((s, x) => s + x.стоимостьДоставки, 0))}
            </span>
          </div>
          <p className="подпись">
            Дата поставки — как можно позже внутри окна хранения: материал, привезённый заранее,
            занимает место, портится и пропадает. Товарный бетон везут день в день.
          </p>
          <div className="прокрутка">
            <table className="таблица">
              <thead>
                <tr>
                  <th style={{ width: 88 }}>Дата</th>
                  <th>Материал</th>
                  <th className="ч" style={{ width: 92 }}>Кол-во</th>
                  <th className="ч" style={{ width: 76 }}>Тонн</th>
                  <th style={{ width: 120 }}>Транспорт</th>
                  <th style={{ width: 120 }}>Этап</th>
                  <th className="ч" style={{ width: 100 }}>Сумма</th>
                </tr>
              </thead>
              <tbody>
                {поставки.поставки.map((п2) => (
                  <tr key={п2.id}>
                    <td>
                      {дата(п2.дата)}
                      {п2.хранениеДней > 0 && <div className="подпись мелко">лежит {п2.хранениеДней} дн.</div>}
                    </td>
                    <td>
                      {п2.наименование}
                      {п2.замечания.map((з, i) => (
                        <div key={i} className="подпись мелко">
                          {з}
                        </div>
                      ))}
                    </td>
                    <td className="ч">
                      {число(п2.количество, 1)} {п2.единица}
                    </td>
                    <td className="ч">{число(п2.тонн, 1)}</td>
                    <td className="мелко">
                      {п2.транспортНазвание}
                      <div className="подпись мелко">{п2.рейсов} рейс(ов)</div>
                    </td>
                    <td className="мелко">{п2.этапы.join(", ")}</td>
                    <td className="ч">{рубли(п2.сумма, false)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {поставки?.нетГрафика && (
        <div className="внимание" style={{ marginTop: 14 }}>
          График поставок считается от графика работ: сначала постройте график на вкладке «График и
          приёмка».
        </div>
      )}
    </>
  );
}

function КарточкаЗаявки({
  заявка,
  роль,
  маршрут,
  занято,
  наШаг,
  наОтказ,
}: {
  заявка: Заявка;
  роль: Роль;
  маршрут: { id: string; описание: string }[];
  занято: boolean;
  наШаг(шаг: string): void;
  наОтказ(причина: string): void;
}) {
  const текущий = маршрут.findIndex((м) => м.id === заявка.статус);
  const следующий = маршрут[текущий + 1];
  const отклонена = заявка.статус === "Отклонена";

  const можноШаг =
    следующий &&
    ((следующий.id === "Одобрение" && роль.действия.includes("одобритьЗаявку")) ||
      (следующий.id === "Оплата" && роль.действия.includes("оплатитьЗаявку")) ||
      (следующий.id === "Поставка" && роль.действия.includes("принятьПоставку")));

  return (
    <div className="сообщение">
      <div className="ряд-между">
        <div>
          <b>
            №{заявка.номер} · {заявка.наименование}
          </b>
          <div className="подпись мелко">
            {заявка.дом || "объект не указан"} · {заявка.основание} · создал {заявка.создал}
          </div>
        </div>
        <div style={{ textAlign: "right" }}>
          <div style={{ fontWeight: 700, fontVariantNumeric: "tabular-nums" }}>{рубли(заявка.сумма)}</div>
          {заявка.нужноКДате && <div className="подпись мелко">к {дата(заявка.нужноКДате)}</div>}
        </div>
      </div>

      <div className="маршрут" style={{ marginTop: 8 }}>
        {маршрут.map((м, i) => (
          <span key={м.id}>
            <span className={`шаг ${i <= текущий ? "пройден" : i === текущий + 1 && !отклонена ? "текущий" : ""}`}>{м.id}</span>
            {i < маршрут.length - 1 && <span className="стрелка"> → </span>}
          </span>
        ))}
        {отклонена && <span className="метка красная">отклонена: {заявка.причинаОтказа}</span>}
      </div>

      {!отклонена && следующий && (
        <div className="ряд" style={{ marginTop: 8 }}>
          <span className="подпись мелко">{заявка.поясн}</span>
          <span className="растяжка" />
          {заявка.заказатьДо && (
            <span className={`метка ${заявка.просрочена ? "красная" : ""}`}>заказать до {дата(заявка.заказатьДо)}</span>
          )}
          {можноШаг && (
            <button className="кн главная" disabled={занято} onClick={() => наШаг(следующий.id)}>
              {следующий.id === "Одобрение" ? "Одобрить" : следующий.id === "Оплата" ? "Отметить оплату" : "Принять поставку"}
            </button>
          )}
          {!можноШаг && <span className="метка жёлтая">ждёт: {заявка.ждёт}</span>}
          {роль.действия.includes("одобритьЗаявку") && заявка.статус === "Заявка" && (
            <button
              className="кн опасная"
              disabled={занято}
              onClick={() => {
                const причина = prompt("Почему отклоняем?") ?? "";
                if (причина) наОтказ(причина);
              }}
            >
              Отклонить
            </button>
          )}
        </div>
      )}

      {заявка.позиции.length > 0 && (
        <table className="таблица" style={{ marginTop: 8 }}>
          <tbody>
            {заявка.позиции.map((поз, i) => (
              <tr key={i}>
                <td>{поз.наименование}</td>
                <td className="ч" style={{ width: 110 }}>
                  {число(поз.количество, 2)} {поз.единица}
                </td>
                <td className="ч" style={{ width: 100 }}>
                  {рубли(поз.цена, false)}
                </td>
                <td className="ч" style={{ width: 110 }}>
                  {рубли(поз.сумма, false)}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </div>
  );
}
