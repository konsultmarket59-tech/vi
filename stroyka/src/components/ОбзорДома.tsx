// Обзор дома: паспорт объекта и путь к его проекту.
//
// Проект здесь не хранится и не копируется — показывается то, что лежит по
// указанному архитектором пути прямо сейчас: сколько файлов, какие разделы
// закрыты, когда последний раз правили. Дата правки — не украшение: смета,
// посчитанная до этой даты, могла устареть, и это единственный способ такое
// заметить, не открывая чертежи.

import { useEffect, useState } from "react";
import type { Дом, Посёлок, Роль } from "../lib/types";
import { дата, датаВремя } from "../lib/types";

interface Свойства {
  дом: Дом;
  посёлок: Посёлок | null;
  роль: Роль;
  обновитьДома(): Promise<Дом[]>;
  наОшибку(текст: string): void;
  наВкладку(id: string): void;
}

type Проект = Awaited<ReturnType<Window["стройка"]["проект"]>>;

export default function ОбзорДома(п: Свойства) {
  const [проект, setПроект] = useState<Проект | null>(null);
  const [правка, setПравка] = useState(false);
  const [черновик, setЧерновик] = useState<Partial<Дом>>({});
  const ключ = `${п.дом.посёлокПапка}/${п.дом.папка}`;
  const можноПравить = п.роль.действия.includes("видетьВсеОбъекты") || п.роль.id === "прораб";

  useEffect(() => {
    let живо = true;
    window.стройка
      .проект(ключ)
      .then((данные) => живо && setПроект(данные))
      .catch(() => живо && setПроект(null));
    return () => {
      живо = false;
    };
  }, [ключ]);

  async function сохранить() {
    try {
      await window.стройка.обновитьДом(п.дом.посёлокПапка, п.дом.папка, черновик);
      await п.обновитьДома();
      setПравка(false);
      setЧерновик({});
    } catch (e) {
      п.наОшибку(e instanceof Error ? e.message : String(e));
    }
  }

  const значение = <K extends keyof Дом>(ключПоля: K): Дом[K] =>
    (черновик[ключПоля] !== undefined ? черновик[ключПоля] : п.дом[ключПоля]) as Дом[K];

  return (
    <div className="view-narrow">
      <div className="колонки">
        <div className="панель">
          <div className="ряд-между">
            <h2>
              {п.дом.улица} {п.дом.номер}
            </h2>
            {можноПравить && (
              <button className="ссылка" onClick={() => setПравка(!правка)}>
                {правка ? "отменить" : "править"}
              </button>
            )}
          </div>

          {правка ? (
            <>
              <div className="поля">
                <label className="поле">
                  Статус
                  <select value={String(значение("статус"))} onChange={(e) => setЧерновик({ ...черновик, статус: e.target.value as Дом["статус"] })}>
                    <option value="план">план</option>
                    <option value="стройка">стройка</option>
                    <option value="готов">готов</option>
                    <option value="передан">передан</option>
                  </select>
                </label>
                <label className="поле">
                  Площадь, м²
                  <input value={String(значение("площадь"))} onChange={(e) => setЧерновик({ ...черновик, площадь: Number(e.target.value) || 0 })} />
                </label>
                <label className="поле">
                  Кадастровый номер
                  <input value={String(значение("кадастровый"))} onChange={(e) => setЧерновик({ ...черновик, кадастровый: e.target.value })} />
                </label>
                <label className="поле">
                  Начало работ
                  <input type="date" value={String(значение("датаНачала"))} onChange={(e) => setЧерновик({ ...черновик, датаНачала: e.target.value })} />
                </label>
                <label className="поле">
                  Сдача по договору
                  <input type="date" value={String(значение("датаСдачи"))} onChange={(e) => setЧерновик({ ...черновик, датаСдачи: e.target.value })} />
                </label>
                <label className="поле">
                  Прораб
                  <input value={String(значение("прораб"))} onChange={(e) => setЧерновик({ ...черновик, прораб: e.target.value })} />
                </label>
                <label className="поле">
                  Название проекта
                  <input value={String(значение("проектНазвание"))} onChange={(e) => setЧерновик({ ...черновик, проектНазвание: e.target.value })} />
                </label>
              </div>
              <div className="ряд" style={{ marginTop: 10 }}>
                <button className="кн главная" onClick={сохранить}>
                  Сохранить
                </button>
              </div>
            </>
          ) : (
            <table className="таблица">
              <tbody>
                <Строка что="Посёлок" значение={п.посёлок?.название || "—"} />
                <Строка что="Статус" значение={п.дом.статус} />
                <Строка что="Площадь" значение={`${п.дом.площадь || "—"} м²`} />
                <Строка что="Кадастровый" значение={п.дом.кадастровый || "—"} />
                <Строка что="Проект" значение={п.дом.проектНазвание || "—"} />
                <Строка что="Прораб" значение={п.дом.прораб || "—"} />
                <Строка что="Начало работ" значение={дата(п.дом.датаНачала)} />
                <Строка что="Сдача по договору" значение={дата(п.дом.датаСдачи)} />
              </tbody>
            </table>
          )}
        </div>

        <div className="панель">
          <div className="ряд-между">
            <h2>Заказчик</h2>
            {можноПравить && !правка && (
              <button className="ссылка" onClick={() => setПравка(true)}>
                править
              </button>
            )}
          </div>
          {правка ? (
            <div className="поля">
              <label className="поле">
                Имя
                <input
                  value={значение("заказчик")?.имя || ""}
                  onChange={(e) => setЧерновик({ ...черновик, заказчик: { ...значение("заказчик"), имя: e.target.value } as Дом["заказчик"] })}
                />
              </label>
              <label className="поле">
                Телефон
                <input
                  value={значение("заказчик")?.телефон || ""}
                  onChange={(e) => setЧерновик({ ...черновик, заказчик: { ...значение("заказчик"), телефон: e.target.value } as Дом["заказчик"] })}
                />
              </label>
              <label className="поле">
                Договор
                <input
                  value={значение("заказчик")?.договор || ""}
                  onChange={(e) => setЧерновик({ ...черновик, заказчик: { ...значение("заказчик"), договор: e.target.value } as Дом["заказчик"] })}
                />
              </label>
              <label className="поле">
                Папка для отчётов заказчику
                <input
                  value={значение("заказчик")?.чатПуть || ""}
                  placeholder="общий диск или синхронизируемая папка"
                  onChange={(e) => setЧерновик({ ...черновик, заказчик: { ...значение("заказчик"), чатПуть: e.target.value } as Дом["заказчик"] })}
                />
              </label>
            </div>
          ) : (
            <table className="таблица">
              <tbody>
                <Строка что="Имя" значение={п.дом.заказчик?.имя || "—"} />
                <Строка что="Телефон" значение={п.дом.заказчик?.телефон || "—"} />
                <Строка что="Договор" значение={п.дом.заказчик?.договор || "—"} />
                <Строка что="Папка отчётов" значение={п.дом.заказчик?.чатПуть || "не указана"} />
              </tbody>
            </table>
          )}
          <p className="подпись мелко" style={{ marginTop: 8 }}>
            Одобренный отчёт кладётся файлом в папку дома и, если указана папка заказчика, копируется
            туда. Программа сама никуда ничего не отправляет — файл ложится в папку, о которой
            договорились люди.
          </p>
        </div>
      </div>

      <div className="панель">
        <div className="ряд-между">
          <h2>Проектная документация</h2>
          <button className="ссылка" onClick={() => п.наВкладку("смета")}>
            перейти к смете
          </button>
        </div>
        {!проект && <p className="подпись">Читаем папку проекта…</p>}
        {проект && !проект.доступен && (
          <div className="внимание">
            {проект.замечание} Путь указывает архитектор в разделе «Источники данных».
          </div>
        )}
        {проект?.доступен && (
          <>
            <p className="подпись">
              Файлов {проект.файлы.length}, последняя правка {датаВремя(проект.изменён)}. Программа
              читает эту папку, но ничего в ней не меняет.
            </p>
            <table className="таблица">
              <thead>
                <tr>
                  <th>Раздел</th>
                  <th className="ч">Файлов</th>
                  <th className="ч">Чертежей</th>
                  <th className="ч">Спецификаций</th>
                  <th className="ч">Правили</th>
                </tr>
              </thead>
              <tbody>
                {проект.разделы.map((р) => (
                  <tr key={р.раздел}>
                    <td>{р.раздел}</td>
                    <td className="ч">{р.файлов}</td>
                    <td className="ч">{р.чертежей}</td>
                    <td className="ч">{р.спецификаций}</td>
                    <td className="ч">{дата(р.изменён)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </>
        )}
      </div>

      <div className="ряд">
        <button className="кн" onClick={() => window.стройка.открытьПапкуДома(п.дом.посёлокПапка, п.дом.папка).catch((e) => п.наОшибку(String(e.message || e)))}>
          Открыть папку дома
        </button>
        <span className="подпись мелко">
          Смета, график, заявки, чат и отчёты этого дома лежат там обычными файлами.
        </span>
      </div>
    </div>
  );
}

function Строка({ что, значение }: { что: string; значение: string }) {
  return (
    <tr>
      <td style={{ color: "var(--text-dim)", width: "45%" }}>{что}</td>
      <td>{значение}</td>
    </tr>
  );
}
