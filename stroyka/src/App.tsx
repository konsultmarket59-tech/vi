// Каркас окна.
//
// Программа открывается КАРТОЙ, а не списком объектов и не сводкой. Это не
// оформление, а то, как устроена работа: и прораб, и снабженец, и директор
// начинают разговор со слов «на Липовой 6», а не «по объекту №4». На карте
// видно улицу, соседей и цвет статуса — и дальше человек нажимает на дом.
//
// Роль переключается вверху и меняет всё сразу: набор вкладок, колонки сметы,
// доступные кнопки. Переключатель здесь, а не в настройках, ровно потому, что
// на стройке за одним компьютером в бытовке сидят по очереди трое.

import { useCallback, useEffect, useState } from "react";
import type { Дом, Настройки, Посёлок, Справочники } from "./lib/types";
import КартаПосёлков from "./components/КартаПосёлков";
import КарточкаДома from "./components/КарточкаДома";
import СводныйПлан from "./components/СводныйПлан";
import Источники from "./components/Источники";
import Настройка from "./components/Настройки";

export type Экран =
  | { вид: "карта" }
  | { вид: "дом"; посёлок: string; дом: string }
  | { вид: "план"; посёлок: string }
  | { вид: "источники" }
  | { вид: "настройки" };

export default function App() {
  const [справочники, setСправочники] = useState<Справочники | null>(null);
  const [настройки, setНастройки] = useState<Настройки | null>(null);
  const [посёлки, setПосёлки] = useState<Посёлок[]>([]);
  const [выбранныйПосёлок, setВыбранныйПосёлок] = useState<string>("");
  const [дома, setДома] = useState<Дом[]>([]);
  const [экран, setЭкран] = useState<Экран>({ вид: "карта" });
  const [загрузка, setЗагрузка] = useState(true);
  const [ошибка, setОшибка] = useState("");

  const обновитьПосёлки = useCallback(async () => {
    const список = await window.стройка.посёлки();
    setПосёлки(список);
    return список;
  }, []);

  useEffect(() => {
    (async () => {
      try {
        const [спр, наст, список] = await Promise.all([
          window.стройка.справочники(),
          window.стройка.настройки(),
          window.стройка.посёлки(),
        ]);
        setСправочники(спр);
        setНастройки(наст);
        setПосёлки(список);
        if (список.length) setВыбранныйПосёлок(список[0].папка);
      } catch (e) {
        setОшибка(e instanceof Error ? e.message : String(e));
      } finally {
        setЗагрузка(false);
      }
    })();
  }, []);

  const обновитьДома = useCallback(async (посёлок: string) => {
    if (!посёлок) {
      setДома([]);
      return [];
    }
    const список = await window.стройка.дома(посёлок);
    setДома(список);
    return список;
  }, []);

  useEffect(() => {
    обновитьДома(выбранныйПосёлок).catch((e) => setОшибка(String(e.message || e)));
  }, [выбранныйПосёлок, обновитьДома]);

  async function сменитьРоль(роль: string) {
    const новые = await window.стройка.сохранитьНастройки({ роль: роль as Настройки["роль"] });
    setНастройки(новые);
    // Роль меняет набор разделов: если человек стоял на вкладке, которой у
    // новой роли нет, оставлять его там нельзя — вернём на карту.
    const дозволено = справочники?.роли.find((р) => р.id === роль)?.разделы || [];
    if (экран.вид === "источники" && !дозволено.includes("источники")) setЭкран({ вид: "карта" });
    if (экран.вид === "план" && !дозволено.includes("поставки")) setЭкран({ вид: "карта" });
    if (экран.вид === "карта" && !дозволено.includes("карта")) {
      setЭкран(дома[0] ? { вид: "дом", посёлок: выбранныйПосёлок, дом: дома[0].папка } : { вид: "настройки" });
    }
  }

  if (загрузка) return <div className="загрузка">Загрузка…</div>;
  if (!справочники || !настройки) {
    return (
      <div className="загрузка">
        <div className="ошибка">Не удалось запуститься: {ошибка || "нет данных"}</div>
      </div>
    );
  }

  const роль = справочники.роли.find((р) => р.id === настройки.роль) || справочники.роли[0];
  const виден = (раздел: string) => роль.разделы.includes(раздел);
  const активныйДом = экран.вид === "дом" ? дома.find((д) => д.папка === экран.дом) : undefined;

  return (
    <div className="app">
      <aside className="sidebar">
        <div className="sidebar-head">
          <div className="logo">
            Строй<span>ка</span>
          </div>
          <div className="подпись мелко">организация строительства</div>
        </div>

        <div className="sidebar-scroll">
          <div className="nav-title">Посёлки</div>
          {посёлки.length === 0 && <div className="подпись мелко" style={{ padding: "4px 8px" }}>Пока ни одного — заведите на карте.</div>}
          {посёлки.map((п) => (
            <button
              key={п.папка}
              className={`nav-item ${выбранныйПосёлок === п.папка ? "on" : ""}`}
              onClick={() => {
                setВыбранныйПосёлок(п.папка);
                setЭкран(виден("карта") ? { вид: "карта" } : { вид: "план", посёлок: п.папка });
              }}
            >
              <span>{п.название}</span>
              <span className="счётчик">{п.домов ?? 0}</span>
            </button>
          ))}

          {выбранныйПосёлок && дома.length > 0 && (
            <>
              <div className="nav-title">Дома</div>
              {дома.slice(0, 40).map((д) => (
                <button
                  key={д.папка}
                  className={`nav-item ${экран.вид === "дом" && экран.дом === д.папка ? "on" : ""}`}
                  onClick={() => setЭкран({ вид: "дом", посёлок: выбранныйПосёлок, дом: д.папка })}
                >
                  <span>
                    {д.улица} {д.номер}
                  </span>
                  <span className="счётчик">{д.статус}</span>
                </button>
              ))}
              {дома.length > 40 && <div className="подпись мелко" style={{ padding: "4px 8px" }}>…и ещё {дома.length - 40}. Остальные — на карте.</div>}
            </>
          )}

          <div className="nav-title">Разделы</div>
          {виден("карта") && (
            <button className={`nav-item ${экран.вид === "карта" ? "on" : ""}`} onClick={() => setЭкран({ вид: "карта" })}>
              Карта посёлков
            </button>
          )}
          {(виден("поставки") || виден("бригады")) && выбранныйПосёлок && (
            <button
              className={`nav-item ${экран.вид === "план" ? "on" : ""}`}
              onClick={() => setЭкран({ вид: "план", посёлок: выбранныйПосёлок })}
            >
              Сводный план посёлка
            </button>
          )}
          {виден("источники") && (
            <button className={`nav-item ${экран.вид === "источники" ? "on" : ""}`} onClick={() => setЭкран({ вид: "источники" })}>
              Источники данных
            </button>
          )}
          <button className={`nav-item ${экран.вид === "настройки" ? "on" : ""}`} onClick={() => setЭкран({ вид: "настройки" })}>
            Настройки
          </button>
        </div>

        <div className="sidebar-foot">
          <label className="поле">
            Я сейчас
            <select value={настройки.роль} onChange={(e) => сменитьРоль(e.target.value)}>
              {справочники.роли.map((р) => (
                <option key={р.id} value={р.id}>
                  {р.название}
                </option>
              ))}
            </select>
          </label>
          <div className="подпись мелко" style={{ marginTop: 6 }}>{роль.описание}</div>
        </div>
      </aside>

      <main className="main">
        <header className="topbar">
          <div className="крошки">
            <button onClick={() => setЭкран(виден("карта") ? { вид: "карта" } : { вид: "настройки" })}>
              {посёлки.find((п) => п.папка === выбранныйПосёлок)?.название || "Стройка"}
            </button>
            {активныйДом && (
              <>
                <span className="разделитель">/</span>
                <span>
                  {активныйДом.улица} {активныйДом.номер}
                </span>
              </>
            )}
          </div>
          <span className="растяжка" />
          <span className="метка охра">{роль.название}</span>
          {настройки.пользователь && <span className="подпись">{настройки.пользователь}</span>}
        </header>

        {ошибка && (
          <div style={{ padding: "12px 16px 0" }}>
            <div className="ошибка">
              {ошибка} <button className="ссылка" onClick={() => setОшибка("")}>скрыть</button>
            </div>
          </div>
        )}

        {экран.вид === "карта" && (
          <КартаПосёлков
            посёлки={посёлки}
            выбранный={выбранныйПосёлок}
            дома={дома}
            роль={роль}
            наПосёлок={setВыбранныйПосёлок}
            наДом={(дом) => setЭкран({ вид: "дом", посёлок: выбранныйПосёлок, дом })}
            наПлан={() => setЭкран({ вид: "план", посёлок: выбранныйПосёлок })}
            обновитьПосёлки={обновитьПосёлки}
            обновитьДома={() => обновитьДома(выбранныйПосёлок)}
            наОшибку={setОшибка}
          />
        )}

        {экран.вид === "дом" && активныйДом && (
          <КарточкаДома
            дом={активныйДом}
            посёлок={посёлки.find((п) => п.папка === экран.посёлок) || null}
            роль={роль}
            справочники={справочники}
            настройки={настройки}
            обновитьДома={() => обновитьДома(выбранныйПосёлок)}
            наОшибку={setОшибка}
          />
        )}

        {экран.вид === "дом" && !активныйДом && <div className="view"><div className="пусто">Дом не найден — возможно, его папку переименовали.</div></div>}

        {экран.вид === "план" && (
          <СводныйПлан
            посёлок={посёлки.find((п) => п.папка === экран.посёлок) || null}
            роль={роль}
            наДом={(дом) => setЭкран({ вид: "дом", посёлок: экран.посёлок, дом })}
            наОшибку={setОшибка}
          />
        )}

        {экран.вид === "источники" && <Источники роль={роль} справочники={справочники} наОшибку={setОшибка} />}

        {экран.вид === "настройки" && (
          <Настройка настройки={настройки} справочники={справочники} наИзменение={setНастройки} наОшибку={setОшибка} />
        )}
      </main>
    </div>
  );
}
