// Демонстрация в браузере: то же окно, те же движки, другое хранилище.
//
// Приложение — десктопное, и посмотреть его в браузере нельзя: оно читает
// файлы на диске, открывает системные диалоги и ходит к модели. Но окно и
// расчёты от этого не зависят, и именно их полезно показать до установки.
//
// Здесь подменяется ровно один слой — тот, что в приложении разговаривает с
// главным процессом. Вместо файлов — localStorage, вместо диалогов выбора
// файла — заглушки, вместо прайса снабженца — таблица из «данные.ts». Всё
// остальное настоящее: смету, график, очередь бригад, объединение поставок и
// пороги одобрения считают те же модули из electron/, что и в приложении.
// Поэтому демонстрация не может «показать красиво», а потом разойтись с
// продуктом: разойдётся — значит сломано и в продукте.
//
// Два места, где демонстрация честно не может сделать вид:
//
//   1. АГЕНТ. В браузере нет ключа к модели, и просить его у человека,
//      открывшего демо по ссылке, нельзя. Разбор отчёта и совет по логистике
//      возвращают заготовленный пример, ПОМЕЧЕННЫЙ как пример. Подделывать
//      ответ модели «умной» подстановкой по ключевым словам было бы хуже
//      отсутствия ответа: человек решил бы, что видел работу агента.
//   2. ФАЙЛЫ. Комплект исполнительной документации, чтение папки проекта и
//      выбор путей требуют файловой системы. Они отвечают прямым «в демо
//      недоступно», а не пустым результатом.

