/**
 * Первый запуск: посёлок, улица домов, сметы у тех, что уже строятся, и
 * несколько отчётов в ленте. Пустая демонстрация бесполезна — по пустому
 * экрану не видно ни очереди бригад, ни объединения поставок.
 */
function завести(): Состояние {
  const состояние: Состояние = {
    посёлки: [
      {
        id: "demo",
        папка: ПАПКА,
        название: ПОСЁЛОК.название,
        адрес: ПОСЁЛОК.адрес,
        картаФайл: "",
        улицы: ПОСЁЛОК.улицы,
      },
    ],
    дома: { [ПАПКА]: [] },
    разделы: {},
    настройки: пустыеНастройки(),
  };

  состояние.дома[ПАПКА] = ДОМА.map((д, i) => ({
    id: `d${i}`,
    папка: `${д.улица} ${д.номер}`,
    посёлокПапка: ПАПКА,
    улица: д.улица,
    номер: д.номер,
    кадастровый: д.кадастровый,
    площадь: д.площадь,
    участок: 0,
    статус: д.статус,
    точка: д.точка,
    проектПуть: "",
    проектНазвание: д.проектНазвание,
    заказчик: д.заказчик,
    прораб: д.прораб,
    бригада: "",
    датаНачала: д.датаНачала,
    датаСдачи: д.датаСдачи,
  }));

  for (const [i, описание] of ДОМА.entries()) {
    if (!описание.сСметой) continue;
    const дом = состояние.дома[ПАПКА][i];
    const смета = estimateEngine.пустаяСмета();
    const { набор } = calc.прикидкаПоПлощади(описание.площадь);
    for (const шаг of набор) {
      const расчёт = calc.рассчитать(шаг.вид, шаг.параметры, { прайс: ПРАЙС_С_МАРКАМИ, регион: "пермский", сложность: "типовой" });
      estimateEngine.применитьРасчёт(смета, расчёт, "Сметчик", "руководитель");
    }
    if (описание.номер === "2") {
      estimateEngine.согласовать(смета, "Петров А. А.", "директор", "по договору №14");
      // У дома, который уже строится, часть работ принята по факту — иначе не
      // видно ни отклонений, ни того, что вообще попадает в КС-2.
      for (const поз of смета.позиции.slice(0, 6)) {
        const отклонение = 1 + (Math.round((поз.количество % 7) - 3) / 100);
        estimateEngine.внестиФакт(смета, поз.id, Math.round(поз.количество * отклонение * 100) / 100, "Синицын И.", "прораб", "отчёт с объекта");
      }
    }
    состояние.разделы[раздел(ПАПКА, дом.папка, "смета")] = смета;

    const этапы = scheduleEngine.этапыИзРасчёта(scheduleEngine.этапыИзСметы(смета), {});
    let график = scheduleEngine.построить(этапы, { начало: дом.датаНачала, режим: "6/1" });
    // отметитьФакт возвращает новый график, а не правит старый: результат надо
    // забрать. Без присваивания отметки просто теряются, и дом, который уже
    // строится, показывает нулевую готовность.
    for (const [этап, готовность] of отметкиГотовности(описание)) {
      график = scheduleEngine.отметитьФакт(график, этап, {
        готовность,
        статус: готовность >= 100 ? "выполнен" : "идёт",
      });
    }
    состояние.разделы[раздел(ПАПКА, дом.папка, "график")] = график;
    состояние.разделы[раздел(ПАПКА, дом.папка, "приёмка")] = { приёмки: scheduleEngine.графикПриёмки(график) };
  }

  for (const с of СООБЩЕНИЯ) {
    const дом = состояние.дома[ПАПКА].find((д) => `${д.улица} ${д.номер}` === с.дом);
    if (!дом) continue;
    const ключ = раздел(ПАПКА, дом.папка, "чат");
    const лента = (состояние.разделы[ключ] as ReturnType<typeof chatEngine.пусто>) || chatEngine.пусто();
    const сообщение = chatEngine.добавитьСообщение(лента, { текст: с.текст, автор: с.автор, рольАвтора: с.роль, фото: с.фото, дата: с.дата });
    // Отчёты были написаны в разные дни, и в ленте это должно быть видно:
    // иначе все три показывают одну и ту же секунду создания демонстрации.
    сообщение.когда = `${с.дата}T${с.время}:00.000Z`;
    состояние.разделы[ключ] = лента;
  }

  return состояние;
}

/** Этап графика в том виде, в каком его отдаёт движок расписания. */
interface ЭтапДемо {
  id: string;
  статус: string;
  готовность: number;
  конец: string;
}

/** Пустой график: с явной формой, иначе `этапы: []` выводится как never[]. */
function пустойГрафик(): { этапы: ЭтапДемо[]; сдача?: string; прогнозСдачи?: string; сдвигСдачи?: number } {
  return { этапы: [] };
}

/**
 * Насколько продвинулся дом. Зависит от того, давно ли он начат: улица должна
 * выглядеть живой — где-то фундамент, где-то отделка, а не всё сразу.
 */
function отметкиГотовности(описание: { статус: string; номер: string }): [string, number][] {
  if (описание.статус === "готов") return [];
  if (описание.статус !== "стройка") return [];
  if (описание.номер === "2") return [["Земляные работы", 100], ["Фундамент", 100], ["Кладка", 100], ["Перекрытие", 100], ["Кровля", 60]];
  if (описание.номер === "4") return [["Земляные работы", 100], ["Фундамент", 100], ["Кладка", 70]];
  return [["Земляные работы", 100], ["Фундамент", 45]];
}

function раздел(посёлок: string, дом: string, имя: string) {
  return `${посёлок}/${дом}/${имя}`;
}

let состояние: Состояние = загрузить();

function загрузить(): Состояние {
  try {
    const сохранённое = localStorage.getItem(КЛЮЧ_ХРАНИЛИЩА);
    if (сохранённое) return JSON.parse(сохранённое) as Состояние;
  } catch {
    // Приватное окно, отключённые куки, переполненное хранилище — во всех этих
    // случаях демонстрация должна открыться, просто без сохранения.
  }
  const свежее = завести();
  сохранить(свежее);
  return свежее;
}

function сохранить(что: Состояние = состояние) {
  try {
    localStorage.setItem(КЛЮЧ_ХРАНИЛИЩА, JSON.stringify(что));
  } catch {
    // Не сохранилось — работаем в памяти до перезагрузки страницы.
  }
}

function взять<T>(ключ: string, пусто: T): T {
  const данные = состояние.разделы[ключ];
  return данные ? ({ ...пусто, ...(данные as object) } as T) : (JSON.parse(JSON.stringify(пусто)) as T);
}

function положить(ключ: string, данные: unknown) {
  состояние.разделы[ключ] = данные;
  сохранить();
}

function домПоПапке(посёлок: string, папка: string) {
  const найден = (состояние.дома[посёлок] || []).find((д) => д.папка === папка);
  if (!найден) throw new Error("Дом не найден");
  return найден;
}

function нельзя(что: string): never {
  throw new Error(
    `${что} работает с файлами на компьютере, поэтому в демонстрации недоступно. ` +
      `В приложении это обычный диалог выбора файла или папки.`
  );
}

