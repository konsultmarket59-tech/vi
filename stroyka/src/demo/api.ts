/** Сборка объектов посёлка для сводного плана — как в главном процессе. */
function объектыПосёлка(посёлок: string) {
  return (состояние.дома[посёлок] || [])
    .filter((д) => д.статус !== "готов" && д.статус !== "передан")
    .map((дом) => {
      const смета = взять(раздел(посёлок, дом.папка, "смета"), estimateEngine.пустаяСмета());
      const расчёты = смета.позиции.length
        ? scheduleEngine.этапыИзСметы(смета)
        : calc.рассчитатьНабор(calc.прикидкаПоПлощади(дом.площадь || 100).набор, {}).расчёты;
      return {
        ...дом,
        ключ: `${посёлок}/${дом.папка}`,
        этапы: scheduleEngine.этапыИзРасчёта(расчёты, { бригадНаЭтап: состояние.настройки.бригады || {} }),
        смета: estimateEngine.развернутьСмету(смета),
      };
    });
}

function правкаСметы(посёлок: string, дом: string, изменить: (см: never, кто: string, роль: string) => void, право = "правитьСмету") {
  const н = состояние.настройки;
  if (!roles.можно(н.роль, право)) throw new Error(`Роль «${roles.роль(н.роль).название}» этого не делает.`);
  const ключ = раздел(посёлок, дом, "смета");
  const смета = взять(ключ, estimateEngine.пустаяСмета());
  изменить(смета as never, н.пользователь || roles.роль(н.роль).название, н.роль);
  положить(ключ, смета);
  return estimateEngine.дляРоли(смета, н.роль);
}

