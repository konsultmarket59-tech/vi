/**
 * Обёртка над обработчиком: любая ошибка доезжает до окна текстом, а не
 * «Error invoking remote method». Человек на стройке должен прочитать, что
 * случилось, а не гадать.
 */
function ручка(канал, обработчик) {
  ipcMain.handle(канал, async (_событие, ...аргументы) => {
    try {
      return { ok: true, данные: await обработчик(...аргументы) };
    } catch (e) {
      console.error(`[${канал}]`, e);
      return { ok: false, ошибка: e instanceof Error ? e.message : String(e) };
    }
  });
}

