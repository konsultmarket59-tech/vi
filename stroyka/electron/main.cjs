/** Собирает всё, что нужно для сводного плана: дома, этапы, сметы. */
async function объектыПосёлка(посёлок) {
  const дома = await хранилище.дома(посёлок);
  const н = await настройки();
  const собранные = [];
  for (const дом of дома) {
    if (дом.статус === "готов" || дом.статус === "передан") continue;
    const смета = await сметаДома(посёлок, дом.папка);
    const расчёты = смета.позиции.length
      ? этапыИзСметы(смета)
      : calc.рассчитатьНабор(calc.прикидкаПоПлощади(дом.площадь || 100).набор, {}).расчёты;
    собранные.push({
      ...дом,
      ключ: ключДома(посёлок, дом.папка),
      этапы: schedule.этапыИзРасчёта(расчёты, { бригадНаЭтап: н.бригады || {} }),
      смета: estimate.развернутьСмету(смета),
    });
  }
  return собранные;
}

