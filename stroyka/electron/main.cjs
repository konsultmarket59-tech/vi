/**
 * Один запрос к модели. Без потоковой выдачи: все места, где модель здесь
 * нужна, — это разбор или подготовка документа, где важен цельный ответ, а не
 * буквы по одной.
 */
async function спроситьМодель(system, user, { изображения = [] } = {}) {
  const н = await настройки();
  if (!н.apiKey) throw new Error("Не указан ключ доступа к модели: Настройки → Модель.");
  // Ключ уходит в HTTP-заголовок, а заголовки не принимают ничего, кроме
  // latin-1: случайно скопированный кириллический символ иначе даёт невнятную
  // ошибку из глубины fetch.
  // Проверка намеренно смотрит на диапазон символов, включая управляющие:
  // заголовку HTTP нельзя ничего вне latin-1, каким бы этот символ ни был.
  // eslint-disable-next-line no-control-regex
  if (/[^\u0000-\u00ff]/.test(н.apiKey)) {
    throw new Error("В ключе есть символы, недопустимые для заголовка запроса (например, кириллица). Скопируйте ключ заново.");
  }

  const содержимое = изображения.length
    ? [{ type: "text", text: user }, ...изображения.map((url) => ({ type: "image_url", image_url: { url } }))]
    : user;

  const ответ = await fetch(`${н.baseUrl.replace(/\/$/, "")}/chat/completions`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${н.apiKey}` },
    body: JSON.stringify({
      model: н.model,
      temperature: н.temperature,
      max_tokens: н.maxTokens,
      messages: [
        { role: "system", content: system },
        { role: "user", content: содержимое },
      ],
    }),
  });

  if (!ответ.ok) {
    const текст = await ответ.text().catch(() => "");
    if (ответ.status === 401) throw new Error("Ключ не принят: сервис ответил, что он неверный.");
    if (ответ.status === 407) throw new Error("Прокси требует логин и пароль, а те, что указаны, он не принял.");
    if (ответ.status === 429) throw new Error("Сервис просит подождать: слишком много запросов подряд.");
    throw new Error(`Модель ответила ошибкой ${ответ.status}. ${текст.slice(0, 300)}`);
  }
  const данные = await ответ.json();
  return данные.choices?.[0]?.message?.content || "";
}

