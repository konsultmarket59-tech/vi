ручка("отчёт:отправить", async (посёлок, дом, id) => {
  const н = await настройки();
  const чат = await чатДома(посёлок, дом);
  const отчёт = (чат.отчёты || []).find((о) => о.id === id);
  if (!отчёт) throw new Error("Отчёт не найден");

  // Отчёт кладётся файлом в папку дома и, если у заказчика указана своя папка
  // (общий диск, синхронизируемая папка мессенджера), — ещё и туда. Программа
  // сама никуда ничего не отправляет: она пишет файл в папку, о которой
  // договорились люди. Так у отчёта нет отдельного канала, который однажды
  // перестанет работать вместе с чужим сервисом.
  const папка = хранилище.папкаОтчётов(посёлок, дом);
  await ensureDir(папка);
  const имя = `Отчёт — ${отчёт.дом} — ${отчёт.период || отчёт.когда.slice(0, 10)}.md`.replace(/[\\/:*?"<>|]/g, "-");
  const файл = path.join(папка, имя);
  await fs.writeFile(файл, отчёт.текст, "utf-8");

  const домДанные = await хранилище.дом(посёлок, дом);
  const чатЗаказчика = домДанные?.заказчик?.чатПуть;
  let вПапкуЗаказчика = "";
  if (чатЗаказчика) {
    try {
      await ensureDir(чатЗаказчика);
      вПапкуЗаказчика = path.join(чатЗаказчика, имя);
      await fs.copyFile(файл, вПапкуЗаказчика);
    } catch (e) {
      вПапкуЗаказчика = `не удалось положить в папку заказчика: ${e.message}`;
    }
  }

  chat.отправитьОтчёт(чат, id, н.пользователь || "", н.роль, файл);
  await хранилище.записатьРаздел(посёлок, дом, "чат", чат);
  return { отчёты: чат.отчёты, файл, вПапкуЗаказчика };
});

