/** Фото читается с диска и уезжает в модель картинкой; в программе — только путь. */
async function фотоКакДанные(пути, предел = 4) {
  const данные = [];
  for (const путь of (пути || []).slice(0, предел)) {
    try {
      const файл = await fs.readFile(путь);
      // Снимок с телефона на 8 МБ в base64 весит 11 МБ, и запрос с четырьмя
      // такими просто не уходит — крупные пропускаем, назвав это в ответе.
      if (файл.length > 6 * 1024 * 1024) continue;
      const ext = path.extname(путь).slice(1).toLowerCase();
      данные.push(`data:image/${ext === "jpg" ? "jpeg" : ext};base64,${файл.toString("base64")}`);
    } catch {
      // Фото могло переехать вместе с папкой — это не повод ронять разбор.
    }
  }
  return данные;
}

