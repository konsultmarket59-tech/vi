/** Прайс читается по запросу и держится в памяти, пока файл не изменился. */
let кэшПрайса = { путь: "", изменён: "", данные: null };

async function прайс(ключ) {
  const запись = await источники.путь("прайс", ключ);
  if (!запись?.путь) return { доступен: false, замечание: "Путь к прайсу не указан", позиции: [] };
  const состояние = await проверить(запись.путь, "файл");
  if (!состояние.доступен) return { доступен: false, замечание: состояние.замечание, позиции: [] };
  if (кэшПрайса.путь === запись.путь && кэшПрайса.изменён === состояние.изменён && кэшПрайса.данные) {
    return кэшПрайса.данные;
  }
  const данные = await pricesFile.прочитатьПрайс(запись.путь);
  кэшПрайса = { путь: запись.путь, изменён: состояние.изменён, данные };
  return данные;
}

