async function применитьПрокси(настройкиТекущие) {
  setProxyCredentials(настройкиТекущие.proxyUsername || "", настройкиТекущие.proxyPassword || "");
  const режим = настройкиТекущие.proxyMode || "system";
  const конфигПрокси =
    режим === "manual" && настройкиТекущие.proxyUrl?.trim()
      ? { proxyRules: настройкиТекущие.proxyUrl.trim() }
      : режим === "direct"
        ? { mode: "direct" }
        : { mode: "system" };
  try {
    await session.defaultSession.setProxy(конфигПрокси);
  } catch (e) {
    console.error("Не удалось применить прокси:", e);
  }
}

async function подготовить() {
  await ensureDir(ПАПКА_НАСТРОЕК);
  конфиг = await readJson(ФАЙЛ_КОНФИГА, { rootPath: "" });
  if (!конфиг.rootPath) конфиг.rootPath = КОРЕНЬ_ПО_УМОЛЧАНИЮ;
  try {
    await ensureDir(конфиг.rootPath);
  } catch {
    // «Документы» могут быть недоступны: перенесены в отключённое облако, нет
    // прав на запись. Программа не должна из-за этого не запуститься — уходим
    // в свою служебную папку и говорим об этом человеку в настройках.
    конфиг.rootPath = ЗАПАСНОЙ_КОРЕНЬ;
    конфиг.запасной = true;
    await ensureDir(конфиг.rootPath);
  }
  await writeJson(ФАЙЛ_КОНФИГА, конфиг);
  хранилище = new Хранилище(конфиг.rootPath);
  источники = new Источники(path.join(конфиг.rootPath, "источники.json"));
  await хранилище.подготовить();
  await применитьПрокси(await настройки());
}

async function настройки() {
  const данные = await readJson(path.join(конфиг.rootPath, "настройки.json"), {});
  return {
    ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ,
    ...данные,
    компания: { ...НАСТРОЙКИ_ПО_УМОЛЧАНИЮ.компания, ...данные.компания },
  };
}

function создатьОкно() {
  const окно = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 1024,
    minHeight: 640,
    title: "Стройка",
    backgroundColor: "#f6f5f2",
    webPreferences: {
      preload: path.join(__dirname, "preload.cjs"),
      contextIsolation: true,
      nodeIntegration: false,
    },
  });
  const адресРазработки = process.env.VITE_DEV_SERVER_URL;
  if (адресРазработки) окно.loadURL(адресРазработки);
  else окно.loadFile(path.join(__dirname, "..", "dist", "index.html"));

  окно.webContents.setWindowOpenHandler(({ url }) => {
    shell.openExternal(url);
    return { action: "deny" };
  });
  return окно;
}

