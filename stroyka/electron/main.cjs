/**
 * Картинка карты отдаётся окну как data-URL.
 *
 * Файл при этом остаётся на своём месте: программа не копирует карту к себе, а
 * читает по пути — ровно как проект и прайс.
 */
ручка("файл:какКартинка", async (путь) => {
  const данные = await fs.readFile(путь);
  const ext = path.extname(путь).slice(1).toLowerCase();
  const тип = ext === "svg" ? "image/svg+xml" : ext === "jpg" ? "image/jpeg" : `image/${ext}`;
  return `data:${тип};base64,${данные.toString("base64")}`;
});

