// На некоторых установках Windows (замечено при «Документах», перенесённых в
// OneDrive) app.getPath отдаёт путь с префиксом «\\?\», который path.join потом
// ломает. Свои короткие пути в нём не нуждаются — снимаем сразу.
function безПрефикса(p) {
  return typeof p === "string" && p.startsWith("\\\\?\\") ? p.slice(4) : p;
}

