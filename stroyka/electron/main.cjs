/** Текстовое представление таблицы или документа — то, что уезжает в модель. */
async function читатьТаблицу(файл) {
  const ext = path.extname(файл).toLowerCase();
  if (ext === ".xlsx" || ext === ".xls") {
    const ExcelJS = require("exceljs");
    const книга = new ExcelJS.Workbook();
    await книга.xlsx.readFile(файл);
    const куски = [];
    книга.eachSheet((лист) => {
      куски.push(`# Лист «${лист.name}»`);
      let строк = 0;
      лист.eachRow((строка) => {
        if (строк++ > 400) return;
        const ячейки = [];
        строка.eachCell({ includeEmpty: true }, (я) => ячейки.push(prices.текст(я.value)));
        if (ячейки.some(Boolean)) куски.push(ячейки.join(" | "));
      });
    });
    return куски.join("\n").slice(0, 60000);
  }
  if (ext === ".docx") {
    const mammoth = require("mammoth");
    const { value } = await mammoth.extractRawText({ path: файл });
    return value.slice(0, 60000);
  }
  if (ext === ".csv" || ext === ".txt" || ext === ".md") {
    return (await fs.readFile(файл, "utf-8")).slice(0, 60000);
  }
  if (ext === ".pdf") {
    const pdf = require("pdf-parse");
    const данные = await pdf(await fs.readFile(файл));
    return String(данные.text || "").slice(0, 60000);
  }
  throw new Error(`Не умею читать файлы «${ext || "без расширения"}» — нужен xlsx, csv, docx, pdf или txt.`);
}

