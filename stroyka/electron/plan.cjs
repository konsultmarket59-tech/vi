/**
 * Когда материал должен быть на объекте.
 *
 * «Не позже» — за день до старта этапа: материал, приехавший в день начала
 * работ, означает простой бригады на полсмены.
 * «Не раньше» — за `окноХранения` дней: раньше держать негде.
 */
function окноПоставки(началоЭтапа, окноХранения, наименование) {
  // Бетон — особый случай: товарный бетон выгружают в дело, «завезти заранее»
  // его нельзя вообще. Поэтому окно нулевой ширины: день в день.
  const дней = наименование ? Math.min(окноХранения, срокХранения(наименование, окноХранения)) : окноХранения;
  const неПозже = плюсДней(началоЭтапа, дней === 0 ? 0 : -1);
  return {
    неПозже,
    неРаньше: дней === 0 ? неПозже : плюсДней(началоЭтапа, -Math.max(1, дней)),
    храненияДней: дней,
  };
}

/**
 * Собирает потребность в материалах из смет и графиков всех домов.
 * Каждая строка знает свой дом, улицу, этап и окно поставки.
 */
function потребность(объекты, { окноХранения = 35 } = {}) {
  const строки = [];
  for (const { дом, график, смета } of объекты) {
    const датыЭтапов = new Map(график.этапы.map((э) => [э.id, э]));
    for (const поз of смета?.позиции || []) {
      if (поз.вид !== "материал") continue;
      const этап = датыЭтапов.get(поз.этап);
      if (!этап) continue;
      const окно = окноПоставки(этап.начало, окноХранения, поз.наименование);
      const масса = массаПозиции(поз.наименование, поз.единица);
      строки.push({
        id: id(),
        домКлюч: дом.ключ,
        дом: `${дом.улица} ${дом.номер}`.trim(),
        улица: дом.улица || "без улицы",
        этап: поз.этап,
        стартЭтапа: этап.начало,
        наименование: поз.наименование,
        единица: поз.единица,
        количество: Number(поз.количество) || 0,
        цена: Number(поз.ценаЗакупки) || 0,
        сумма: Math.round((Number(поз.количество) || 0) * (Number(поз.ценаЗакупки) || 0)),
        тонн: Number(((Number(поз.количество) || 0) * масса.тоннНаЕдиницу).toFixed(2)),
        транспорт: масса.транспорт,
        тяжёлое: тяжёлое(поз.наименование, поз.единица),
        ...окно,
      });
    }
  }
  return строки.sort((a, b) => a.неПозже.localeCompare(b.неПозже));
}

/**
 * Объединение поставок в рейсы.
 *
 * Ключ объединения — улица + материал + неделя. Улица, потому что машина
 * заезжает на одну улицу и разгружается по домам; материал, потому что бетон и
 * плитку не везут одной машиной; неделя, потому что объединять сутки в сутки
 * бессмысленно — окно поставки всё равно шире.
 *
 * Дата объединённой поставки — САМАЯ РАННЯЯ из «не позже» в группе. Не средняя
 * и не поздняя: опоздание к первому же дому останавливает бригаду, а лишние
 * несколько дней хранения — это неудобство, но не простой.
 */
function объединить(строки, { окно = "окна" } = {}) {
  // Группируем по улице и материалу — дальше внутри группы работает окно
  // поставки, а не календарь.
  const поМатериалу = new Map();
  for (const строка of строки) {
    const ключ = `${строка.улица}|${строка.наименование}`;
    if (!поМатериалу.has(ключ)) поМатериалу.set(ключ, []);
    поМатериалу.get(ключ).push(строка);
  }

  const партии = [];
  for (const [, список] of поМатериалу) {
    // По «не позже»: первым закрываем то, что нужно раньше всех.
    список.sort((a, b) => a.неПозже.localeCompare(b.неПозже));
    let партия = null;
    for (const строка of список) {
      // Объединять можно ровно тогда, когда у поставок есть ОБЩИЙ ДЕНЬ, в
      // который машина успевает к каждой из них и никому не приезжает раньше,
      // чем есть где хранить. Календарная неделя такого не гарантирует: две
      // поставки в среду и пятницу одной недели могут не иметь общего дня, а
      // поставки 30-го и 2-го — иметь. Поэтому пересечение окон, а не неделя.
      // Даты — строки «ГГГГ-ММ-ДД», и сравнивать их надо строками. Math.max
      // здесь молча даёт NaN (строка приводится к числу), «NaN <= NaN» — ложь,
      // и объединение перестаёт срабатывать вообще, ничего при этом не ломая
      // на вид: план строится, просто каждая поставка едет своей машиной.
      const пересекается =
        партия &&
        (окно === "день"
          ? строка.неПозже === партия.неПозже
          : позже(строка.неРаньше, партия.неРаньше) <= раньше(строка.неПозже, партия.неПозже));
      if (!пересекается) {
        партия = {
          id: id(),
          улица: строка.улица,
          наименование: строка.наименование,
          единица: строка.единица,
          транспорт: строка.транспорт,
          тяжёлое: строка.тяжёлое,
          дома: [],
          количество: 0,
          сумма: 0,
          тонн: 0,
          неПозже: строка.неПозже,
          неРаньше: строка.неРаньше,
          этапы: new Set(),
        };
        партии.push(партия);
      }
      партия.дома.push({ дом: строка.дом, домКлюч: строка.домКлюч, количество: строка.количество, этап: строка.этап });
      партия.количество += строка.количество;
      партия.сумма += строка.сумма;
      партия.тонн += строка.тонн;
      партия.этапы.add(строка.этап);
      // Окно партии сужается до пересечения: «не позже» — самое раннее из
      // требований (опоздать нельзя ни к кому), «не раньше» — самое позднее.
      if (строка.неПозже < партия.неПозже) партия.неПозже = строка.неПозже;
      if (строка.неРаньше > партия.неРаньше) партия.неРаньше = строка.неРаньше;
    }
  }

  return партии
    .map((г) => {
      const т = ТРАНСПОРТ[г.транспорт] || ТРАНСПОРТ.фура;
      const рейсов = рейсы(г.тонн, г.количество, г.транспорт);
      return {
        ...г,
        период: неделя(г.неПозже),
        этапы: [...г.этапы],
        количество: Number(г.количество.toFixed(2)),
        тонн: Number(г.тонн.toFixed(2)),
        // Домов, а не строк: один материал попадает в дом дважды (клей нужен и
        // на стены, и на перегородки), и «10 домов» на улице из пяти домов —
        // цифра, после которой плану перестают верить.
        домов: new Set(г.дома.map((д) => д.домКлюч)).size,
        рейсов,
        стоимостьДоставки: рейсов * т.рейс,
        транспортНазвание: т.название,
        // Дата поставки: как можно позже внутри окна, но не позже «не позже».
        // Позже — потому что деньги за материал уходят раньше, чем он нужен,
        // и потому что материал на участке портится и пропадает.
        дата: г.неПозже,
      };
    })
    .sort((a, b) => a.дата.localeCompare(b.дата));
}

/**
 * Сколько рейсов на такой груз.
 *
 * Одна формула и для объединённой поставки, и для необъединённой — иначе
 * сравнение «было / стало» сравнивает две разные арифметики и показывает
 * экономию там, где её нет (или прячет там, где она есть). Ограничения два:
 * по массе и по объёму кузова, считаем по худшему — фура упирается в объём
 * раньше, чем в тонны, а самосвал с песком наоборот.
 */
function рейсы(тонн, количество, транспорт) {
  const т = ТРАНСПОРТ[транспорт] || ТРАНСПОРТ.фура;
  return Math.max(1, Math.ceil(Math.max(тонн / т.тонн, количество / (т.единиц * 3))));
}

/** Максимум и минимум для дат-строк: сравнение лексикографическое, не числовое. */
function позже(a, b) {
  return a > b ? a : b;
}
function раньше(a, b) {
  return a < b ? a : b;
}

function неделя(датаСтрока) {
  const d = дата(датаСтрока);
  const день = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() - (день - 1));
  return строкаДаты(d);
}

/**
 * Проверка поставок на ограничения и перенос тех, что в них попали.
 *
 * Распутица — единственное ограничение, из-за которого поставка двигается
 * автоматически: везти тяжёлое в это окно либо нельзя, либо вдвое дороже.
 * Двигаем ВПЕРЁД (завезти до ограничений), а не назад: после распутицы
 * материал приедет, когда работы уже должны идти.
 */
function проверить(поставки, { распутица = РАСПУТИЦА } = {}) {
  return поставки.map((п) => {
    const замечания = [];
    let дата = п.дата;

    const хранитьНельзя = срокХранения(п.наименование, 10) === 0;

    if (п.тяжёлое && вРаспутицу(дата, распутица) && хранитьНельзя) {
      // Товарный бетон нельзя ни завезти заранее, ни отложить: он выгружается
      // в дело в тот же час. Двигать тут нечего, и делать вид, что план сошёлся,
      // нельзя — двигать надо саму работу, а это решение человека, а не
      // планировщика. Поэтому поставка остаётся на своём дне с прямой пометкой.
      замечания.push(
        `Бетонирование попадает в весенние ограничения нагрузки (${распутица.начало}—${распутица.конец}), ` +
          `а товарный бетон нельзя завезти заранее. Нужен пропуск на проезд либо перенос самих работ — ` +
          `решает руководитель, план сдвинуть за вас нельзя.`
      );
    } else if (п.тяжёлое && вРаспутицу(дата, распутица)) {
      const год = дата.slice(0, 4);
      const доОграничений = плюсДней(`${год}-${распутица.начало}`, -3);
      const после = плюсДней(`${год}-${распутица.конец}`, 2);
      // Если работа начинается уже после ограничений — просто ждём их конца.
      // Если раньше — завозим заранее и миримся с длительным хранением.
      if (после <= п.неПозже) {
        дата = после;
        замечания.push(`Весенние ограничения нагрузки: поставка сдвинута на ${после}, после снятия.`);
      } else {
        дата = доОграничений;
        const дней = Math.round((schedule.дата(п.неПозже) - schedule.дата(доОграничений)) / 86400000);
        замечания.push(
          `Весенние ограничения нагрузки: завозим до ${доОграничений}, за ${дней} дн. до работ. ` +
            `Нужно место для хранения на объекте.`
        );
      }
    }

    const хранение = Math.round((schedule.дата(п.неПозже) - schedule.дата(дата)) / 86400000);
    if (хранение > срокХранения(п.наименование, 10)) {
      замечания.push(`Лежит на объекте ${хранение} дн. — проверьте, есть ли где хранить и кто отвечает за сохранность.`);
    }
    const месяц = Number(дата.slice(5, 7));
    if ([12, 1, 2].includes(месяц) && /смесь|штукатурк|клей|затирк|шпакл|краск|грунтовк/i.test(п.наименование)) {
      замечания.push("Зимняя поставка сухих смесей: нужен отапливаемый склад, иначе смесь схватывается от влаги.");
    }
    if (п.домов > 1) {
      замечания.push(
        `Объединено ${п.домов} домов на улице ${п.улица}: ${п.рейсов} рейс(ов) ${п.транспортНазвание.toLowerCase()} ` +
          `вместо ${п.домов} отдельных завозов.`
      );
    }

    return { ...п, дата, хранениеДней: хранение, замечания, статус: "план" };
  }).sort((a, b) => a.дата.localeCompare(b.дата));
}

/**
 * Полный график поставок по посёлку. Возвращает и план, и то, что он экономит:
 * без цифры экономии объединение рейсов — просто мнение.
 */
function графикПоставок(объекты, настройки = {}) {
  const строки = потребность(объекты, настройки);
  const поставки = проверить(объединить(строки, настройки), настройки);

  const рейсовБезОбъединения = строки.reduce((s, строка) => s + рейсы(строка.тонн, строка.количество, строка.транспорт), 0);
  const рейсовСОбъединением = поставки.reduce((s, п) => s + п.рейсов, 0);
  const стоимостьБез = строки.reduce(
    (s, строка) => s + рейсы(строка.тонн, строка.количество, строка.транспорт) * (ТРАНСПОРТ[строка.транспорт] || ТРАНСПОРТ.фура).рейс,
    0
  );
  const стоимостьС = поставки.reduce((s, п) => s + п.стоимостьДоставки, 0);

  return {
    поставки,
    строк: строки.length,
    сумма: поставки.reduce((s, п) => s + п.сумма, 0),
    рейсовБезОбъединения,
    рейсовСОбъединением,
    экономияРейсов: рейсовБезОбъединения - рейсовСОбъединением,
    экономияДоставки: стоимостьБез - стоимостьС,
    сЗамечаниями: поставки.filter((п) => п.замечания.length).length,
    вРаспутицу: поставки.filter((п) => п.тяжёлое && вРаспутицу(п.дата)).length,
    // Деньги по месяцам: снабжению нужен не список поставок, а понимание,
    // сколько денег нужно в каком месяце.
    поМесяцам: сводкаПоМесяцам(поставки),
  };
}

function сводкаПоМесяцам(поставки) {
  const карта = new Map();
  for (const п of поставки) {
    const месяц = п.дата.slice(0, 7);
    if (!карта.has(месяц)) карта.set(месяц, { месяц, сумма: 0, поставок: 0, рейсов: 0, доставка: 0 });
    const с = карта.get(месяц);
    с.сумма += п.сумма;
    с.поставок++;
    с.рейсов += п.рейсов;
    с.доставка += п.стоимостьДоставки;
  }
  return [...карта.values()].sort((a, b) => a.месяц.localeCompare(b.месяц));
}

