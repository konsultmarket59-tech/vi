// ---------- очередь бригад по объектам ----------

/**
 * Занятость бригад — интервалами, а не одной датой «свободна с».
 *
 * Разница принципиальная и вылезла на первом же расчёте улицы из пяти домов.
 * Бригада земляных работ копает котлован в начале стройки и делает
 * благоустройство в конце — между этими этапами у неё три месяца свободных.
 * Если помнить только «когда освободится совсем», то второй дом улицы нельзя
 * начать, пока не сдан первый: пять домов растягиваются на два года вместо
 * одного сезона. С интервалами соседние дома встают в свободные окна — как это
 * и происходит на настоящей улице.
 *
 * `штук` — сколько бригад такого вида в компании: две бригады каменщиков
 * работают на двух домах одновременно, и третий дом ждёт.
 */
class Ресурсы {
  constructor(штукПоБригадам = {}) {
    this.штук = штукПоБригадам;
    this.занято = new Map();
  }

  окна(бригада) {
    return this.занято.get(бригада) || [];
  }

  самоеРаннее(бригада, желаемое, смен, режим) {
    const штук = Math.max(1, Number(this.штук[бригада]) || 1);
    let старт = желаемое;
    // Предел на случай, когда окно не находится: лучше вернуть последнюю
    // пробу, чем крутиться вечно на кривых данных.
    for (let попытка = 0; попытка < 300; попытка++) {
      const конец = schedule.плюсСмен(старт, смен, режим);
      const пересечения = this.окна(бригада).filter((и) => и.начало <= конец && и.конец >= старт);
      if (пересечения.length < штук) return старт;
      // Прыгаем к ближайшему освобождению: оно снимает хотя бы одно пересечение.
      const ближайший = пересечения.map((и) => и.конец).sort()[0];
      старт = schedule.следующийРабочий(плюсДней(ближайший, 1), режим);
    }
    return старт;
  }

  занять(бригада, начало, конец) {
    if (!this.занято.has(бригада)) this.занято.set(бригада, []);
    this.занято.get(бригада).push({ начало, конец });
  }
}

/**
 * Строит графики всех домов подряд, передавая занятость бригад дальше.
 *
 * Порядок домов — не алфавитный: первым считается тот, у кого раньше договорной
 * срок сдачи. Иначе очередь бригад раздаётся случайно, и дом со сроком в мае
 * ждёт, пока освободится бригада с дома, который сдавать в сентябре.
 *
 * Жадный порядок, а не полный перебор: домов в посёлке десятки, вариантов
 * очереди — факториал, а руководителю нужен план сегодня. Модель потом
 * посмотрит на результат и скажет, что переставить.
 */
function распределитьБригады(дома, { режим = "6/1", бригадНаЭтап = {}, начало } = {}) {
  const порядок = [...дома].sort((a, b) => {
    const сa = a.датаСдачи || "9999-12-31";
    const сb = b.датаСдачи || "9999-12-31";
    if (сa !== сb) return сa.localeCompare(сb);
    return (a.датаНачала || "").localeCompare(b.датаНачала || "");
  });

  const штук = { ...Object.fromEntries(schedule.БРИГАДЫ.map((б) => [б.id, б.штук])), ...бригадНаЭтап };
  const ресурс = new Ресурсы(штук);
  const графики = [];
  const очередь = [];

  for (const дом of порядок) {
    const стартДома = дом.датаНачала || начало || строкаДаты(new Date());
    const график = schedule.построить(дом.этапы, { начало: стартДома, режим, ресурс });
    графики.push({ дом, график });

    for (const этап of график.этапы) {
      if (!этап.бригада) continue;
      очередь.push({
        бригада: этап.бригада,
        дом: `${дом.улица} ${дом.номер}`.trim(),
        домКлюч: дом.ключ,
        этап: этап.id,
        начало: этап.начало,
        конец: этап.конец,
        смен: этап.смен,
        ждала: этап.ограничитель.includes("занята") ? этап.ограничитель : "",
      });
    }
  }

  // Просрочка договора — то, ради чего вообще строится сводный план.
  const срыв = графики
    .filter(({ дом, график }) => дом.датаСдачи && график.сдача > дом.датаСдачи)
    .map(({ дом, график }) => ({
      дом: `${дом.улица} ${дом.номер}`.trim(),
      договор: дом.датаСдачи,
      получается: график.сдача,
      опоздание: Math.round((дата(график.сдача) - дата(дом.датаСдачи)) / 86400000),
    }));

  return {
    графики,
    очередь: очередь.sort((a, b) => a.начало.localeCompare(b.начало)),
    занятость: Object.fromEntries([...ресурс.занято].map(([б, окна]) => [б, окна])),
    штук,
    срыв,
    ожидание: очередь.filter((о) => о.ждала).length,
    загрузка: загрузкаБригад(очередь),
  };
}

/**
 * Загрузка бригады по месяцам — сколько смен занято.
 *
 * Считается в сменах, а не в «процентах занятости»: процент требует нормы
 * рабочих дней в месяце, а она у каждого своя (5/2, 6/1, вахта), и спор о
 * знаменателе съедает разговор о самой загрузке.
 */
function загрузкаБригад(очередь) {
  const карта = new Map();
  for (const запись of очередь) {
    const месяц = запись.начало.slice(0, 7);
    const ключ = `${запись.бригада}|${месяц}`;
    if (!карта.has(ключ)) карта.set(ключ, { бригада: запись.бригада, месяц, смен: 0, объектов: new Set() });
    const строка = карта.get(ключ);
    строка.смен += запись.смен;
    строка.объектов.add(запись.дом);
  }
  return [...карта.values()]
    .map((с) => ({ ...с, объектов: с.объектов.size }))
    .sort((a, b) => a.месяц.localeCompare(b.месяц) || a.бригада.localeCompare(b.бригада));
}

