// Сводный план посёлка: бригады по объектам и поставки по улицам.
//
// Дом, посчитанный отдельно, — это ещё не план. Посёлок строится улицами, и
// главные деньги теряются не внутри дома, а между домами:
//
//  — БРИГАДА ОДНА НА ПЯТЬ ДОМОВ. График каждого дома в отдельности показывает
//    красивый срок, а в сумме одна бригада каменщиков стоит в очереди на пяти
//    объектах, и сроки, обещанные заказчикам, не выполняются все сразу.
//  — МАШИНА ЕДЕТ ПОЛУПУСТОЙ. Пять домов на одной улице заказывают блоки в
//    разные дни — пять рейсов вместо двух. Доставка при этом платится за рейс,
//    а не за тонну.
//  — РАСПУТИЦА. С апреля по май на региональных дорогах вводят весенние
//    ограничения нагрузки на ось. Тяжёлое (бетон, блоки, арматура, песок)
//    в этот период либо не везут, либо везут вдвое дороже полупустыми машинами.
//    Это не редкий случай — это каждый год, и на него планируют заранее.
//  — ХРАНИТЬ НЕГДЕ. Завезти всё сразу нельзя: на участке нет склада, материал
//    мокнет, бьётся и пропадает. Поэтому у поставки есть не только «не позже»,
//    но и «не раньше».
//
// Что здесь делает код, а что модель. Код строит выполнимый план: очередь
// бригад, даты поставок, объединение рейсов, проверка ограничений — всё это
// арифметика и правила, их можно проверить и защитить. Модель (см. agent.cjs)
// смотрит на ГОТОВЫЙ план и предлагает, что переставить: она видит смысл,
// которого нет в правилах, — но ни одной даты не двигает сама.

const { id } = require("./common.cjs");
