/** Ищет в папке шаблон под этот вид документа. */
async function найтиШаблоны(папка) {
  if (!папка) return [];
  let файлы = [];
  try {
    файлы = await fs.readdir(папка, { withFileTypes: true });
  } catch {
    return [];
  }
  return файлы
    .filter((ф) => ф.isFile() && /\.(docx|xlsx)$/i.test(ф.name) && !ф.name.startsWith("~$"))
    .map((ф) => {
      const вид = ДОКУМЕНТЫ.find((д) => д.шаблонИмя.test(ф.name));
      return { имя: ф.name, путь: path.join(папка, ф.name), вид: вид?.id || "", расширение: path.extname(ф.name).toLowerCase() };
    });
}

/**
 * Сборка комплекта.
 *
 * На каждую приёмку скрытых работ — свой акт, на дом — журнал и реестр, на
 * период — КС-2 и КС-3. То, для чего в папке шаблонов нет формы, собирается
 * встроенной; в реестре видно, что откуда взялось.
 */
async function собрать(контекст, { шаблоныПапка, кудаПапка, только = null } = {}) {
  const шаблоны = await найтиШаблоны(шаблоныПапка);
  const созданные = [];
  const пропущено = [];
  const { дом, приёмки = [], смета } = контекст;
  const базовые = метки(контекст);
  const имяДома = `${дом?.улица || ""} ${дом?.номер || ""}`.trim().replace(/[\\/:*?"<>|]/g, "-") || "дом";

  async function один(видId, приёмка, суффикс, строки) {
    if (только && !только.includes(видId)) return;
    const вид = ДОКУМЕНТЫ.find((д) => д.id === видId);
    const шаблон = шаблоны.find((ш) => ш.вид === видId);
    const значения = { ...базовые, ...метки({ ...контекст, приёмка }) };
    const имяФайла = `${вид.название.slice(0, 40)} — ${имяДома}${суффикс ? ` — ${суффикс}` : ""}`.replace(/[\\/:*?"<>|]/g, "-");
    try {
      let итог;
      if (шаблон?.расширение === ".docx") {
        итог = await заполнитьDocx(шаблон.путь, значения, path.join(кудаПапка, `${имяФайла}.docx`));
      } else if (шаблон?.расширение === ".xlsx") {
        итог = await заполнитьXlsx(шаблон.путь, значения, строки, path.join(кудаПапка, `${имяФайла}.xlsx`));
      } else {
        итог = await собратьВстроенный(видId, { ...контекст, приёмка }, path.join(кудаПапка, `${имяФайла}.docx`), строки || []);
      }
      созданные.push({
        вид: видId,
        название: вид.название,
        файл: итог.файл,
        источник: шаблон ? `шаблон «${шаблон.имя}»` : "встроенная форма",
        незаполненные: итог.незаполненные,
        приёмка: приёмка?.id || "",
        дата: приёмка?.дата || ныне().slice(0, 10),
      });
    } catch (e) {
      пропущено.push({ вид: видId, причина: e.message });
    }
  }

  for (const приёмка of приёмки.filter((п) => п.вид === "скрытые работы")) {
    await один("аоср", приёмка, `${приёмка.этап} — ${приёмка.работа}`.slice(0, 50));
  }
  await один("журнал", null, "");
  if (смета) {
    const кс2 = require("./estimate.cjs").данныеКС2(смета, { период: контекст.период });
    await один("кс2", null, контекст.период || "", кс2.строки);
    await один("кс3", null, контекст.период || "", кс2.строки);
  }

  const реестр = await собратьРеестр(созданные, контекст, path.join(кудаПапка, `Реестр исполнительной документации — ${имяДома}.xlsx`));
  созданные.push(реестр);

  return {
    созданные,
    пропущено,
    папка: кудаПапка,
    шаблоновНайдено: шаблоны.filter((ш) => ш.вид).length,
    // Незаполненные метки — единственное, из-за чего комплект придётся
    // доделывать руками, и человек должен увидеть это списком, а не открывая
    // каждый файл.
    требуютВнимания: созданные.filter((с) => с.незаполненные?.length).map((с) => ({ файл: path.basename(с.файл), метки: с.незаполненные })),
  };
}

/** Реестр: опись комплекта одной таблицей. */
async function собратьРеестр(документы, контекст, кудаФайл) {
  const ExcelJS = require("exceljs");
  const книга = new ExcelJS.Workbook();
  const лист = книга.addWorksheet("Реестр ИД");
  лист.columns = [
    { header: "№", key: "n", width: 6 },
    { header: "Наименование документа", key: "название", width: 52 },
    { header: "Дата", key: "дата", width: 14 },
    { header: "Основание формы", key: "основание", width: 28 },
    { header: "Файл", key: "файл", width: 46 },
    { header: "Откуда форма", key: "источник", width: 24 },
  ];
  лист.getRow(1).font = { bold: true };
  документы.forEach((д, i) => {
    лист.addRow({
      n: i + 1,
      название: д.название,
      дата: д.дата,
      основание: ДОКУМЕНТЫ.find((x) => x.id === д.вид)?.основание || "",
      файл: path.basename(д.файл),
      источник: д.источник,
    });
  });
  лист.addRow({});
  лист.addRow({ название: `Объект: ${метки(контекст)["объект"]}` });
  лист.addRow({ название: `Реестр сформирован ${форматДаты(ныне().slice(0, 10))}` });

  await fs.mkdir(path.dirname(кудаФайл), { recursive: true });
  await книга.xlsx.writeFile(кудаФайл);
  return { вид: "реестр", название: "Реестр исполнительной документации", файл: кудаФайл, источник: "встроенная форма", незаполненные: [], дата: ныне().slice(0, 10) };
}

