// собирают. К моменту сдачи оказывается, что актов на скрытые работы нет,
// потому что арматуру забетонировали в апреле, а вспомнили о ней в ноябре.
// Вскрывать конструкцию уже нельзя, и остаётся переписывать даты, что все и
// делают.
//
// Программа не может подписать акт за человека, но может убрать ту часть, из-за
// которой это откладывается: заполнение. Все данные для акта уже есть — дом,
// проект, этапы, объёмы, даты приёмок, материалы из сметы. Остаётся положить их
// в форму.
//
// О формах. Формы у каждой компании свои: где-то по РД-11-02-2006, где-то с
// логотипом и своими полями, у заказчика-застройщика — третьи. Поэтому
// программа не навязывает свои: она берёт ШАБЛОНЫ ИЗ ПАПКИ, на которую указал
// руководитель, и подставляет в них значения по меткам {{...}}. И только если
// шаблона для какого-то документа в папке нет, собирает документ сама — чтобы
// комплект не оказался неполным из-за отсутствующего файла.
//
// Метки в шаблоне Word — отдельная сложность, о которой стоит знать заранее:
// Word режет текст на куски (run) по любой правке форматирования, и метка
// {{дата}}, набранная в один присест, в файле лежит как «{{да», «т», «а}}».
// Поиск по подстроке её не находит. Поэтому перед подстановкой куски внутри
// абзаца склеиваются.

