/** Метки, доступные в любом шаблоне. */
function метки(контекст) {
  const { дом, посёлок, компания, приёмка, смета, период } = контекст;
  const сегодня = ныне().slice(0, 10);
  return {
    "дата": форматДаты(приёмка?.дата || сегодня),
    "дата.сегодня": форматДаты(сегодня),
    "объект": `${посёлок?.название || ""}, ${дом?.улица || ""} ${дом?.номер || ""}`.trim(),
    "адрес": `${посёлок?.адрес || ""}, ${дом?.улица || ""} ${дом?.номер || ""}`.replace(/^, /, "").trim(),
    "дом": `${дом?.улица || ""} ${дом?.номер || ""}`.trim(),
    "посёлок": посёлок?.название || "",
    "кадастровый": дом?.кадастровый || "",
    "площадь": String(дом?.площадь || ""),
    "заказчик": дом?.заказчик?.имя || "",
    "договор": дом?.заказчик?.договор || "",
    "подрядчик": компания?.название || "",
    "подрядчик.инн": компания?.инн || "",
    "подрядчик.адрес": компания?.адрес || "",
    "руководитель": компания?.руководитель || "",
    "прораб": дом?.прораб || "",
    "проект": дом?.проектНазвание || "",
    "проект.путь": дом?.проектПуть || "",
    "этап": приёмка?.этап || "",
    "работы": приёмка?.работа || "",
    "документ": приёмка?.документ || "",
    "период": период || "",
    "смета.итого": смета ? рубли(смета.итог?.заказчику || 0) : "",
    "смета.факт": смета ? рубли(смета.итог?.факт || 0) : "",
  };
}

function форматДаты(iso) {
  const [г, м, д] = String(iso).slice(0, 10).split("-");
  const месяцы = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];
  return г ? `«${д}» ${месяцы[Number(м) - 1] || м} ${г} г.` : String(iso);
}

function рубли(n) {
  return `${Number(n || 0).toLocaleString("ru-RU")} ₽`;
}

/**
 * Подстановка меток в .docx.
 *
 * Порядок действий именно такой: сначала склеить куски внутри абзаца, потом
 * искать метки. Обратный порядок не находит ничего, кроме меток, которым
 * повезло не попасть на границу форматирования.
 */
async function заполнитьDocx(шаблон, значения, кудаФайл) {
  const JSZip = require("jszip");
  const zip = await JSZip.loadAsync(await fs.readFile(шаблон));
  const цель = zip.file("word/document.xml");
  if (!цель) throw new Error("Это не документ Word: внутри нет word/document.xml");
  let xml = await цель.async("string");

  xml = склеитьАбзацы(xml);
  for (const [ключ, значение] of Object.entries(значения)) {
    xml = xml.split(`{{${ключ}}}`).join(экранироватьXml(String(значение ?? "")));
  }
  // Незаполненные метки не оставляем в документе: «{{подрядчик.инн}}» в акте,
  // который ушёл заказчику, выглядит хуже пустого места.
  const осталось = [...xml.matchAll(/\{\{([^}]{1,60})\}\}/g)].map((m) => m[1]);
  xml = xml.replace(/\{\{[^}]{1,60}\}\}/g, "");

  zip.file("word/document.xml", xml);
  await fs.mkdir(path.dirname(кудаФайл), { recursive: true });
  await fs.writeFile(кудаФайл, await zip.generateAsync({ type: "nodebuffer" }));
  return { файл: кудаФайл, незаполненные: [...new Set(осталось)] };
}

/**
 * Склейка кусков текста внутри абзаца.
 *
 * Внутри <w:p> собираем весь текст из <w:t>, кладём его в первый кусок,
 * остальные опустошаем. Форматирование первого куска при этом распространяется
 * на весь абзац — для служебной строки акта это допустимо, а вот для абзаца, в
 * котором есть метки, других вариантов нет. Абзацы без меток не трогаем вообще,
 * поэтому оформление шаблона в целом сохраняется.
 */
function склеитьАбзацы(xml) {
  return xml.replace(/<w:p[ >][\s\S]*?<\/w:p>/g, (абзац) => {
    if (!абзац.includes("{{") && !/\{\s*\{/.test(абзац.replace(/<[^>]+>/g, ""))) return абзац;
    const тексты = [...абзац.matchAll(/<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>/g)];
    if (тексты.length < 2) return абзац;
    const весь = тексты.map((t) => t[1]).join("");
    if (!весь.includes("{{")) return абзац;
    let первый = true;
    return абзац.replace(/(<w:t(?:\s[^>]*)?>)([\s\S]*?)(<\/w:t>)/g, (_, откр, __, закр) => {
      if (первый) {
        первый = false;
        // xml:space="preserve" обязателен: без него Word съедает пробелы по
        // краям склеенной строки, и «Объект: Липовая 2» становится «Объект:Липовая 2».
        const сПробелом = откр.includes("xml:space") ? откр : откр.replace(/>$/, ' xml:space="preserve">');
        return `${сПробелом}${весь}${закр}`;
      }
      return `${откр}${закр}`;
    });
  });
}

function экранироватьXml(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/**
 * Подстановка меток в .xlsx — формы КС-2 и КС-3 обычно ведут в Excel.
 * Таблица строк (позиции акта) разворачивается по метке {{строки}}: строка с
 * этой меткой размножается по количеству позиций.
 */
async function заполнитьXlsx(шаблон, значения, строки, кудаФайл) {
  const ExcelJS = require("exceljs");
  const книга = new ExcelJS.Workbook();
  await книга.xlsx.readFile(шаблон);
  const незаполненные = new Set();

  книга.eachSheet((лист) => {
    let строкаШаблона = null;
    лист.eachRow((строка) => {
      строка.eachCell({ includeEmpty: false }, (ячейка) => {
        const текст = typeof ячейка.value === "string" ? ячейка.value : ячейка.value?.richText?.map((r) => r.text).join("") || "";
        if (!текст.includes("{{")) return;
        if (текст.includes("{{строки}}")) {
          строкаШаблона = строка.number;
          return;
        }
        let новый = текст;
        for (const [ключ, значение] of Object.entries(значения)) {
          новый = новый.split(`{{${ключ}}}`).join(String(значение ?? ""));
        }
        for (const m of новый.matchAll(/\{\{([^}]{1,60})\}\}/g)) незаполненные.add(m[1]);
        ячейка.value = новый.replace(/\{\{[^}]{1,60}\}\}/g, "");
      });
    });

    if (строкаШаблона && строки?.length) {
      лист.spliceRows(строкаШаблона, 1);
      строки.forEach((с, i) => {
        лист.insertRow(строкаШаблона + i, [
          с.номер, с.позиция, с.наименование, с.единица, с.количество, с.цена, с.сумма,
        ]);
      });
    }
  });

  await fs.mkdir(path.dirname(кудаФайл), { recursive: true });
  await книга.xlsx.writeFile(кудаФайл);
  return { файл: кудаФайл, незаполненные: [...незаполненные] };
}

