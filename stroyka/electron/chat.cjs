// Чат стройки: отчёты с объекта, отклонения и уведомления по ролям.
//
// Прораб отчитывается так, как ему удобно: пишет пару фраз и прикладывает
// фотографии. Всё остальное — работа программы, и она устроена по одному
// принципу: НИЧЕГО НЕ ПРИМЕНЯЕТСЯ МОЛЧА.
//
// Разбор отчёта агентом даёт предложение: этап такой-то, готовность такая-то,
// отклонение такое-то. Предложение лежит рядом с сообщением, пока руководитель
// его не принял. Причина простая: готовность этапа двигает график, график
// двигает поставки, поставки двигают деньги. Цепочка, запущенная тем, что
// модель неправильно поняла фразу «закончили первый этаж», обходится дороже,
// чем одно нажатие кнопки.
//
// Фотографии в программу не копируются — хранится путь. Папку с фото прораб
// синхронизирует как ему удобно (сетевая папка, облачный диск, флешка); задача
// программы — знать, где смотреть, и уметь показать.

const { id, ныне } = require("./workspace.cjs");
const { адресаты, роль } = require("./roles.cjs");

function пусто() {
  return { сообщения: [], отклонения: [], уведомления: [] };
}

/**
 * Сообщение с объекта. `фото` — массив путей к файлам, а не сами файлы.
 */
function добавитьСообщение(чат, { текст, автор, рольАвтора, фото = [], этап = "", дата = "" }) {
  const сообщение = {
    id: id(),
    когда: ныне(),
    дата: дата || ныне().slice(0, 10),
    автор: автор || "",
    роль: рольАвтора || "",
    текст: String(текст || ""),
    фото: фото.filter(Boolean),
    этап,
    разбор: null,
    разборПринят: false,
  };
  чат.сообщения.unshift(сообщение);
  return сообщение;
}

/** Ответ агента складывается рядом с сообщением, но ничего ещё не меняет. */
function приложитьРазбор(чат, idСообщения, разбор) {
  const сообщение = чат.сообщения.find((с) => с.id === idСообщения);
  if (!сообщение) throw new Error("Сообщение не найдено");
  сообщение.разбор = { ...разбор, когда: ныне() };
  return сообщение;
}

/**
 * Принятие разбора: вот здесь предложение становится фактом.
 *
 * Возвращает не только обновлённый чат, но и то, что должно случиться дальше:
 * какую готовность проставить этапу и какие отклонения завести. Применяет их
 * вызывающая сторона — чат не лезет в график сам, иначе получится модуль,
 * который меняет всё подряд и в котором невозможно разобраться.
 */
function принятьРазбор(чат, idСообщения, кто, рольКто, правки = {}) {
  const сообщение = чат.сообщения.find((с) => с.id === idСообщения);
  if (!сообщение) throw new Error("Сообщение не найдено");
  if (!сообщение.разбор) throw new Error("Разбора нет — сначала разберите отчёт");

  const этап = правки.этап ?? сообщение.разбор.этап;
  const готовность = правки.готовность ?? сообщение.разбор.готовность;
  const принятые = (правки.отклонения ?? сообщение.разбор.отклонения ?? []).filter(Boolean);

  const заведённые = принятые.map((о) => {
    const отклонение = {
      id: id(),
      когда: ныне(),
      дата: сообщение.дата,
      вид: о.вид,
      суть: о.суть,
      насколько: о.насколько || "",
      обоснование: о.обоснование || "",
      этап,
      сообщение: сообщение.id,
      кому: адресаты(о.вид),
      статус: "открыто",
      принял: кто,
    };
    чат.отклонения.unshift(отклонение);
    // Уведомление — на каждую роль отдельно: «отправить всем» превращается в
    // ленту, которую перестают читать через неделю.
    for (const комуРоль of отклонение.кому) {
      чат.уведомления.unshift({
        id: id(),
        когда: ныне(),
        роль: комуРоль,
        отклонение: отклонение.id,
        заголовок: `${о.вид}: ${о.суть}`,
        текст: `${этап || "этап не определён"} · ${о.насколько || ""} ${о.обоснование || ""}`.trim(),
        прочитано: false,
      });
    }
    return отклонение;
  });

  сообщение.разборПринят = true;
  сообщение.этап = этап || сообщение.этап;
  сообщение.принял = кто;
  сообщение.рольПринявшего = рольКто;

  return {
    сообщение,
    отклонения: заведённые,
    // Что вызывающая сторона должна применить к графику.
    кГрафику: этап && готовность != null ? { этап, готовность } : null,
  };
}

function закрытьОтклонение(чат, idОтклонения, кто, рольКто, комментарий = "") {
  const о = чат.отклонения.find((x) => x.id === idОтклонения);
  if (!о) throw new Error("Отклонение не найдено");
  о.статус = "закрыто";
  о.закрыл = кто;
  о.рольЗакрывшего = рольКто;
  о.комментарий = комментарий;
  о.закрыто = ныне();
  for (const у of чат.уведомления) if (у.отклонение === idОтклонения) у.прочитано = true;
  return о;
}

/** Уведомления для роли: сначала непрочитанные, потом остальные. */
function уведомления(чат, рольId, { только = "все" } = {}) {
  const список = (чат.уведомления || []).filter((у) => у.роль === рольId);
  const отфильтрованные = только === "новые" ? список.filter((у) => !у.прочитано) : список;
  return отфильтрованные.sort((a, b) => Number(a.прочитано) - Number(b.прочитано) || b.когда.localeCompare(a.когда));
}

function прочитать(чат, idУведомления) {
  const у = чат.уведомления.find((x) => x.id === idУведомления);
  if (у) у.прочитано = true;
  return у;
}

/**
 * Что показать роли в ленте.
 *
 * Заказчик видит только то, что ему адресовано: отчёты, которые одобрил
 * руководитель. Внутреннюю переписку прорабов и разборы агента он не видит —
 * не потому, что там тайна, а потому, что «стяжка вышла на 25 м² больше» без
 * объяснения читается как «нас обманывают».
 */
function лентаДляРоли(чат, рольId) {
  if (рольId === "заказчик") {
    return {
      сообщения: (чат.сообщения || []).filter((с) => с.дляЗаказчика),
      отклонения: [],
      уведомления: [],
    };
  }
  return {
    сообщения: чат.сообщения || [],
    отклонения: (чат.отклонения || []).filter((о) => о.статус === "открыто" || роль(рольId).действия.includes("видетьВсеОбъекты")),
    уведомления: уведомления(чат, рольId),
  };
}

/**
 * Сводка отклонений по дому — то, что видно на карточке и на карте.
 * Открытых отклонений на критическом пути — единственная цифра, которую
 * руководитель смотрит каждый день.
 */
function сводкаОтклонений(чат, график) {
  const открытые = (чат.отклонения || []).filter((о) => о.статус === "открыто");
  const критические = new Set((график?.критический || []));
  return {
    открытых: открытые.length,
    наКритическом: открытые.filter((о) => критические.has(о.этап)).length,
    поВидам: открытые.reduce((acc, о) => {
      acc[о.вид] = (acc[о.вид] || 0) + 1;
      return acc;
    }, {}),
    последнее: открытые[0] || null,
  };
}

/**
 * Отчёт клиенту. Живёт со статусом, потому что путь у него всегда один:
 * агент подготовил → руководитель посмотрел, поправил, одобрил → ушло в чат
 * заказчику. Пропустить середину нельзя: неодобренный отчёт нельзя отправить,
 * и это проверяется здесь, а не в интерфейсе.
 */
function создатьОтчёт(чат, { период, текст, автор, дом, фото = [] }) {
  const отчёт = {
    id: id(),
    когда: ныне(),
    период,
    дом,
    текст,
    фото,
    статус: "черновик",
    автор,
    правил: "",
    одобрил: "",
    отправлен: "",
    файл: "",
  };
  чат.отчёты = чат.отчёты || [];
  чат.отчёты.unshift(отчёт);
  return отчёт;
}

function правитьОтчёт(чат, idОтчёта, текст, кто) {
  const о = (чат.отчёты || []).find((x) => x.id === idОтчёта);
  if (!о) throw new Error("Отчёт не найден");
  if (о.отправлен) throw new Error("Отчёт уже отправлен заказчику — правьте следующий, а не отправленный.");
  о.текст = текст;
  о.правил = кто;
  о.статус = "правится";
  return о;
}

function одобритьОтчёт(чат, idОтчёта, кто, рольКто) {
  if (!require("./roles.cjs").можно(рольКто, "одобритьОтчётКлиенту")) {
    throw new Error(`Роль «${роль(рольКто).название}» не одобряет отчёты клиентам.`);
  }
  const о = (чат.отчёты || []).find((x) => x.id === idОтчёта);
  if (!о) throw new Error("Отчёт не найден");
  о.статус = "одобрен";
  о.одобрил = кто;
  о.одобрен = ныне();
  return о;
}

function отправитьОтчёт(чат, idОтчёта, кто, рольКто, файл = "") {
  const о = (чат.отчёты || []).find((x) => x.id === idОтчёта);
  if (!о) throw new Error("Отчёт не найден");
  if (о.статус !== "одобрен") throw new Error("Отчёт не одобрен: отправлять неодобренный отчёт заказчику нельзя.");
  if (!require("./roles.cjs").можно(рольКто, "отправитьОтчётКлиенту")) {
    throw new Error(`Роль «${роль(рольКто).название}» не отправляет отчёты клиентам.`);
  }
  о.статус = "отправлен";
  о.отправлен = ныне();
  о.отправил = кто;
  о.файл = файл;
  // Отправленный отчёт появляется в ленте заказчика — это единственное, что он
  // в этой ленте видит.
  добавитьСообщение(чат, {
    текст: о.текст,
    автор: кто,
    рольАвтора: рольКто,
    фото: о.фото,
  }).дляЗаказчика = true;
  return о;
}

module.exports = {
  пусто, добавитьСообщение, приложитьРазбор, принятьРазбор, закрытьОтклонение,
  уведомления, прочитать, лентаДляРоли, сводкаОтклонений,
  создатьОтчёт, правитьОтчёт, одобритьОтчёт, отправитьОтчёт,
};
