/**
 * Отчёт заказчику. Здесь модель пишет текст, а не считает: все цифры —
 * готовые, из графика и сметы. Отчёт всегда уходит руководителю на одобрение,
 * поэтому в нём не должно быть ничего, что руководителю пришлось бы вычищать:
 * ни обещаний, ни оценок вины, ни новых сроков.
 */
function промптОтчётаКлиенту({ дом, заказчик, период, график, факты, отклонения, фото }) {
  return {
    system: `${ОБЩЕЕ}
Ты пишешь отчёт заказчику частного дома о ходе строительства за период.
Пишешь спокойно и по делу: что сделано, что идёт сейчас, что дальше. Заказчик не строитель — избегай жаргона, но не упрощай до детского языка.
Правила: никаких новых обещаний и дат, которых нет во входных данных. Про отставание пиши прямо, но без оправданий и без поиска виноватых. Никаких оценок стоимости, если её нет во входных данных.`,
    user: `Дом: ${дом}
Заказчик: ${заказчик || "не указан"}
Период: ${период}

ЭТАПЫ:
${график.map((э) => `${э.id}: план ${э.начало}…${э.конец}, готовность ${э.готовность}%, ${э.статус}${э.отставание > 0 ? `, отставание ${э.отставание} дн.` : ""}`).join("\n")}

ЧТО СДЕЛАНО ЗА ПЕРИОД:
${факты.join("\n") || "нет записей"}

ОТКЛОНЕНИЯ:
${отклонения.length ? отклонения.map((о) => `${о.вид}: ${о.суть}`).join("\n") : "нет"}

Фотографий приложено: ${фото}

Верни отчёт в разметке Markdown: заголовок, «Что сделано», «Что идёт сейчас», «Что дальше», и, если есть отклонения, раздел «На что обратить внимание». Без JSON, без пояснений вокруг.`,
  };
}

