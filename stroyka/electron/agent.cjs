/**
 * Разбор готового плана поставок.
 *
 * Модели даётся УЖЕ ПОСТРОЕННЫЙ план и ограничения, по которым он построен.
 * Она не строит план заново — она ищет то, что правила не заметили: соседние
 * поставки, которые стоило бы свести в один рейс; материал, который дешевле
 * взять до сезонного роста цен; поставку, из-за которой встанет бригада.
 */
function промптЛогистики({ поставки, очередь, посёлок, ограничения }) {
  const строки = поставки.slice(0, 120).map((п) =>
    [
      п.дата,
      п.улица,
      п.наименование,
      `${п.количество} ${п.единица}`,
      `${п.домов} дом(ов)`,
      `${п.рейсов} рейс ${п.транспортНазвание}`,
      `окно ${п.неРаньше}…${п.неПозже}`,
      п.замечания.join(" "),
    ].join(" | ")
  );
  const бригады = очередь.slice(0, 60).map((о) => `${о.начало}…${о.конец} ${о.бригада} · ${о.дом} · ${о.этап}${о.ждала ? " (ждала бригаду)" : ""}`);
  return {
    system: `${ОБЩЕЕ}
Ты разбираешь план поставок посёлка, который уже построен программой по правилам:
— поставка не позже чем за день до старта этапа;
— не раньше предельного срока хранения этого материала на объекте;
— объединяются поставки одной улицы и одного материала, у которых окна пересекаются;
— тяжёлое не возят в весенние ограничения нагрузки на ось.
Твоя задача — найти то, чего правила не видят.`,
    user: `Посёлок: ${посёлок}
Ограничения: ${JSON.stringify(ограничения)}

ПЛАН ПОСТАВОК (дата | улица | материал | количество | домов | рейсы | окно | замечания):
${строки.join("\n")}

ЗАНЯТОСТЬ БРИГАД:
${бригады.join("\n")}

Верни JSON:
\`\`\`json
{
  "предложения": [
    {"вид": "объединить|сдвинуть|разделить|заказать раньше|сменить транспорт",
     "поставки": ["точное название материала и дата из плана"],
     "что": "что сделать одной фразой",
     "зачем": "какая выгода или какой риск снимается",
     "риск": "чем это может обернуться",
     "экономия": "оценка словами или прочерк"}
  ],
  "риски": [{"что": "", "когда": "дата или период", "кого касается": "снабжение|руководитель|прораб"}],
  "вывод": "две-три фразы для планёрки"
}
\`\`\`
Не предлагай того, что уже сделано в плане. Не двигай поставку за пределы её окна.`,
  };
}

function разборЛогистики(текст) {
  const данные = извлечьJson(текст);
  if (!данные) return { ok: false, ошибка: "Модель ответила не разбираемым текстом — попробуйте ещё раз.", предложения: [] };
  return {
    ok: true,
    предложения: Array.isArray(данные.предложения) ? данные.предложения : [],
    риски: Array.isArray(данные.риски) ? данные.риски : [],
    вывод: String(данные.вывод || ""),
  };
}

