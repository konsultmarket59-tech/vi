//
// Граница между кодом и моделью в этой программе проведена жёстко и в одну
// сторону: ЧИСЛА СЧИТАЕТ КОД, СМЫСЛ ЧИТАЕТ МОДЕЛЬ. Смета, объёмы, даты, рейсы,
// лимиты — арифметика и правила, они детерминированы и проверяемы. Модель
// занимается тем, чего в правилах нет:
//
//  — читает фотографию с объекта и говорит, что на ней видно;
//  — сверяет рассказ прораба с этапом графика и называет расхождение;
//  — смотрит на ГОТОВЫЙ план поставок и предлагает, что переставить;
//  — пишет отчёт заказчику человеческим языком.
//
// И ни в одном из этих случаев модель ничего не применяет сама. Она возвращает
// предложение, человек нажимает кнопку. Причина не в осторожности вообще, а в
// конкретной цене ошибки: сдвинутая моделью дата поставки — это простой
// бригады на объекте, а «уточнённый» ею объём в смете — это деньги в акте,
// который кто-то подпишет.
//
// Формат ответа — JSON в блоке ```json. Разбор устроен снисходительно: модель
// регулярно добавляет вежливое предисловие перед блоком, и падать на этом
// нельзя.

/**
 * Достаёт JSON из ответа модели.
 *
 * Три попытки по убыванию строгости: блок ```json, любой блок ```, первая
 * сбалансированная фигурная скобка. Последнее нужно, когда модель ответила
 * голым JSON без разметки — это тоже частый случай.
 */
function извлечьJson(текст) {
  const строка = String(текст || "");
  const блоки = [
    /```json\s*([\s\S]*?)```/i,
    /```\s*([\s\S]*?)```/,
  ];
  for (const шаблон of блоки) {
    const m = шаблон.exec(строка);
    if (m) {
      try {
        return JSON.parse(m[1].trim());
      } catch { /* пробуем следующий способ */ }
    }
  }
  const начало = строка.indexOf("{");
  if (начало >= 0) {
    let глубина = 0;
    let вСтроке = false;
    let экран = false;
    for (let i = начало; i < строка.length; i++) {
      const c = строка[i];
      if (экран) { экран = false; continue; }
      if (c === "\\") { экран = true; continue; }
      if (c === '"') { вСтроке = !вСтроке; continue; }
      if (вСтроке) continue;
      if (c === "{") глубина++;
      else if (c === "}") {
        глубина--;
        if (глубина === 0) {
          try {
            return JSON.parse(строка.slice(начало, i + 1));
          } catch {
            return null;
          }
        }
      }
    }
  }
  return null;
}

