/**
 * Разбор отчёта прораба, в том числе по фотографиям.
 *
 * Главное здесь — не «оценить качество по фото», на что модель не способна и
 * чего от неё нельзя требовать. Задача уже: сверить, что говорит прораб и что
 * видно на фотографии, с тем, какой этап должен идти по графику, и назвать
 * расхождение. Дальше расхождение попадает к людям по ролям, и решают они.
 *
 * Фотографии передаются как изображения; на диске остаются их пути.
 */
function промптОтчёта({ дом, этапы, сообщение, сегодня, фотоОписание }) {
  const план = этапы
    .map((э) => `${э.id}: ${э.начало}…${э.конец}, ${э.статус}, готовность ${э.готовность}%${э.критический ? ", критический путь" : ""}`)
    .join("\n");
  return {
    system: `${ОБЩЕЕ}
Ты разбираешь отчёт прораба с объекта и сверяешь его с графиком работ.
Про фотографии: описывай только то, что действительно видно. Не оценивай прочность, качество бетона или соответствие проекту по фотографии — этого по ней не определить.
Отклонение — это расхождение между отчётом, фотографиями и графиком, а не твоё мнение о стройке.`,
    user: `Дом: ${дом}
Сегодня: ${сегодня}

ГРАФИК:
${план}

ОТЧЁТ ПРОРАБА:
${сообщение}
${фотоОписание ? `\nПрикреплено фотографий: ${фотоОписание}` : "\nФотографий нет."}

Верни JSON:
\`\`\`json
{
  "этап": "название этапа из графика, к которому относится отчёт, или пусто",
  "по фото": "что видно на фотографиях, одна-две фразы; пусто, если фото нет",
  "выполнено": [{"работа": "", "объём": "число с единицей, если названо, иначе прочерк"}],
  "готовность": "число 0-100 или прочерк, если по отчёту не определить",
  "отклонения": [
    {"вид": "срок|качество|объём|материалы|поставка|безопасность|проект|деньги",
     "суть": "одна фраза",
     "насколько": "на сколько дней или на сколько процентов, если понятно",
     "почему так считаешь": "на что именно в отчёте или на фото опираешься"}
  ],
  "вопросы": ["что надо уточнить у прораба"],
  "коротко": "одна фраза для ленты"
}
\`\`\`
Если отчёт совпадает с графиком — верни пустой список отклонений, не выдумывай их.`,
  };
}

function разборОтчёта(текст) {
  const данные = извлечьJson(текст);
  if (!данные) return { ok: false, ошибка: "Не удалось разобрать ответ модели.", отклонения: [] };
  const виды = require("./roles.cjs").ВИДЫ_ОТКЛОНЕНИЙ;
  return {
    ok: true,
    этап: String(данные["этап"] || ""),
    поФото: String(данные["по фото"] || ""),
    выполнено: Array.isArray(данные.выполнено) ? данные.выполнено : [],
    готовность: Number.isFinite(Number(данные.готовность)) ? Number(данные.готовность) : null,
    отклонения: (Array.isArray(данные.отклонения) ? данные.отклонения : [])
      .map((о) => ({
        // Вид приводится к известному: по нему определяются адресаты, и
        // выдуманный моделью вид оставил бы отклонение без получателя.
        вид: виды.includes(о.вид) ? о.вид : "срок",
        суть: String(о.суть || ""),
        насколько: String(о["насколько"] || ""),
        обоснование: String(о["почему так считаешь"] || ""),
      }))
      .filter((о) => о.суть),
    вопросы: Array.isArray(данные.вопросы) ? данные.вопросы.map(String) : [],
    коротко: String(данные.коротко || ""),
  };
}

