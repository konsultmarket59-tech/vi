function разборСпецификации(текст) {
  const данные = извлечьJson(текст);
  if (!данные) return { ok: false, ошибка: "Не удалось разобрать ответ модели.", позиции: [] };
  return {
    ok: true,
    позиции: (Array.isArray(данные.позиции) ? данные.позиции : [])
      .map((п) => ({
        наименование: String(п.наименование || "").trim(),
        единица: String(п.единица || "").trim(),
        количество: Number(п.количество) || 0,
        вид: п.вид === "материал" ? "материал" : "работа",
        этап: String(п.этап || "Прочее"),
        источник: "проект",
      }))
      .filter((п) => п.наименование && п.количество > 0),
    пропущено: Array.isArray(данные.пропущено) ? данные.пропущено : [],
    замечания: Array.isArray(данные.замечания) ? данные.замечания.map(String) : [],
  };
}

