// Снабжение: заявка проходит по порогу одобрения.
//
// Устройство простое и держится на одном решении: ПОРОГ, А НЕ РОЛЬ. Вопрос на
// стройке звучит не «может ли снабженец одобрять заявки», а «до какой суммы».
// Прораб заказывает материал с объекта, до установленного лимита заявку
// закрывает снабженец, выше — она уходит руководителю. Всё, что происходит
// дальше — оплата и поставка, — видно в той же карточке: без этого начинаются
// звонки «а вы оплатили?», на которые уходит день.
//
// Второе решение: заявка НЕ РОЖДАЕТСЯ ИЗ ВОЗДУХА. Она приходит либо из графика
// поставок (тогда в ней уже стоят дата, к которой материал нужен на объекте, и
// дом), либо создаётся руками с объекта. В обоих случаях у неё есть срок
// заказа — дата, позже которой заказывать поздно: срок поставки поставщика
// вычитается из даты, к которой материал нужен.

const { id, ныне } = require("./common.cjs");
const { роль } = require("./roles.cjs");

/** Маршрут заявки. Порядок значим: следующий шаг берётся отсюда. */
const МАРШРУТ = [
  { id: "Заявка", описание: "Создана, ждёт решения" },
  { id: "Одобрение", описание: "Одобрена, ждёт оплаты" },
  { id: "Оплата", описание: "Оплачена, ждёт поставки" },
  { id: "Поставка", описание: "Поставлено на объект" },
];

/** Срок поставки по умолчанию, если поставщик его не указал в прайсе. */
const СРОК_ПОСТАВКИ_ДНЕЙ = 7;

function пусто() {
  return { заявки: [], следующийНомер: 1 };
}

/**
 * Кто должен одобрить заявку на такую сумму.
 *
 * Возвращает роль, а не «да/нет»: карточка обязана прямо говорить, чьего
 * решения ждёт, иначе заявка неделю лежит, и каждый думает, что решает другой.
 */
function ктоОдобряет(сумма, { лимитСнабженца } = {}) {
  const лимит = Number.isFinite(Number(лимитСнабженца)) ? Number(лимитСнабженца) : роль("снабжение").лимитОдобрения;
  return сумма <= лимит
    ? { роль: "снабжение", лимит, поясн: `в пределах лимита снабженца (${лимит.toLocaleString("ru-RU")} ₽)` }
    : { роль: "руководитель", лимит, поясн: `выше лимита снабженца (${лимит.toLocaleString("ru-RU")} ₽) — решает руководитель` };
}

function создать(снабжение, данные, кто, рольКто) {
  const позиции = (данные.позиции || []).map((п) => ({
    наименование: п.наименование || "",
    единица: п.единица || "",
    количество: Number(п.количество) || 0,
    цена: Number(п.цена) || 0,
    сумма: Math.round((Number(п.количество) || 0) * (Number(п.цена) || 0)),
  }));
  const сумма = позиции.reduce((s, п) => s + п.сумма, 0);
  const заявка = {
    id: id(),
    номер: снабжение.следующийНомер || (снабжение.заявки.length + 1),
    дом: данные.дом || "",
    домКлюч: данные.домКлюч || "",
    улица: данные.улица || "",
    наименование: данные.наименование || позиции[0]?.наименование || "Заявка",
    позиции,
    сумма,
    поставщик: данные.поставщик || "",
    нужноКДате: данные.нужноКДате || "",
    срокПоставки: Number(данные.срокПоставки) || СРОК_ПОСТАВКИ_ДНЕЙ,
    // Дата, позже которой заказывать поздно. Считается один раз при создании и
    // хранится: пересчитывать её «на сегодня» нельзя — тогда просроченная
    // заявка каждый день выглядит как свежая.
    заказатьДо: данные.заказатьДо || "",
    основание: данные.основание || "создана руками",
    статус: "Заявка",
    создал: кто,
    рольСоздателя: рольКто,
    создана: ныне(),
    история: [{ когда: ныне(), кто, роль: рольКто, что: "заявка создана", сумма }],
  };
  const кто2 = ктоОдобряет(сумма, данные);
  заявка.ждёт = кто2.роль;
  заявка.поясн = кто2.поясн;
  снабжение.заявки.unshift(заявка);
  снабжение.следующийНомер = заявка.номер + 1;
  return заявка;
}

/**
 * Перевод заявки на следующий шаг.
 *
 * Проверка лимита здесь, а не в интерфейсе: кнопку можно нарисовать любую, а
 * решение о деньгах должно приниматься в одном месте и одинаково — из окна, из
 * пакетной операции, из будущего мобильного клиента.
 */
function продвинуть(снабжение, idЗаявки, шаг, кто, рольКто, детали = {}) {
  const заявка = снабжение.заявки.find((з) => з.id === idЗаявки);
  if (!заявка) throw new Error("Заявка не найдена");

  const текущий = МАРШРУТ.findIndex((м) => м.id === заявка.статус);
  const целевой = МАРШРУТ.findIndex((м) => м.id === шаг);
  if (целевой < 0) throw new Error(`Неизвестный шаг: ${шаг}`);
  if (целевой !== текущий + 1) {
    throw new Error(`Из «${заявка.статус}» нельзя сразу в «${шаг}»: шаги идут по порядку.`);
  }

  if (шаг === "Одобрение") {
    const нужен = ктоОдобряет(заявка.сумма, детали);
    const лимитРоли = роль(рольКто).лимитОдобрения;
    if (заявка.сумма > лимитРоли) {
      throw new Error(
        `Заявка на ${заявка.сумма.toLocaleString("ru-RU")} ₽ выше лимита роли «${роль(рольКто).название}» ` +
          `(${лимитРоли.toLocaleString("ru-RU")} ₽). Одобряет ${роль(нужен.роль).название}.`
      );
    }
  }
  if (шаг === "Оплата" && !require("./roles.cjs").можно(рольКто, "оплатитьЗаявку")) {
    throw new Error(`Роль «${роль(рольКто).название}» не отмечает оплату.`);
  }
  if (шаг === "Поставка" && !require("./roles.cjs").можно(рольКто, "принятьПоставку")) {
    throw new Error(`Роль «${роль(рольКто).название}» не принимает поставку.`);
  }

  заявка.статус = шаг;
  заявка.ждёт = целевой + 1 < МАРШРУТ.length ? МАРШРУТ[целевой + 1].id : "";
  заявка.история.unshift({ когда: ныне(), кто, роль: рольКто, что: шаг.toLowerCase(), ...детали });
  if (шаг === "Поставка") заявка.поставлено = детали.дата || ныне().slice(0, 10);
  return заявка;
}

function отклонить(снабжение, idЗаявки, причина, кто, рольКто) {
  const заявка = снабжение.заявки.find((з) => з.id === idЗаявки);
  if (!заявка) throw new Error("Заявка не найдена");
  заявка.статус = "Отклонена";
  заявка.ждёт = "";
  заявка.причинаОтказа = причина;
  заявка.история.unshift({ когда: ныне(), кто, роль: рольКто, что: "отклонена", причина });
  return заявка;
}

/**
 * Заявки из графика поставок.
 *
 * График говорит, что и когда нужно на объекте; заявка добавляет к этому срок
 * поставщика и превращает «нужно 20 апреля» в «заказать до 13 апреля». Это и
 * есть та работа, которую иначе делают в голове и забывают.
 *
 * Уже созданные заявки не дублируются: сверка идёт по номеру поставки из
 * графика, а не по названию материала.
 */
function изГрафика(снабжение, поставки, { прайс = [], сегодня = ныне().slice(0, 10) } = {}) {
  const созданные = [];
  const уже = new Set(снабжение.заявки.map((з) => з.поставка).filter(Boolean));
  const { плюсДней } = require("./schedule.cjs");

  for (const п of поставки) {
    if (уже.has(п.id)) continue;
    const изПрайса = прайс.find((c) => c.наименование === п.наименование);
    const срок = Number(изПрайса?.срок) || СРОК_ПОСТАВКИ_ДНЕЙ;
    const заказатьДо = плюсДней(п.дата, -срок);
    const заявка = создать(
      снабжение,
      {
        дом: п.домов > 1 ? `${п.улица}: ${п.домов} дом(ов)` : п.дома[0]?.дом || "",
        улица: п.улица,
        наименование: п.наименование,
        позиции: [{ наименование: п.наименование, единица: п.единица, количество: п.количество, цена: п.сумма / (п.количество || 1) }],
        поставщик: изПрайса?.поставщик || "",
        нужноКДате: п.дата,
        срокПоставки: срок,
        заказатьДо,
        основание: `график поставок · ${п.улица}`,
      },
      "график поставок",
      "снабжение"
    );
    заявка.поставка = п.id;
    заявка.дома = п.дома;
    заявка.просрочена = заказатьДо < сегодня;
    созданные.push(заявка);
  }
  return созданные;
}

/**
 * Сводка для экрана: сколько ждёт кого и сколько денег в работе.
 * Просроченные по дате заказа выносятся отдельно — это то, из-за чего встанет
 * бригада, и на экране это должно быть первым, а не строкой в списке.
 */
function сводка(снабжение, сегодня = ныне().slice(0, 10)) {
  const заявки = снабжение.заявки || [];
  const активные = заявки.filter((з) => з.статус !== "Поставка" && з.статус !== "Отклонена");
  return {
    всего: заявки.length,
    активных: активные.length,
    сумма: активные.reduce((s, з) => s + з.сумма, 0),
    ждутРуководителя: активные.filter((з) => з.статус === "Заявка" && з.ждёт === "Одобрение" && ктоОдобряет(з.сумма).роль === "руководитель").length,
    ждутСнабженца: активные.filter((з) => з.статус === "Заявка" && ктоОдобряет(з.сумма).роль === "снабжение").length,
    ждутОплаты: активные.filter((з) => з.статус === "Одобрение").length,
    ждутПоставки: активные.filter((з) => з.статус === "Оплата").length,
    просрочено: активные.filter((з) => з.заказатьДо && з.заказатьДо < сегодня).map((з) => ({
      номер: з.номер,
      наименование: з.наименование,
      заказатьДо: з.заказатьДо,
      нужноКДате: з.нужноКДате,
      опоздание: Math.round((new Date(сегодня) - new Date(з.заказатьДо)) / 86400000),
    })),
  };
}

module.exports = { МАРШРУТ, СРОК_ПОСТАВКИ_ДНЕЙ, пусто, создать, продвинуть, отклонить, изГрафика, сводка, ктоОдобряет };
