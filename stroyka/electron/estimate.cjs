// Смета: план и факт в одной строке, с журналом — кто и когда внёс правку.
//
// Смета на стройке живёт полгода и правится десятки раз. Через месяц после
// сдачи возникает вопрос «откуда взялась эта цифра», и ответ на него нужен не
// в виде памяти прораба, а в виде записи. Поэтому:
//
// 1. ПЛАН И ФАКТ — В ОДНОЙ СТРОКЕ. Не две сметы («плановая» и «исполнительная»),
//    которые расходятся уже на второй неделе, а одна позиция с двумя цифрами.
//    Отклонение тогда видно сразу и не требует сверки двух файлов.
//
// 2. КАЖДАЯ ПРАВКА ПОПАДАЕТ В ЖУРНАЛ. Кто, когда, что было, что стало. Журнал
//    пишется здесь, а не в интерфейсе: правку можно внести и из расчёта, и из
//    отчёта прораба, и руками, а запись должна появиться в любом случае.
//
// 3. СОГЛАСОВАННАЯ СМЕТА ЗАМОРАЖИВАЕТСЯ ВЕРСИЕЙ. Согласование — это точка, на
//    которую потом ссылаются в договоре. Правка после согласования разрешена,
//    но она переводит смету в «есть изменения после согласования», и прежняя
//    версия остаётся целиком.
//
// Деньги считаются в двух видах: закупка (сколько стоит нам) и цена заказчику
// (сколько в договоре). Разницу между ними видит не каждый — см. roles.cjs.

const { id, ныне } = require("./workspace.cjs");
const { срезатьПоРоли } = require("./roles.cjs");

const СТАТУСЫ = ["черновик", "на согласовании", "согласована", "изменена после согласования"];

/** Наценки по умолчанию: работы дороже материалов, потому что это и есть услуга. */
const НАЦЕНКИ = { работы: 0.25, материалы: 0.12 };

function пустаяСмета() {
  return {
    позиции: [],
    статус: "черновик",
    журнал: [],
    версии: [],
    коэффициенты: { регион: "пермский", сложность: "типовой", ...НАЦЕНКИ },
    согласована: "",
    согласовал: "",
  };
}

function запись(смета, кто, роль, что, детали = {}) {
  смета.журнал.unshift({ id: id(), когда: ныне(), кто: кто || "", роль: роль || "", что, ...детали });
  // Журнал не растёт бесконечно: держим последнюю тысячу записей, а версии
  // сметы хранят полное состояние на каждое согласование.
  if (смета.журнал.length > 1000) смета.журнал.length = 1000;
}

/**
 * Позиция со всеми производными числами.
 *
 * Суммы не хранятся, а считаются: хранимая сумма рано или поздно расходится с
 * количеством и ценой (правку внесли, пересчитать забыли), и тогда смета
 * перестаёт сходиться сама с собой.
 */
function развернуть(поз, коэффициенты) {
  const наценка = поз.вид === "работа" ? коэффициенты.работы ?? НАЦЕНКИ.работы : коэффициенты.материалы ?? НАЦЕНКИ.материалы;
  const ценаЗакупки = Number(поз.ценаЗакупки) || 0;
  const ценаЗаказчику = поз.ценаЗаказчику != null && поз.ценаЗаказчику !== ""
    ? Number(поз.ценаЗаказчику)
    : Math.round(ценаЗакупки * (1 + наценка));
  const количество = Number(поз.количество) || 0;
  const факт = поз.количествоФакт === "" || поз.количествоФакт == null ? null : Number(поз.количествоФакт);
  const суммаЗакупки = Math.round(количество * ценаЗакупки);
  const суммаЗаказчику = Math.round(количество * ценаЗаказчику);
  const суммаФакт = факт == null ? null : Math.round(факт * ценаЗаказчику);
  return {
    ...поз,
    ценаЗакупки,
    ценаЗаказчику,
    количество,
    количествоФакт: факт,
    суммаЗакупки,
    суммаЗаказчику,
    суммаФакт,
    // Отклонение — в единицах работы, а не в процентах: прорабу и заказчику
    // «на 25 м² больше» понятнее, чем «+1,1%», а процент считается рядом.
    отклонение: факт == null ? null : Number((факт - количество).toFixed(2)),
    отклонениеПроцент: факт == null || количество === 0 ? null : Number((((факт - количество) / количество) * 100).toFixed(1)),
    маржа: суммаЗаказчику - суммаЗакупки,
  };
}

/** Смета целиком, с итогами. */
function развернутьСмету(смета) {
  const к = { ...НАЦЕНКИ, ...смета.коэффициенты };
  const позиции = (смета.позиции || []).map((п) => развернуть(п, к));
  const итог = позиции.reduce(
    (acc, п) => {
      acc.закупка += п.суммаЗакупки;
      acc.заказчику += п.суммаЗаказчику;
      acc.факт += п.суммаФакт ?? 0;
      acc.маржа += п.маржа;
      if (п.вид === "работа") acc.работы += п.суммаЗаказчику;
      else acc.материалы += п.суммаЗаказчику;
      if (п.количествоФакт != null) acc.сФактом++;
      if (п.ценаЗакупки === 0) acc.безЦены++;
      return acc;
    },
    { закупка: 0, заказчику: 0, факт: 0, маржа: 0, работы: 0, материалы: 0, сФактом: 0, безЦены: 0 }
  );
  return {
    ...смета,
    позиции,
    итог: {
      ...итог,
      позиций: позиции.length,
      рентабельность: итог.заказчику ? Number(((итог.маржа / итог.заказчику) * 100).toFixed(1)) : 0,
    },
  };
}

/**
 * Смета глазами роли: колонки, которых роль не видит, вырезаны на этой стороне.
 *
 * Именно вырезаны: если оставить их и «не показывать», закупочная цена всё
 * равно уедет в окно заказчика вместе с данными и найдётся в первой же
 * выгрузке.
 */
function дляРоли(смета, рольId) {
  const развёрнутая = развернутьСмету(смета);
  const видитДеньгиЗакупки = require("./roles.cjs").роль(рольId).колонки.includes("ценаЗакупки");
  const видитМаржу = require("./roles.cjs").роль(рольId).колонки.includes("маржа");
  const видитЦену = require("./roles.cjs").роль(рольId).колонки.includes("ценаЗаказчику");
  return {
    ...развёрнутая,
    позиции: срезатьПоРоли(развёрнутая.позиции, рольId),
    итог: {
      позиций: развёрнутая.итог.позиций,
      сФактом: развёрнутая.итог.сФактом,
      безЦены: развёрнутая.итог.безЦены,
      ...(видитЦену ? { заказчику: развёрнутая.итог.заказчику, работы: развёрнутая.итог.работы, материалы: развёрнутая.итог.материалы, факт: развёрнутая.итог.факт } : {}),
      ...(видитДеньгиЗакупки ? { закупка: развёрнутая.итог.закупка } : {}),
      ...(видитМаржу ? { маржа: развёрнутая.итог.маржа, рентабельность: развёрнутая.итог.рентабельность } : {}),
    },
    // Журнал видят все: право «не видеть, кто внёс правку» бессмысленно, а
    // видимость журнала — половина доверия к смете.
    журнал: развёрнутая.журнал.slice(0, 200),
  };
}

/** Следующий номер позиции внутри этапа: «2.6» — шестая позиция второго этапа. */
function следующийНомер(позиции, этап) {
  const этапы = [...new Set(позиции.map((п) => п.этап))];
  const номерЭтапа = (этапы.includes(этап) ? этапы.indexOf(этап) : этапы.length) + 1;
  const вЭтапе = позиции.filter((п) => п.этап === этап).length + 1;
  return `${номерЭтапа}.${вЭтапе}`;
}

function добавитьПозицию(смета, данные, кто, роль) {
  const поз = {
    id: id(),
    номер: данные.номер || следующийНомер(смета.позиции, данные.этап || "Прочее"),
    наименование: данные.наименование || "",
    единица: данные.единица || "",
    количество: Number(данные.количество) || 0,
    ценаЗакупки: Number(данные.ценаЗакупки) || 0,
    ценаЗаказчику: данные.ценаЗаказчику ?? "",
    количествоФакт: null,
    вид: данные.вид === "материал" ? "материал" : "работа",
    этап: данные.этап || "Прочее",
    источник: данные.источник || "внесено руками",
    примечание: данные.примечание || "",
  };
  смета.позиции.push(поз);
  запись(смета, кто, роль, "добавлена позиция", { позиция: поз.id, наименование: поз.наименование, стало: поз.количество });
  пометитьИзменение(смета);
  return поз;
}

function правитьПозицию(смета, idПозиции, правка, кто, роль) {
  const поз = смета.позиции.find((п) => п.id === idПозиции);
  if (!поз) throw new Error("Позиция не найдена");
  for (const [ключ, значение] of Object.entries(правка)) {
    if (поз[ключ] === значение) continue;
    запись(смета, кто, роль, `правка «${ключ}»`, {
      позиция: поз.id,
      наименование: поз.наименование,
      поле: ключ,
      было: поз[ключ],
      стало: значение,
    });
    поз[ключ] = значение;
  }
  пометитьИзменение(смета);
  return поз;
}

function удалитьПозицию(смета, idПозиции, кто, роль) {
  const индекс = смета.позиции.findIndex((п) => п.id === idПозиции);
  if (индекс < 0) return;
  const [удалённая] = смета.позиции.splice(индекс, 1);
  запись(смета, кто, роль, "позиция удалена", { позиция: удалённая.id, наименование: удалённая.наименование, было: удалённая.количество });
  пометитьИзменение(смета);
}

/**
 * Фактический объём.
 *
 * Отдельная операция, а не правка поля: факт вносит прораб по выполненной
 * работе, и в журнале это должно читаться как «принято по факту», а не как
 * «кто-то поменял цифру в смете».
 */
function внестиФакт(смета, idПозиции, количество, кто, роль, основание = "") {
  const поз = смета.позиции.find((п) => п.id === idПозиции);
  if (!поз) throw new Error("Позиция не найдена");
  const было = поз.количествоФакт;
  поз.количествоФакт = количество === "" || количество == null ? null : Number(количество);
  запись(смета, кто, роль, "принято по факту", {
    позиция: поз.id,
    наименование: поз.наименование,
    было,
    стало: поз.количествоФакт,
    основание,
  });
  return поз;
}

/**
 * Перенос расчёта в смету — тот самый явный шаг.
 *
 * Пока его не сделали, расчёт лежит отдельным документом и в смете нет ни
 * строки. Здесь же расчёт получает отметку, из какого он вида работ и с
 * какими параметрами: через месяц по позиции «Кладка стен 34,8 м³» видно, что
 * это стена 42 × 3,2 м толщиной 300 мм, а не «просто цифра».
 */
function применитьРасчёт(смета, расчёт, кто, роль) {
  const добавленные = [];
  const описаниеПараметров = Object.entries(расчёт.параметры || {})
    .map(([к, з]) => `${к} ${з}`)
    .join(", ");
  for (const ресурс of расчёт.ресурсы) {
    добавленные.push(
      добавитьПозицию(
        смета,
        {
          наименование: ресурс.наименование,
          единица: ресурс.единица,
          количество: ресурс.количество,
          ценаЗакупки: ресурс.цена ?? 0,
          вид: ресурс.вид,
          этап: расчёт.этап,
          источник: `расчёт · ${расчёт.название}`,
          примечание: описаниеПараметров,
        },
        кто,
        роль
      )
    );
  }
  запись(смета, кто, роль, "применён расчёт", {
    наименование: расчёт.название,
    стало: `${добавленные.length} позиций на ${расчёт.итого.toLocaleString("ru-RU")} ₽`,
  });
  return добавленные;
}

function пометитьИзменение(смета) {
  if (смета.статус === "согласована") смета.статус = "изменена после согласования";
}

/**
 * Согласование замораживает версию.
 *
 * Версия — полная копия позиций, а не ссылка: смысл в том, чтобы через полгода
 * можно было открыть смету ровно в том виде, в каком её подписали, даже если
 * с тех пор половину позиций удалили.
 */
function согласовать(смета, кто, роль, комментарий = "") {
  const развёрнутая = развернутьСмету(смета);
  смета.версии.unshift({
    id: id(),
    когда: ныне(),
    кто,
    роль,
    комментарий,
    итог: развёрнутая.итог,
    позиции: JSON.parse(JSON.stringify(смета.позиции)),
  });
  if (смета.версии.length > 30) смета.версии.length = 30;
  смета.статус = "согласована";
  смета.согласована = ныне();
  смета.согласовал = кто;
  запись(смета, кто, роль, "смета согласована", { стало: `${развёрнутая.итог.заказчику.toLocaleString("ru-RU")} ₽` });
  return смета;
}

/**
 * Что изменилось после согласования.
 *
 * Вопрос, который задают на каждой встрече с заказчиком: «мы же согласовали
 * другую сумму». Сравнение с последней замороженной версией отвечает на него
 * построчно, а не суммой.
 */
function изменениеПослеСогласования(смета) {
  const версия = смета.версии?.[0];
  if (!версия) return null;
  const было = new Map(версия.позиции.map((п) => [п.id, п]));
  const стало = new Map((смета.позиции || []).map((п) => [п.id, п]));
  const строки = [];
  for (const [idП, п] of стало) {
    const прежняя = было.get(idП);
    if (!прежняя) {
      строки.push({ вид: "добавлена", наименование: п.наименование, стало: п.количество });
    } else if (Number(прежняя.количество) !== Number(п.количество) || Number(прежняя.ценаЗакупки) !== Number(п.ценаЗакупки)) {
      строки.push({
        вид: "изменена",
        наименование: п.наименование,
        было: `${прежняя.количество} × ${прежняя.ценаЗакупки}`,
        стало: `${п.количество} × ${п.ценаЗакупки}`,
      });
    }
  }
  for (const [idП, п] of было) {
    if (!стало.has(idП)) строки.push({ вид: "удалена", наименование: п.наименование, было: п.количество });
  }
  const итогТогда = версия.итог.заказчику;
  const итогСейчас = развернутьСмету(смета).итог.заказчику;
  return { версия: версия.когда, строки, итогТогда, итогСейчас, разница: итогСейчас - итогТогда };
}

/**
 * Данные для акта КС-2: только то, что действительно выполнено.
 *
 * В акт идёт факт, а не план: позиция без внесённого факта в акт не попадает.
 * Это не строгость ради строгости — акт подписывают, и в нём не должно быть
 * работ, которых пока нет на объекте.
 */
function данныеКС2(смета, { период } = {}) {
  const развёрнутая = развернутьСмету(смета);
  const строки = развёрнутая.позиции
    .filter((п) => п.количествоФакт != null && п.количествоФакт > 0)
    .map((п, i) => ({
      номер: i + 1,
      позиция: п.номер,
      наименование: п.наименование,
      единица: п.единица,
      количество: п.количествоФакт,
      цена: п.ценаЗаказчику,
      сумма: п.суммаФакт,
      этап: п.этап,
    }));
  const итого = строки.reduce((s, с) => s + с.сумма, 0);
  return {
    строки,
    итого,
    // Пропущенные позиции показываются рядом: «не вошло в акт, потому что факт
    // не внесён» — частая причина спора о сумме акта.
    неВошло: развёрнутая.позиции.filter((п) => п.количествоФакт == null).length,
    период: период || "",
  };
}

