let пройдено = 0;
const провалы = [];

function проверка(что, условие, подробности = "") {
  if (условие) {
    пройдено++;
    console.log(`  ok  ${что}`);
  } else {
    провалы.push(`${что}${подробности ? ` — ${подробности}` : ""}`);
    console.log(`  ХХ  ${что}${подробности ? ` — ${подробности}` : ""}`);
  }
}

function равно(что, факт, ожидание) {
  проверка(что, факт === ожидание, `получили ${JSON.stringify(факт)}, ждали ${JSON.stringify(ожидание)}`);
}

function около(что, факт, ожидание, допуск = 0.5) {
  проверка(что, Math.abs(факт - ожидание) <= допуск, `получили ${факт}, ждали ${ожидание} ± ${допуск}`);
}

function бросает(что, действие, кусокТекста) {
  try {
    действие();
    проверка(что, false, "исключения не было");
  } catch (e) {
    проверка(что, String(e.message).includes(кусокТекста), `сообщение «${e.message}» не содержит «${кусокТекста}»`);
  }
}

