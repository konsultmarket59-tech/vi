    равно("реестр вошёл в комплект", комплект.созданные.some((д) => д.вид === "реестр"), true);
    равно("ничего не отвалилось", комплект.пропущено.length, 0);

    // Файл с названием «КС-2», внутри которого текст акта скрытых работ, хуже
    // отсутствующего файла: его подпишут не глядя.
    const JSZip = require("jszip");
    const кс2 = комплект.созданные.find((д) => д.вид === "кс2");
    const zip = await JSZip.loadAsync(await fs.readFile(кс2.файл));
    const текст = (await zip.file("word/document.xml").async("string")).replace(/<[^>]+>/g, "");
    равно("внутри файла КС-2 действительно форма КС-2", текст.includes("о приёмке выполненных работ"), true);

    // Шаблон компании важнее встроенной формы, и метки в нём должны заполниться.
    const { Document, Packer, Paragraph, TextRun } = require("docx");
    const шаблоны = path.join(корень, "шаблоны");
    await fs.mkdir(шаблоны, { recursive: true });
    await fs.writeFile(
      path.join(шаблоны, "АОСР форма.docx"),
      await Packer.toBuffer(
        new Document({
          sections: [{ children: [new Paragraph({ children: [new TextRun("Объект: "), new TextRun("{{до"), new TextRun("м}}, заказчик "), new TextRun("{{заказчик}}")] })] }],
        })
      )
    );
    const сШаблоном = await execdocs.собрать(контекст, { шаблоныПапка: шаблоны, кудаПапка: path.join(корень, "ид2"), только: ["аоср"] });
