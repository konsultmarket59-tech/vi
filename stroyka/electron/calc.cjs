/**
 * Расчёт одного вида работ.
 *
 * `прайс` необязателен: без него считаются объёмы, но не деньги — и это
 * честнее, чем подставить выдуманную цену. Позиции без цены попадают в
 * `замечания` и видны человеку строкой «цены нет в прайсе».
 */
function рассчитать(idВида, параметры, { прайс = [], регион = "пермский", сложность = "типовой" } = {}) {
  const вид = ПО_ID.get(idВида);
  if (!вид) throw new Error(`Неизвестный вид работ: ${idВида}`);

  const p = {};
  for (const пар of вид.параметры) {
    const значение = Number(параметры?.[пар.ключ]);
    p[пар.ключ] = Number.isFinite(значение) ? значение : пар.поумолчанию;
  }

  const объём = вид.объём(p);
  const кРегион = коэффициентРегиона(регион);
  const кСложность = коэффициентСложности(сложность);
  const кРабот = кРегион * кСложность;

  const { цена: ценаИзПрайса } = require("./prices.cjs");
  const ресурсы = [];
  const замечания = [];
  if (!прайс.length) {
    // Молчаливый расчёт с нулями — худший из возможных ответов: объёмы
    // выглядят посчитанными, итог показывает ноль, и человек решает, что
    // работа бесплатная. Поэтому отсутствие прайса — первое, что он читает.
    замечания.push(
      "Прайс не подключён: посчитаны объёмы и материалы, цен нет. " +
        "Путь к прайсу указывает снабжение в разделе «Источники данных»."
    );
  }

  for (const строка of вид.состав) {
    const базовый = строка.расход(объём, p);
    const сЗапасом = базовый * (1 + (строка.запас || 0));
    const количество = округлить(сЗапасом, строка.округление || (строка.единица === "шт" ? "целое" : "десятые"));
    if (количество <= 0) continue;

    let цена = null;
    let источникЦены = "";
    let вариантыЦены = [];
    if (прайс.length) {
      const найдено = ценаИзПрайса(строка.наименование, прайс);
      if (найдено.найдено) {
        цена = найдено.позиция.цена;
        источникЦены = найдено.позиция.поставщик ? `прайс · ${найдено.позиция.поставщик}` : "прайс";
        вариантыЦены = найдено.варианты;
      } else {
        вариантыЦены = найдено.варианты || [];
        замечания.push(`«${строка.наименование}» — ${найдено.причина}. Цену нужно поставить руками.`);
      }
    }

    // Коэффициенты — только на работы. Материал стоит столько, сколько просит
    // поставщик: наценка за регион и сложность относится к труду, а не к товару.
    const коэффициент = строка.вид === "работа" ? кРабот : 1;
    // Цена показывается округлённой, а сумма считается от неокруглённой. Иначе
    // на большом объёме копейки округления собираются в заметные деньги: при
    // 2000 м³ округление цены на 50 копеек — это сто тысяч рублей разницы между
    // тем, что видно в строке, и тем, что стоит в итоге.
    const ценаСКоэффициентом = цена == null ? null : Math.round(цена * коэффициент);

    ресурсы.push({
      вид: строка.вид,
      наименование: строка.наименование,
      единица: строка.единица,
      количествоБез: округлить(базовый, строка.округление || "десятые"),
      запас: строка.запас || 0,
      количество,
      ценаБазовая: цена,
      коэффициент,
      цена: ценаСКоэффициентом,
      сумма: цена == null ? null : Math.round(количество * цена * коэффициент),
      источникЦены,
      вариантыЦены: вариантыЦены.slice(0, 3).map((в) => ({ наименование: в.наименование, цена: в.цена, поставщик: в.поставщик })),
    });
  }

  const итогРабот = ресурсы.filter((р) => р.вид === "работа").reduce((s, р) => s + (р.сумма || 0), 0);
  const итогМатериалов = ресурсы.filter((р) => р.вид === "материал").reduce((s, р) => s + (р.сумма || 0), 0);
  const безЦены = ресурсы.filter((р) => р.цена == null).length;

  return {
    вид: idВида,
    название: вид.название,
    этап: вид.этап,
    единица: вид.единица,
    параметры: p,
    объём: округлить(объём, "десятые"),
    // Смен на бригаду — отсюда берутся сроки в графике работ.
    сменБригады: Math.max(1, Math.ceil(объём / вид.выработка)),
    регион,
    сложность,
    коэффициентРабот: Number(кРабот.toFixed(3)),
    ресурсы,
    итогРабот,
    итогМатериалов,
    итого: итогРабот + итогМатериалов,
    безЦены,
    замечания,
  };
}

/** Несколько видов работ подряд — расчёт целого дома по параметрам. */
function рассчитатьНабор(набор, настройки) {
  const расчёты = набор.map((э) => рассчитать(э.вид, э.параметры, настройки));
  return {
    расчёты,
    итогРабот: расчёты.reduce((s, р) => s + р.итогРабот, 0),
    итогМатериалов: расчёты.reduce((s, р) => s + р.итогМатериалов, 0),
    итого: расчёты.reduce((s, р) => s + р.итого, 0),
    замечания: расчёты.flatMap((р) => р.замечания),
  };
}

