//
// Считает КОД, целиком. Объём кладки, количество блоков, мешки клея, метры
// армопояса — всё это арифметика по размерам, и языковой модели тут делать
// нечего: цифру, которую придумала модель, нельзя ни проверить, ни защитить
// перед заказчиком, а ошибка в расходе на 5% — это лишний поддон блоков на
// каждом доме улицы. Модель в этом модуле не участвует вообще.
//
// Три правила, которые важнее остального.
//
// 1. КОЭФФИЦИЕНТЫ УМНОЖАЮТ ТОЛЬКО РАБОТЫ. Региональный коэффициент и сложность
//    объекта — это про труд: в Иркутске бригада стоит дороже, на сложной
//    геометрии кладут медленнее. Материал стоит столько, сколько просит
//    поставщик, и никакой коэффициент его цену не меняет. Когда коэффициент
//    применяют ко всей смете разом, объект дорожает на бумаге, а деньги на
//    закупку считаются неправильно.
//
// 2. РАСЧЁТ — ЕЩЁ НЕ СМЕТА. Пока не нажата «Применить в смету», в смете не
//    появилось ни строки и в снабжении не появилось ни заявки. Расчёт живёт
//    отдельным документом со своими версиями. Иначе смета растёт от каждого
//    пробного расчёта, и к концу недели в ней тридцать вариантов одной стены.
//
// 3. ЗАПАС ПИШЕТСЯ ОТДЕЛЬНО ОТ ОБЪЁМА. Блоков нужно на 5% больше, чем объём
//    кладки, — это подрезка и бой. Если запас втянуть в объём, то в акте
//    выполненных работ появится 36,5 м³ кладки вместо 34,8 — и заказчик
//    оплатит подрезку как работу.
//
// Нормы расхода и выработки — стартовые значения, а не истина: у каждой
// компании свои. Они лежат отдельной таблицей, их видно в интерфейсе, и их
// можно заменить своим файлом (см. источник «нормы»).

/** Округление под смысл величины: мешки — целыми, объёмы — до десятых. */
function округлить(значение, вид) {
  if (!Number.isFinite(значение)) return 0;
  if (вид === "целое") return Math.ceil(значение - 1e-9);
  if (вид === "сотые") return Math.round(значение * 100) / 100;
  return Math.round(значение * 10) / 10;
}

