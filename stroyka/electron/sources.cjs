// Источники: программа хранит пути, а не данные.
//
// Проект дома — это гигабайты чертежей, которые архитектор ведёт в своей
// программе и правит каждую неделю. Прайс — файл снабженца, который он
// перезаливает от поставщиков. Шаблоны исполнительной документации лежат у
// руководителя в папке и меняются, когда меняется форма. Копировать всё это
// внутрь приложения нельзя по трём причинам, и каждая уже случалась:
//
//  1. КОПИЯ УСТАРЕВАЕТ МОЛЧА. Архитектор поправил узел, а смета продолжает
//     считаться по чертежу двухмесячной давности — и никто этого не видит,
//     пока не привезут не тот материал.
//  2. ДАННЫЕ РАЗЪЕЗЖАЮТСЯ. Один и тот же прайс в трёх местах — это три разные
//     цены, и спорить о том, какая настоящая, будут на совещании.
//  3. ЭТО ЧУЖИЕ ДАННЫЕ. Проект принадлежит архитектору, прайс — снабжению.
//     Программа не должна становиться ещё одним владельцем файла.
//
// Поэтому здесь — реестр путей: кто указал, когда, что по этому пути лежит и
// доступен ли он прямо сейчас. Доступность проверяется каждый раз при чтении:
// сетевой диск отключили, папку переименовали, флешку вынули — человек должен
// увидеть это строкой «путь не открывается», а не пустой сметой.

const fs = require("node:fs/promises");
const path = require("node:path");

const { ныне, readJson, writeJson } = require("./workspace.cjs");

