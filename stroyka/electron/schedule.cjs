/**
 * Собирает этапы из расчёта дома.
 *
 * Длительность берётся из смен, посчитанных калькулятором по объёму и норме
 * выработки, — то есть срок связан с объёмом работ, а не назначен «на глаз».
 * Несколько видов работ одного этапа складываются, но делятся на количество
 * бригад: две бригады каменщиков кладут вдвое быстрее, и это ровно тот вопрос,
 * который задаёт руководитель, глядя на срок.
 */
function этапыИзРасчёта(расчёты, { бригадНаЭтап = {} } = {}) {
  const поЭтапам = new Map();
  for (const р of расчёты) {
    const ключ = р.этап;
    if (!поЭтапам.has(ключ)) поЭтапам.set(ключ, { смен: 0, работы: [], запретМесяцев: new Set(), причины: [] });
    const строка = поЭтапам.get(ключ);
    строка.смен += р.сменБригады;
    строка.работы.push({ вид: р.вид, название: р.название, объём: р.объём, единица: р.единица });
    const вид = ВИДЫ_РАБОТ.find((в) => в.id === р.вид);
    for (const м of вид?.сезон?.запрет || []) строка.запретМесяцев.add(м);
    if (вид?.сезон?.причина) строка.причины.push(вид.сезон.причина);
  }
  return ЭТАПЫ.filter((э) => поЭтапам.has(э.id) || э.id === "Сдача").map((э) => {
    const данные = поЭтапам.get(э.id);
    const бригад = Math.max(1, Number(бригадНаЭтап[э.бригада]) || 1);
    return {
      id: э.id,
      название: э.id,
      бригада: э.бригада,
      бригад,
      смен: данные ? Math.max(1, Math.ceil(данные.смен / бригад)) : э.длительностьСмен || 1,
      после: э.после.filter((п) => поЭтапам.has(п)),
      выдержка: э.выдержка,
      поясВыдержки: э.поясВыдержки || "",
      запретМесяцев: данные ? [...данные.запретМесяцев] : [],
      сезонПричина: данные ? [...new Set(данные.причины)][0] || "" : "",
      работы: данные?.работы || [],
    };
  });
}

/**
 * Прямой проход по календарю.
 *
 * Этап начинается, когда закончились все предшественники, прошла выдержка и
 * наступил разрешённый сезоном месяц. Дальше — смены по рабочему календарю.
 */
function построить(этапы, { начало, режим = "6/1", ресурс = null } = {}) {
  const старт = следующийРабочий(начало || строкаДаты(new Date()), режим);
  const конецЭтапа = new Map();
  const результат = [];

  // Порядок обхода — топологический: этап нельзя посчитать раньше, чем
  // посчитаны все, от кого он зависит.
  const очередь = топология(этапы);

  for (const этап of очередь) {
    let раннийСтарт = старт;
    let ограничитель = "начало объекта";
    for (const предыдущий of этап.после) {
      const конец = конецЭтапа.get(предыдущий);
      if (!конец) continue;
      const предок = ПО_ЭТАПАМ.get(предыдущий);
      const сВыдержкой = плюсДней(конец, 1 + (предок?.выдержка || 0));
      if (сВыдержкой > раннийСтарт) {
        раннийСтарт = сВыдержкой;
        ограничитель = предок?.выдержка ? `${предыдущий} + выдержка ${предок.выдержка} дн.` : предыдущий;
      }
    }

    const поСезону = сдвинутьПоСезону(следующийРабочий(раннийСтарт, режим), этап.запретМесяцев, режим);

    // Бригада может быть занята на другом доме. Спрашиваем не «когда она
    // освободится совсем», а «когда у неё есть окно нужной длины»: бригада
    // земляных работ делает и котлован в начале дома, и благоустройство в
    // конце, и если считать её занятой до последнего этапа, следующий дом
    // нельзя даже начать копать. Свободные окна между этапами — обычное дело,
    // и именно в них встают соседние объекты.
    let началоЭтапа = поСезону.дата;
    if (ресурс && этап.бригада) {
      const окно = ресурс.самоеРаннее(этап.бригада, началоЭтапа, этап.смен, режим);
      if (окно > началоЭтапа) {
        началоЭтапа = окно;
        ограничитель = `бригада «${этап.бригада}» занята на другом объекте`;
      }
    }

    const конец = плюсСмен(началоЭтапа, этап.смен, режим);
    конецЭтапа.set(этап.id, конец);
    if (ресурс && этап.бригада) ресурс.занять(этап.бригада, началоЭтапа, конец);

    результат.push({
      ...этап,
      начало: началоЭтапа,
      конец,
      ограничитель: поСезону.сдвиг && началоЭтапа === поСезону.дата ? `${поСезону.причина}: ${этап.сезонПричина}` : ограничитель,
      сезонныйСдвиг: поСезону.сдвиг,
      дней: Math.round((дата(конец) - дата(началоЭтапа)) / 86400000) + 1,
      статус: "не начат",
      фактНачало: "",
      фактКонец: "",
      готовность: 0,
    });
  }

  const сдача = результат.reduce((max, э) => (э.конец > max ? э.конец : max), старт);
  return {
    этапы: результат.sort((a, b) => a.начало.localeCompare(b.начало)),
    начало: старт,
    сдача,
    срокДней: Math.round((дата(сдача) - дата(старт)) / 86400000) + 1,
    режим,
    критический: критическийПуть(результат),
    // Когда бригада освободится — это ответ сводному плану посёлка.
    освобождение: результат.reduce((acc, э) => {
      if (!э.бригада) return acc;
      if (!acc[э.бригада] || э.конец > acc[э.бригада]) acc[э.бригада] = плюсДней(э.конец, 1);
      return acc;
    }, {}),
  };
}

/** Топологический порядок; цикл в зависимостях не должен вешать расчёт. */
function топология(этапы) {
  const поId = new Map(этапы.map((э) => [э.id, э]));
  const посещён = new Set();
  const вПроцессе = new Set();
  const порядок = [];
  function обход(этап) {
    if (посещён.has(этап.id) || вПроцессе.has(этап.id)) return;
    вПроцессе.add(этап.id);
    for (const п of этап.после) {
      const предок = поId.get(п);
      if (предок) обход(предок);
    }
    вПроцессе.delete(этап.id);
    посещён.add(этап.id);
    порядок.push(этап);
  }
  for (const э of этапы) обход(э);
  return порядок;
}

/**
 * Критический путь — самая длинная цепочка от начала до сдачи.
 *
 * Нужен ровно для одного вопроса: отставание на этом этапе двигает сдачу или
 * нет. Без него любое отставание выглядит одинаково страшно, и руководитель
 * тратит внимание на этап, у которого две недели запаса.
 */
function критическийПуть(этапы) {
  const поId = new Map(этапы.map((э) => [э.id, э]));
  const кэш = new Map();
  function длина(этап) {
    if (кэш.has(этап.id)) return кэш.get(этап.id);
    let максимум = 0;
    let через = null;
    for (const п of этап.после) {
      const предок = поId.get(п);
      if (!предок) continue;
      const l = длина(предок).длина + (ПО_ЭТАПАМ.get(п)?.выдержка || 0);
      if (l > максимум) { максимум = l; через = п; }
    }
    const значение = { длина: максимум + этап.смен, через };
    кэш.set(этап.id, значение);
    return значение;
  }
  let последний = null;
  for (const э of этапы) {
    const l = длина(э).длина;
    if (!последний || l > длина(последний).длина) последний = э;
  }
  const путь = [];
  let текущий = последний;
  while (текущий) {
    путь.unshift(текущий.id);
    const через = кэш.get(текущий.id)?.через;
    текущий = через ? поId.get(через) : null;
  }
  return путь;
}

/**
 * Отметка факта по этапу и пересчёт того, что за ним.
 *
 * Отставание считается не «сколько дней прошло», а «на сколько сдвинулась
 * сдача»: этап с запасом может опоздать на неделю и ничего не сломать, а этап
 * на критическом пути опаздывает вместе со всем домом.
 */
function отметитьФакт(график, idЭтапа, { статус, готовность, фактНачало, фактКонец }) {
  const этапы = график.этапы.map((э) =>
    э.id === idЭтапа
      ? {
          ...э,
          статус: статус || э.статус,
          готовность: готовность == null ? э.готовность : Math.max(0, Math.min(100, Number(готовность))),
          фактНачало: фактНачало || э.фактНачало,
          фактКонец: фактКонец || э.фактКонец,
        }
      : э
  );
  return пересчитать({ ...график, этапы });
}

/**
 * Пересчёт по факту: где сейчас находится стройка относительно плана.
 */
function пересчитать(график, сегодня = строкаДаты(new Date())) {
  const критические = new Set(график.критический || []);
  const этапы = график.этапы.map((э) => {
    const завершён = э.статус === "выполнен" || э.готовность >= 100;
    const фактическийКонец = э.фактКонец || (завершён ? сегодня : "");
    let отставание = 0;
    if (фактическийКонец) {
      отставание = Math.round((дата(фактическийКонец) - дата(э.конец)) / 86400000);
    } else if (сегодня > э.конец) {
      отставание = Math.round((дата(сегодня) - дата(э.конец)) / 86400000);
    } else if (сегодня > э.начало && э.готовность > 0) {
      // Этап идёт: сравниваем готовность с тем, сколько должно быть сделано к
      // сегодняшнему дню. Разница в процентах переводится в дни по своей же
      // длительности — иначе «отстаём на 20%» ничего не говорит о сдаче.
      const прошло = (дата(сегодня) - дата(э.начало)) / 86400000 + 1;
      const должноБыть = Math.min(100, (прошло / э.дней) * 100);
      if (должноБыть - э.готовность > 5) {
        отставание = Math.round(((должноБыть - э.готовность) / 100) * э.дней);
      }
    }
    return {
      ...э,
      критический: критические.has(э.id),
      отставание,
      // Отставание вне критического пути съедает запас, а не срок сдачи, — и
      // называется по-другому, чтобы на планёрке эти два случая не путали.
      двигаетСдачу: критические.has(э.id) && отставание > 0,
      статус: завершён ? "выполнен" : сегодня >= э.начало && сегодня <= э.конец ? (э.статус === "не начат" ? "должен идти" : э.статус) : э.статус,
    };
  });
  const сдвигСдачи = этапы.filter((э) => э.двигаетСдачу).reduce((max, э) => Math.max(max, э.отставание), 0);
  return {
    ...график,
    этапы,
    сегодня,
    отстают: этапы.filter((э) => э.отставание > 0).length,
    сдвигСдачи,
    прогнозСдачи: сдвигСдачи ? плюсДней(график.сдача, сдвигСдачи) : график.сдача,
    готовность: Math.round(
      этапы.reduce((s, э) => s + (э.готовность || 0) * э.смен, 0) / Math.max(1, этапы.reduce((s, э) => s + э.смен, 0))
    ),
  };
}

/**
 * График приёмки: когда и что принимать.
 *
 * Приёмка привязана не к календарю, а к окончанию этапа — принимать нужно то,
 * что закроется следующей работой. Скрытые работы (арматура до бетона,
 * гидроизоляция до стяжки, разводка до штукатурки) освидетельствуются актом
 * ДО закрытия: после закрытия их можно только вскрывать.
 */
const СКРЫТЫЕ = {
  Фундамент: ["Армирование плиты", "Гидроизоляция фундамента", "Основание под плиту"],
  Перекрытие: ["Армирование перекрытия", "Опалубка и опирание"],
  Кровля: ["Пароизоляция", "Утепление кровли", "Гидроизоляция подкровельная"],
  Инженерия: ["Скрытая электропроводка", "Трубопроводы в конструкциях", "Опрессовка систем"],
  Стяжка: ["Гидроизоляция полов", "Утепление пола", "Трубы тёплого пола"],
  Фасад: ["Крепление утеплителя", "Армирующий слой"],
};

function графикПриёмки(график) {
  const приёмки = [];
  for (const этап of график.этапы) {
    const скрытые = СКРЫТЫЕ[этап.id] || [];
    for (const работа of скрытые) {
      приёмки.push({
        id: id(),
        этап: этап.id,
        работа,
        вид: "скрытые работы",
        документ: "АОСР",
        // За день до конца этапа: акт подписывают, пока работу ещё видно.
        дата: плюсДней(этап.конец, -1),
        участники: ["прораб", "руководитель", "технадзор"],
        статус: "запланирована",
      });
    }
    приёмки.push({
      id: id(),
      этап: этап.id,
      работа: `Этап «${этап.id}» целиком`,
      вид: "этап",
      документ: этап.id === "Сдача" ? "Акт приёма-передачи" : "КС-2",
      дата: этап.конец,
      участники: этап.id === "Сдача" ? ["руководитель", "заказчик"] : ["прораб", "руководитель"],
      статус: "запланирована",
    });
  }
  return приёмки.sort((a, b) => a.дата.localeCompare(b.дата));
}

