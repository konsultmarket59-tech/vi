// ---------- календарь ----------

function дата(строка) {
  // Полдень по UTC, а не полночь: при полуночи любой сдвиг часового пояса на
  // час назад превращает дату в предыдущий день, и график «съезжает» на сутки
  // у пользователя западнее Гринвича.
  const [г, м, д] = String(строка).slice(0, 10).split("-").map(Number);
  return new Date(Date.UTC(г, (м || 1) - 1, д || 1, 12));
}

function строкаДаты(d) {
  return d.toISOString().slice(0, 10);
}

function плюсДней(строка, дней) {
  const d = дата(строка);
  d.setUTCDate(d.getUTCDate() + дней);
  return строкаДаты(d);
}

function рабочий(строка, режим) {
  const d = дата(строка);
  const день = d.getUTCDay();
  if (ПРАЗДНИКИ.has(строкаДаты(d).slice(5))) return false;
  if (режим === "7/0") return true;
  if (режим === "6/1") return день !== 0;
  return день !== 0 && день !== 6;
}

function следующийРабочий(строка, режим) {
  let d = строка;
  for (let i = 0; i < 400; i++) {
    if (рабочий(d, режим)) return d;
    d = плюсДней(d, 1);
  }
  return d;
}

/** Прибавляет к дате N рабочих смен и возвращает дату последней смены. */
function плюсСмен(начало, смен, режим) {
  let d = следующийРабочий(начало, режим);
  let сделано = 1;
  while (сделано < смен) {
    d = следующийРабочий(плюсДней(d, 1), режим);
    сделано++;
  }
  return d;
}

function месяц(строка) {
  return Number(String(строка).slice(5, 7));
}

/**
 * Двигает старт вперёд, пока он попадает в запрещённый для этапа месяц.
 *
 * Двигает именно старт, а не отдельные дни внутри работы: разбивать кладку на
 «кусочки по погоде» — это фантазия планировщика, бригада так не работает.
 * Ограничение на 400 дней — защита от вида работ, у которого запрещены все
 * двенадцать месяцев (опечатка в справочнике не должна вешать расчёт).
 */
function сдвинутьПоСезону(старт, запретМесяцев, режим) {
  if (!запретМесяцев?.length) return { дата: старт, сдвиг: 0, причина: "" };
  let d = старт;
  let сдвиг = 0;
  while (запретМесяцев.includes(месяц(d)) && сдвиг < 400) {
    d = плюсДней(d, 1);
    сдвиг++;
  }
  return { дата: следующийРабочий(d, режим), сдвиг, причина: сдвиг ? "сезонное ограничение" : "" };
}

