// График работ: один срок — и дни, разложенные по этапам.
//
// Почему это считает код, а не человек в Excel и не языковая модель.
//
// Срок стройки складывается не из суммы работ. Между работами стоят вещи,
// которые не видно в смете и о которых забывают именно тогда, когда планируют
// сдачу заказчику:
//
//  — ВЫДЕРЖКА. Бетон фундамента набирает прочность; класть стены на него
//    завтра нельзя. Стяжка сохнет до укладки покрытия недели, а не дни. Это не
//    работа, за неё никто не платит, но в календаре это дни, и их не пройти
//    быстрее, наняв больше людей.
//  — СЕЗОН. Мокрый фасад не наносят при +3 °C, бетонируют зимой только с
//    прогревом, грунт в январе мёрзлый. Работу, попавшую в запрещённый месяц,
//    двигают — иначе получается график, который на бумаге сходится, а на
//    объекте нет.
//  — ВЫХОДНЫЕ И ПРАЗДНИКИ. «Двадцать смен» — это не двадцать дней подряд.
//
// Поэтому расчёт идёт по календарю: продолжительность в сменах превращается в
// даты с учётом рабочих дней, выдержек, зависимостей и сезонных окон. И
// поэтому критический путь считается, а не назначается: отставание важно не
// само по себе, а тем, двигает оно сдачу или съедает запас.

