// Мост между окном и программой.
//
// Каждый обработчик в main.cjs возвращает конверт {ok, данные|ошибка}. Здесь
// конверт разворачивается: окно получает либо данные, либо обычное исключение с
// человеческим текстом. Это избавляет каждый экран от проверки `if (!ответ.ok)`
// — а именно такие проверки и забывают, после чего интерфейс молча показывает
// пустой список вместо «нет доступа к сетевой папке».

const { contextBridge, ipcRenderer } = require("electron");

async function позвать(канал, ...аргументы) {
  const ответ = await ipcRenderer.invoke(канал, ...аргументы);
  if (!ответ || ответ.ok !== true) {
    throw new Error(ответ?.ошибка || `Не получилось выполнить «${канал}»`);
  }
  return ответ.данные;
}

