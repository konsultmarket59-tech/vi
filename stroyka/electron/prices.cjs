// Прайс: чтение файла снабженца и поиск позиции по названию.
//
// Прайс — не база данных, а таблица, которую человек ведёт руками. В ней
// шапка не на первой строке, а на пятой, потому что сверху логотип и телефон
// поставщика. Единицы записаны семью способами («м2», «м²», «кв.м», «кв. м»,
// «М2»). Цена бывает текстом «по запросу», числом с пробелами-разделителями и
// формулой. Названия — живые: «Блок газобетонный D500 600х300х200» и
// «Газоблок D500 300мм» в двух прайсах означают одно и то же.
//
// Поэтому здесь две отдельные задачи, и обе решает код, а не модель.
//
// ПЕРВАЯ — прочитать таблицу: найти шапку по смыслу колонок, а не по номеру
// строки, и привести единицы к одному виду.
//
// ВТОРАЯ — сопоставить название из сметы с названием из прайса. Здесь важно
// одно правило, из-за которого нельзя обойтись «похожестью строк»: ЧИСЛА И
// МАРКИ — ЖЁСТКОЕ УСЛОВИЕ. «D500» и «D400» похожи на 90%, но это разный
// материал, разная цена и разная несущая способность. Совпадение по словам
// даёт баллы, несовпадение по марке — отказ.

/** Единицы измерения: как встречается → как хранится. */
const ЕДИНИЦЫ = [
  { канон: "м²", варианты: ["м2", "м²", "кв.м", "кв. м", "квм", "m2", "кв.метр", "кв.метров"] },
  { канон: "м³", варианты: ["м3", "м³", "куб.м", "куб. м", "кубм", "m3", "куб.метр"] },
  { канон: "м", варианты: ["м", "м.п.", "мп", "пог.м", "пог. м", "погм", "п.м.", "пм", "метр"] },
  { канон: "шт", варианты: ["шт", "шт.", "штук", "штука", "ед", "ед.", "компл", "компл."] },
  { канон: "т", варианты: ["т", "тн", "тонна", "тонн"] },
  { канон: "кг", варианты: ["кг", "килограмм"] },
  { канон: "л", варианты: ["л", "литр", "литров"] },
  { канон: "меш", варианты: ["меш", "мешок", "мешков", "меш."] },
  { канон: "пал", варианты: ["пал", "поддон", "паллета", "паллет"] },
  { канон: "точка", варианты: ["точка", "точек", "точки"] },
  { канон: "смена", варианты: ["смена", "смен", "чел/см", "чел.-см"] },
];

function единица(сырая) {
  const t = String(сырая || "").trim().toLowerCase().replace(/\s+/g, "");
  for (const е of ЕДИНИЦЫ) {
    if (е.варианты.some((v) => v.replace(/\s+/g, "") === t)) return е.канон;
  }
  return String(сырая || "").trim();
}

/**
 * Число из ячейки прайса.
 *
 * «1 250,50 ₽» — обычная запись цены в таблице, которую вели руками: неразрывный
 * пробел как разделитель тысяч, запятая как десятичная точка, знак валюты в той
 * же ячейке. Обычный Number на такой строке даёт NaN, и позиция молча уезжает в
 * смету с нулевой ценой.
 */
function число(v) {
  if (v == null) return null;
  if (typeof v === "number") return Number.isFinite(v) ? v : null;
  if (typeof v === "object") {
    if (v.result != null) return число(v.result);
    if (v.text != null) return число(v.text);
    if (Array.isArray(v.richText)) return число(v.richText.map((p) => p.text).join(""));
    return null;
  }
  const t = String(v)
    .replace(/[\s  ]/g, "")
    .replace(/[₽руб.]*$/i, "")
    .replace(",", ".");
  const n = Number(t);
  return Number.isFinite(n) ? n : null;
}

function текст(v) {
  if (v == null) return "";
  if (typeof v === "object") {
    if (Array.isArray(v.richText)) return v.richText.map((p) => p.text).join("").trim();
    if (v.text != null) return String(v.text).trim();
    if (v.result != null) return String(v.result).trim();
    if (v instanceof Date) return v.toISOString().slice(0, 10);
    return "";
  }
  return String(v).trim();
}

/** Какие слова в шапке означают какую колонку. */
const КОЛОНКИ_ПРАЙСА = [
  { ключ: "наименование", слова: ["наименование", "название", "материал", "номенклатура", "позиция", "товар", "работа"] },
  { ключ: "единица", слова: ["ед", "ед.изм", "единица", "ед. изм", "изм", "unit"] },
  { ключ: "цена", слова: ["цена", "стоимость", "прайс", "руб", "price", "ценаруб"] },
  { ключ: "поставщик", слова: ["поставщик", "продавец", "контрагент", "склад", "магазин"] },
  { ключ: "срок", слова: ["срок", "срокпоставки", "доставка", "днейдопоставки", "отгрузка"] },
  { ключ: "партия", слова: ["минпартия", "минимальнаяпартия", "кратность", "упаковка", "вупаковке", "норма отгрузки"] },
  { ключ: "артикул", слова: ["артикул", "код", "sku", "штрихкод"] },
  { ключ: "примечание", слова: ["примечание", "коммент", "заметка", "описание"] },
];

function опознатьКолонку(заголовок) {
  const t = String(заголовок || "").toLowerCase().replace(/[^а-яёa-z]/gi, "");
  if (!t) return null;
  for (const к of КОЛОНКИ_ПРАЙСА) {
    if (к.слова.some((с) => t === с.replace(/[^а-яёa-z]/gi, "") || t.startsWith(с.replace(/[^а-яёa-z]/gi, "")))) {
      return к.ключ;
    }
  }
  return null;
}

/**
 * Ищет строку-шапку.
 *
 * Не «первая строка»: сверху прайса обычно шапка поставщика с логотипом,
 * телефоном и датой. Настоящая шапка — та, где одновременно есть колонка с
 * названием и колонка с ценой; ищем такую в первых тридцати строках.
 */
function найтиШапку(строки) {
  for (let i = 0; i < Math.min(строки.length, 30); i++) {
    const карта = {};
    строки[i].forEach((ячейка, j) => {
      const ключ = опознатьКолонку(ячейка);
      if (ключ && карта[ключ] === undefined) карта[ключ] = j;
    });
    if (карта.наименование !== undefined && карта.цена !== undefined) {
      return { строка: i, карта };
    }
  }
  return null;
}

/**
 * CSV, разобранный посимвольно, а не split(",").
 *
 * Название материала регулярно содержит запятую («Блок газобетонный D500,
 * 600х300х200»), и разбиение по запятой рвёт такую строку пополам: половина
 * названия уезжает в колонку цены. Кавычки при этом обязаны работать по
 * правилам CSV, включая удвоенную кавычку внутри значения.
 */
function читатьCsv(текстФайла) {
  const разделитель = (текстФайла.split("\n")[0].match(/;/g) || []).length >
    (текстФайла.split("\n")[0].match(/,/g) || []).length ? ";" : ",";
  const строки = [];
  let строка = [];
  let поле = "";
  let вКавычках = false;
  for (let i = 0; i < текстФайла.length; i++) {
    const c = текстФайла[i];
    if (вКавычках) {
      if (c === '"') {
        if (текстФайла[i + 1] === '"') { поле += '"'; i++; }
        else вКавычках = false;
      } else поле += c;
      continue;
    }
    if (c === '"') { вКавычках = true; continue; }
    if (c === разделитель) { строка.push(поле); поле = ""; continue; }
    if (c === "\n") { строка.push(поле); строки.push(строка); строка = []; поле = ""; continue; }
    if (c === "\r") continue;
    поле += c;
  }
  if (поле || строка.length) { строка.push(поле); строки.push(строка); }
  return [{ имя: "csv", строки }];
}

/**
 * Разбор уже прочитанных листов в позиции прайса.
 *
 * Отделено от чтения файла намеренно. Разобрать таблицу и достать её с диска —
 * разные задачи: первая это чистая арифметика над строками, вторая требует
 * файловой системы и библиотеки чтения xlsx. Пока они лежали в одном модуле,
 * любой, кому нужна была только цена по названию, тянул за собой exceljs —
 * полтора мегабайта кода ради сравнения двух строк.
 *
 * Возвращает и позиции, и замечания. Замечания не мелочь: «в 14 строках нет
 * цены» лучше увидеть при загрузке, чем обнаружить нулём в смете.
 */
function разобратьЛисты(листы) {
  const позиции = [];
  const замечания = [];
  let листовСШапкой = 0;

  for (const лист of листы) {
    const строкиТекстом = лист.строки.map((с) => (с || []).map(текст));
    const шапка = найтиШапку(строкиТекстом);
    if (!шапка) continue;
    листовСШапкой++;
    let безЦены = 0;
    for (let i = шапка.строка + 1; i < лист.строки.length; i++) {
      const сырая = лист.строки[i] || [];
      const наименование = текст(сырая[шапка.карта.наименование]);
      if (!наименование) continue;
      const цена = число(сырая[шапка.карта.цена]);
      if (цена == null) {
        // Строка-раздел («СТЕНОВЫЕ МАТЕРИАЛЫ») выглядит так же, как позиция без
        // цены. Отличаем по остальным колонкам: у раздела они пустые.
        const естьЕщё = Object.values(шапка.карта).some((j, k) => k > 0 && текст(сырая[j]));
        if (естьЕщё) безЦены++;
        continue;
      }
      позиции.push({
        наименование,
        единица: единица(текст(сырая[шапка.карта.единица])),
        цена,
        поставщик: текст(сырая[шапка.карта.поставщик]),
        срок: число(сырая[шапка.карта.срок]) ?? null,
        партия: число(сырая[шапка.карта.партия]) ?? null,
        артикул: текст(сырая[шапка.карта.артикул]),
        примечание: текст(сырая[шапка.карта.примечание]),
        лист: лист.имя,
        ключ: нормализовать(наименование),
        марки: марки(наименование),
      });
      if (позиции.length > 60000) break;
    }
    if (безЦены > 0) замечания.push(`Лист «${лист.имя}»: ${безЦены} строк без цены — они пропущены.`);
  }

  if (листовСШапкой === 0) {
    замечания.push(
      "В файле не нашлась шапка таблицы. Нужны колонки с названием материала и с ценой — " +
        "проверьте, что они подписаны («Наименование», «Цена»)."
    );
  }

  return { позиции, замечания };
}

// ---------- сопоставление названий ----------

const СТОП_СЛОВА = new Set([
  "и", "в", "на", "для", "с", "из", "по", "от", "до", "шт", "мм", "см", "м",
  "ГОСТ", "гост", "ту", "тм", "марка", "класс", "тип",
]);

/**
 * Приведение названия к сравнимому виду.
 * «ё» к «е» — потому что в одном прайсе «щебёнка», в другом «щебенка».
 */
function нормализовать(строка) {
  return String(строка || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^а-я0-9a-z]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

function слова(строка) {
  return нормализовать(строка)
    .split(" ")
    .filter((с) => с.length > 2 && !СТОП_СЛОВА.has(с));
}

/**
 * Марки и размеры — то, что обязано совпадать.
 *
 * Сюда попадают «D500», «М300», «В25», «А500С», «12» (диаметр), «600х300х200».
 * Именно эти обозначения отличают материал от похожего на него, и именно их
 * теряет любое сравнение «по похожести букв».
 */
function марки(строка) {
  const t = String(строка || "").toLowerCase().replace(/ё/g, "е");
  const найдено = new Set();
  // Буквенно-цифровые марки: d500, м300, в25, а500с, ф150
  for (const m of t.matchAll(/\b([a-zа-я]{1,3})\s?-?\s?(\d{2,4})([а-яa-z]?)\b/g)) {
    найдено.add(`${m[1]}${m[2]}${m[3]}`);
  }
  // Габариты: 600х300х200 и 600x300x200 — русский «х» и латинский «x» вперемешку
  for (const m of t.matchAll(/\b(\d{2,4}(?:\s?[хx]\s?\d{2,4}){1,2})\b/g)) {
    найдено.add(m[1].replace(/\s/g, "").replace(/x/g, "х"));
  }
  // Диаметр арматуры: ⌀12, д12, диаметр 12
  for (const m of t.matchAll(/[⌀ø]\s?(\d{1,2})\b/g)) найдено.add(`d${m[1]}`);
  return [...найдено];
}

/**
 * Оценка совпадения от 0 до 1.
 *
 * Марки — не баллы, а условие: если в запросе есть марка, а в позиции прайса
 * стоит другая марка того же вида, совпадения нет вообще. Отсутствие марки в
 * прайсе — не отказ (её могли не написать), но и не подтверждение: такая
 * позиция получает меньше, чем позиция с точным совпадением марки.
 */
function оценка(запрос, позиция) {
  const слЗапрос = слова(запрос);
  const слПозиция = слова(позиция.наименование);
  if (!слЗапрос.length || !слПозиция.length) return 0;

  const мЗапрос = марки(запрос);
  const мПозиция = позиция.марки || марки(позиция.наименование);
  let бонусМарки = 0;
  if (мЗапрос.length) {
    const совпали = мЗапрос.filter((м) => мПозиция.includes(м));
    if (совпали.length === 0 && мПозиция.length > 0) {
      // В прайсе есть своя марка, и она другая. Это другой материал.
      const конфликт = мЗапрос.some((м) => {
        const вид = м.replace(/\d+/g, "");
        return мПозиция.some((п) => п.replace(/\d+/g, "") === вид && п !== м);
      });
      if (конфликт) return 0;
    }
    бонусМарки = (совпали.length / мЗапрос.length) * 0.35;
  }

  const набор = new Set(слПозиция);
  const пересечение = слЗапрос.filter((с) =>
    набор.has(с) ||
    // Однокоренные: «кладка/кладочный», «штукатурка/штукатурный». Сравниваем
    // по началу слова длиной 5 — на русском это устойчивее любой леммы.
    [...набор].some((п) => п.length > 4 && с.length > 4 && (п.startsWith(с.slice(0, 5)) || с.startsWith(п.slice(0, 5))))
  ).length;
  const доляЗапроса = пересечение / слЗапрос.length;
  const доляПозиции = пересечение / слПозиция.length;
  // Гармоническое среднее: длинное название прайса не должно выигрывать только
  // потому, что в него случайно попали все слова запроса и ещё двадцать своих.
  const база = доляЗапроса + доляПозиции > 0 ? (2 * доляЗапроса * доляПозиции) / (доляЗапроса + доляПозиции) : 0;
  return Math.min(1, база * 0.75 + бонусМарки);
}

/**
 * Подбор позиций прайса под название. Возвращает несколько вариантов, а не
 * один: выбор между «Блок D500 300мм» за 5400 и «Блок D500 300мм (акция)» за
 * 4900 — решение снабженца, а не программы.
 */
function подобрать(запрос, прайс, { сколько = 5, порог = 0.34 } = {}) {
  const оценённые = [];
  for (const п of прайс) {
    const о = оценка(запрос, п);
    if (о >= порог) оценённые.push({ ...п, совпадение: Number(о.toFixed(3)) });
  }
  оценённые.sort((a, b) => b.совпадение - a.совпадение || a.цена - b.цена);
  return оценённые.slice(0, сколько);
}

/**
 * Цена по названию: лучший вариант, если он заметно лучше остальных.
 *
 * Когда первые два варианта почти равны, автоматический выбор — это подмена
 * решения: программа поставит в смету не тот материал, и заметят это на
 * объекте. Такой случай возвращается как «неоднозначно» и попадает в замечания.
 */
function цена(запрос, прайс) {
  const варианты = подобрать(запрос, прайс, { сколько: 3 });
  if (!варианты.length) return { найдено: false, причина: "в прайсе нет похожей позиции", варианты: [] };
  const [первый, второй] = варианты;
  if (второй && первый.совпадение - второй.совпадение < 0.05 && первый.цена !== второй.цена) {
    return { найдено: false, причина: "несколько одинаково подходящих позиций с разной ценой", варианты };
  }
  return { найдено: true, позиция: первый, варианты };
}

