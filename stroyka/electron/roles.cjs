const ПО_ID = new Map(РОЛИ.map((r) => [r.id, r]));

function роль(id) {
  return ПО_ID.get(id) || ПО_ID.get("прораб");
}

/** Есть ли у роли право на действие. */
function можно(idРоли, действие) {
  return роль(idРоли).действия.includes(действие);
}

/** Виден ли роли раздел. */
function виденРаздел(idРоли, раздел) {
  return роль(idРоли).разделы.includes(раздел);
}

/** Колонки сметы для роли — в каноническом порядке, а не в порядке списка роли. */
function колонкиСметы(idРоли) {
  const набор = new Set(роль(idРоли).колонки);
  return Object.keys(КОЛОНКИ)
    .filter((k) => набор.has(k))
    .map((k) => ({ ключ: k, заголовок: КОЛОНКИ[k] }));
}

/**
 * Вырезает из позиций сметы всё, чего роль видеть не должна.
 *
 * Именно вырезает, а не прячет: позиция уезжает в окно уже без закупочной цены,
 * поэтому её нельзя достать ни из памяти вкладки, ни из выгрузки в файл.
 */
/**
 * Производные поля. Проценту отклонения нет отдельной колонки, но он —
 * то же самое число другим способом, и роль, которой отклонение не положено,
 * не должна получать его в процентах через заднюю дверь. Такие поля
 * перечислены явно: молчаливое «всё, чего нет в колонках, — служебное»
 * однажды выпустит наружу как раз то, что прятали.
 */
const ПРОИЗВОДНЫЕ = {
  отклонениеПроцент: "отклонение",
  рентабельность: "маржа",
  суммаБезНДС: "суммаЗаказчику",
};

function срезатьПоРоли(позиции, idРоли) {
  const разрешено = new Set(роль(idРоли).колонки);
  return позиции.map((поз) => {
    const срез = {};
    for (const ключ of Object.keys(поз)) {
      const управляющая = ПРОИЗВОДНЫЕ[ключ] || ключ;
      // Служебные поля (id, коды, привязки к этапам) — не деньги и не колонки,
      // они нужны любой роли, чтобы позиция вообще осталась позицией.
      if (!(управляющая in КОЛОНКИ) || разрешено.has(управляющая)) срез[ключ] = поз[ключ];
    }
    return срез;
  });
}

