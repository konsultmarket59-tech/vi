// Мелочи, нужные всем расчётным модулям: идентификатор и текущее время.
//
// Вынесено в отдельный файл ради одного свойства: расчётные модули не должны
// зависеть от файловой системы. Раньше они брали `id` и `ныне` из
// workspace.cjs, а тот первой же строкой требует node:fs — и вся арифметика
// сметы, графика и логистики оказывалась привязана к Node, хотя ничего от него
// не хочет. Теперь calc, schedule, plan, estimate, supply и chat не знают ни
// про файлы, ни про Electron: их можно посчитать где угодно, в том числе в
// браузере — на этом стоит веб-демонстрация.

/**
 * Идентификатор записи.
 *
 * crypto.randomUUID есть не везде: в браузере он доступен только в защищённом
 * контексте, и страница, открытая двойным кликом из папки (file://), его не
 * получает. Поэтому запасной вариант — время плюс случайный хвост: для
 * идентификаторов позиций сметы и сообщений чата этого достаточно с большим
 * запасом, а падать из-за отсутствия функции нельзя.
 */
function id() {
  const свой = typeof globalThis !== "undefined" ? globalThis.crypto : undefined;
  if (свой && typeof свой.randomUUID === "function") return свой.randomUUID().slice(0, 8);
  return `${Date.now().toString(36).slice(-5)}${Math.random().toString(36).slice(2, 5)}`;
}

/** Текущий момент в том виде, в каком он ложится в файлы. */
function ныне() {
  return new Date().toISOString();
}

module.exports = { id, ныне };
