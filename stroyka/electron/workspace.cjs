// Хранилище: посёлки, дома и всё, что к дому относится.
//
// Данных в этой программе нет. Есть папка на компьютере, а в ней обычные файлы
// и папки, которые видно в проводнике и которые можно скопировать на флешку,
// положить в общую сетевую папку или отдать бухгалтеру. Это не оговорка в
// описании, а требование: стройка живёт дольше любой программы, и через пять
// лет по дому должны находиться документы, даже если этой программы уже нет.
//
// Отсюда — раскладка «папка на дом», а не одна большая база:
//
//   Стройка/
//     посёлки/<посёлок>/
//       посёлок.json        — название, картинка карты, улицы
//       дома/<дом>/
//         дом.json          — карточка: адрес, заказчик, статус, точка на карте
//         смета.json        — позиции, план и факт, журнал изменений
//         график.json       — этапы, сроки, зависимости
//         снабжение.json    — заявки
//         приёмка.json      — приёмки и акты
//         чат.json          — отчёты с объекта и разбор агента
//         отчёты/           — готовые отчёты клиенту
//
// Файл на раздел, а не один общий: прораб пишет в чат с телефона в то же
// время, когда сметчик правит смету, а руководитель двигает график. Пока это
// разные файлы, две правки рядом не затирают друг друга. Один общий файл
// означал бы, что последний сохранивший стёр чужую работу молча.
//
// Проект, прайс, шаблоны и фотографии здесь НЕ ЛЕЖАТ — на них хранятся только
// пути (см. sources.cjs). Дом весит килобайты, а не гигабайты.

const fs = require("node:fs/promises");
const fsSync = require("node:fs");
const path = require("node:path");
const { id, ныне } = require("./common.cjs");

/** Разделы дома, каждый в своём файле. Ключ — имя файла без расширения. */
const РАЗДЕЛЫ_ДОМА = ["смета", "график", "снабжение", "приёмка", "чат"];

/** Пустое содержимое раздела. Читающая сторона не должна проверять null. */
const ПУСТО = {
  смета: { позиции: [], статус: "черновик", журнал: [], версии: [], коэффициенты: {} },
  график: { этапы: [], срокДней: 0, начало: "", сдача: "", пересчитан: "" },
  снабжение: { заявки: [] },
  приёмка: { приёмки: [] },
  чат: { сообщения: [], отклонения: [], уведомления: [] },
};

/**
 * Имя папки из названия. Кириллицу оставляем: папку открывают в проводнике
 * руками, и «posyolok-udachnyy» там читается хуже, чем «Удачный».
 */
function имяПапки(название) {
  const base = String(название || "")
    .trim()
    .replace(/[\\/:*?"<>|]+/g, " ")
    .replace(/\s+/g, " ")
    .slice(0, 60)
    .trim();
  return base || "без названия";
}

function свободноеИмя(dir, базовое) {
  let имя = базовое;
  let n = 2;
  while (fsSync.existsSync(path.join(dir, имя))) {
    имя = `${базовое} ${n}`;
    n++;
  }
  return имя;
}

async function ensureDir(p) {
  await fs.mkdir(p, { recursive: true });
}

async function readJson(file, fallback) {
  try {
    return JSON.parse(await fs.readFile(file, "utf-8"));
  } catch {
    return fallback;
  }
}

/**
 * Запись через временный файл.
 *
 * Прямая запись поверх существующего файла на стройке уже стоила данных: свет
 * моргнул посреди сохранения сметы — и вместо сметы обрезанный кусок JSON,
 * который не читается ничем. Запись во временный файл и переименование делает
 * замену мгновенной: либо старый файл целиком, либо новый целиком.
 */
async function writeJson(file, data) {
  await ensureDir(path.dirname(file));
  const tmp = `${file}.tmp`;
  await fs.writeFile(tmp, JSON.stringify(data, null, 2), "utf-8");
  await fs.rename(tmp, file);
}

class Хранилище {
  constructor(корень) {
    this.корень = корень;
  }

  get папкаПосёлков() {
    return path.join(this.корень, "посёлки");
  }

  путьПосёлка(имя) {
    return path.join(this.папкаПосёлков, имя);
  }

  путьДома(имяПосёлка, имяДома) {
    return path.join(this.путьПосёлка(имяПосёлка), "дома", имяДома);
  }

  async подготовить() {
    await ensureDir(this.папкаПосёлков);
  }

  // ---------- посёлки ----------

  async посёлки() {
    await this.подготовить();
    const записи = await fs.readdir(this.папкаПосёлков, { withFileTypes: true });
    const список = [];
    for (const запись of записи) {
      if (!запись.isDirectory()) continue;
      const данные = await readJson(path.join(this.путьПосёлка(запись.name), "посёлок.json"), null);
      if (!данные) continue;
      const дома = await this.дома(запись.name);
      список.push({
        ...данные,
        папка: запись.name,
        домов: дома.length,
        // Сводка по статусам нужна прямо в списке посёлков: руководитель
        // выбирает посёлок по тому, где сейчас стройка, а не по алфавиту.
        поСтатусам: дома.reduce((acc, д) => {
          acc[д.статус] = (acc[д.статус] || 0) + 1;
          return acc;
        }, {}),
      });
    }
    return список.sort((a, b) => a.название.localeCompare(b.название, "ru"));
  }

  async посёлок(папка) {
    const данные = await readJson(path.join(this.путьПосёлка(папка), "посёлок.json"), null);
    return данные ? { ...данные, папка } : null;
  }

  async создатьПосёлок(данные) {
    await this.подготовить();
    const папка = свободноеИмя(this.папкаПосёлков, имяПапки(данные.название));
    const посёлок = {
      id: id(),
      название: данные.название || папка,
      адрес: данные.адрес || "",
      // Картинка карты не копируется внутрь — хранится путь к файлу на диске.
      картаФайл: данные.картаФайл || "",
      картаШирина: данные.картаШирина || 0,
      картаВысота: данные.картаВысота || 0,
      улицы: данные.улицы || [],
      создан: ныне(),
    };
    await writeJson(path.join(this.путьПосёлка(папка), "посёлок.json"), посёлок);
    await ensureDir(path.join(this.путьПосёлка(папка), "дома"));
    return { ...посёлок, папка };
  }

  async обновитьПосёлок(папка, правка) {
    const текущий = await this.посёлок(папка);
    if (!текущий) throw new Error(`Посёлок «${папка}» не найден`);
    const { папка: _, ...чистый } = { ...текущий, ...правка };
    await writeJson(path.join(this.путьПосёлка(папка), "посёлок.json"), чистый);
    return { ...чистый, папка };
  }

  async удалитьПосёлок(папка) {
    await fs.rm(this.путьПосёлка(папка), { recursive: true, force: true });
  }

  // ---------- дома ----------

  async дома(папкаПосёлка) {
    const dir = path.join(this.путьПосёлка(папкаПосёлка), "дома");
    let записи = [];
    try {
      записи = await fs.readdir(dir, { withFileTypes: true });
    } catch {
      return [];
    }
    const список = [];
    for (const запись of записи) {
      if (!запись.isDirectory()) continue;
      const дом = await readJson(path.join(dir, запись.name, "дом.json"), null);
      if (дом) список.push({ ...дом, папка: запись.name, посёлокПапка: папкаПосёлка });
    }
    return список.sort(сравнитьАдреса);
  }

  async дом(папкаПосёлка, папкаДома) {
    const дом = await readJson(path.join(this.путьДома(папкаПосёлка, папкаДома), "дом.json"), null);
    return дом ? { ...дом, папка: папкаДома, посёлокПапка: папкаПосёлка } : null;
  }

  async создатьДом(папкаПосёлка, данные) {
    const dir = path.join(this.путьПосёлка(папкаПосёлка), "дома");
    await ensureDir(dir);
    const подпись = `${данные.улица || ""} ${данные.номер || ""}`.trim() || "дом";
    const папка = свободноеИмя(dir, имяПапки(подпись));
    const дом = {
      id: id(),
      улица: данные.улица || "",
      номер: данные.номер || "",
      кадастровый: данные.кадастровый || "",
      площадь: Number(данные.площадь) || 0,
      участок: Number(данные.участок) || 0,
      статус: данные.статус || "план",
      // Точка на картинке карты — в долях от её ширины и высоты, а не в
      // пикселях: карту можно заменить на другую картинку, и метки останутся
      // на своих местах.
      точка: данные.точка || { x: 0.5, y: 0.5 },
      контур: данные.контур || [],
      проектПуть: данные.проектПуть || "",
      проектНазвание: данные.проектНазвание || "",
      заказчик: данные.заказчик || { имя: "", телефон: "", договор: "", чатПуть: "" },
      прораб: данные.прораб || "",
      бригада: данные.бригада || "",
      датаНачала: данные.датаНачала || "",
      датаСдачи: данные.датаСдачи || "",
      создан: ныне(),
      изменён: ныне(),
    };
    await writeJson(path.join(dir, папка, "дом.json"), дом);
    return { ...дом, папка, посёлокПапка: папкаПосёлка };
  }

  async обновитьДом(папкаПосёлка, папкаДома, правка) {
    const текущий = await this.дом(папкаПосёлка, папкаДома);
    if (!текущий) throw new Error(`Дом «${папкаДома}» не найден`);
    const { папка: _, посёлокПапка: __, ...чистый } = { ...текущий, ...правка, изменён: ныне() };
    await writeJson(path.join(this.путьДома(папкаПосёлка, папкаДома), "дом.json"), чистый);
    return { ...чистый, папка: папкаДома, посёлокПапка: папкаПосёлка };
  }

  async удалитьДом(папкаПосёлка, папкаДома) {
    await fs.rm(this.путьДома(папкаПосёлка, папкаДома), { recursive: true, force: true });
  }

  /**
   * Улица домов одной кнопкой.
   *
   * Посёлки строятся улицами, а не по одному дому: заводить пятнадцать
   * одинаковых карточек руками — полчаса работы и три опечатки в нумерации.
   * Метки раскладываются вдоль прямой, а потом их таскают мышкой по карте.
   */
  async создатьУлицу(папкаПосёлка, { улица, сНомера, доНомера, шагНомера, площадь, проектПуть, проектНазвание, начало, конец }) {
    const первый = Number(сНомера) || 1;
    const последний = Number(доНомера) || первый;
    const шаг = Math.max(1, Number(шагНомера) || 1);
    const созданные = [];
    const всего = Math.max(1, Math.floor((последний - первый) / шаг) + 1);
    for (let i = 0; i < всего; i++) {
      const доля = всего === 1 ? 0 : i / (всего - 1);
      const точка = начало && конец
        ? { x: начало.x + (конец.x - начало.x) * доля, y: начало.y + (конец.y - начало.y) * доля }
        : { x: 0.1 + доля * 0.8, y: 0.5 };
      созданные.push(
        await this.создатьДом(папкаПосёлка, {
          улица,
          номер: String(первый + i * шаг),
          площадь,
          проектПуть,
          проектНазвание,
          точка,
        })
      );
    }
    return созданные;
  }

  // ---------- разделы дома ----------

  файлРаздела(папкаПосёлка, папкаДома, раздел) {
    if (!РАЗДЕЛЫ_ДОМА.includes(раздел)) throw new Error(`Неизвестный раздел дома: ${раздел}`);
    return path.join(this.путьДома(папкаПосёлка, папкаДома), `${раздел}.json`);
  }

  async раздел(папкаПосёлка, папкаДома, раздел) {
    const пусто = ПУСТО[раздел];
    const данные = await readJson(this.файлРаздела(папкаПосёлка, папкаДома, раздел), null);
    // Разложение поверх пустого, а не вместо него: файл, записанный прошлой
    // версией программы, не должен ронять новую отсутствующим полем.
    return данные ? { ...структураКопия(пусто), ...данные } : структураКопия(пусто);
  }

  async записатьРаздел(папкаПосёлка, папкаДома, раздел, данные) {
    await writeJson(this.файлРаздела(папкаПосёлка, папкаДома, раздел), данные);
    return данные;
  }

  /** Папка отчётов клиенту — обычная папка, её открывают в проводнике. */
  папкаОтчётов(папкаПосёлка, папкаДома) {
    return path.join(this.путьДома(папкаПосёлка, папкаДома), "отчёты");
  }
}

function структураКопия(o) {
  return JSON.parse(JSON.stringify(o));
}

/**
 * Порядок домов — как на улице, а не как в алфавите.
 *
 * «Липовая 2, 10, 12» строкой сортируется как «10, 12, 2»: номер дома читается
 * посимвольно, и десятый дом оказывается раньше второго. На карте это заметно
 * сразу — метки идут вразнобой, — а в списке поставок приводит к тому, что
 * машина едет по улице зигзагом.
 */
function сравнитьАдреса(a, b) {
  const поУлице = String(a.улица || "").localeCompare(String(b.улица || ""), "ru");
  if (поУлице !== 0) return поУлице;
  const na = Number(String(a.номер).replace(/\D+/g, "")) || 0;
  const nb = Number(String(b.номер).replace(/\D+/g, "")) || 0;
  if (na !== nb) return na - nb;
  return String(a.номер).localeCompare(String(b.номер), "ru");
}

module.exports = { Хранилище, РАЗДЕЛЫ_ДОМА, ПУСТО, id, ныне, readJson, writeJson, ensureDir, имяПапки, сравнитьАдреса };
