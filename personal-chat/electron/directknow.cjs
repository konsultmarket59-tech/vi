/**
 * Вопрос к модели про одну ячейку таблицы.
 *
 * Модели отдаются все числа строки, а не только та, в которую ткнули: объяснить
 * высокий CPA, не видя CTR и конверсии, невозможно — получится общий текст.
 */
function explainCellPrompt({ column, value, row, totals, range }) {
  const числа = [
    ["Расход, ₽", row.cost],
    ["Показы", row.impressions],
    ["Клики", row.clicks],
    ["CTR, %", row.ctr],
    ["CPC, ₽", row.cpc],
    ["Конверсии", row.conversions],
    ["Конверсия, %", row.conversionRate],
    ["CPA, ₽", row.cpa],
    ["Доход, ₽", row.revenue],
    ["ДРР, %", row.drr],
    ["ROI, %", row.roi],
    ["Отказы, %", row.bounceRate],
  ]
    .map(([имя, знач]) => `${имя}: ${знач === null || знач === undefined ? "нет данных" : знач}`)
    .join("\n");

  const среднее = totals
    ? [
        `Расход по отобранным кампаниям: ${totals.cost}`,
        `CTR: ${totals.ctr ?? "нет данных"}`,
        `CPC: ${totals.cpc ?? "нет данных"}`,
        `CPA: ${totals.cpa ?? "нет данных"}`,
        `Конверсия: ${totals.conversionRate ?? "нет данных"}`,
      ].join("\n")
    : "нет";

  return `${KNOWLEDGE}

## Вопрос

Человек ткнул в ячейку «${column.title}» и спрашивает, почему там такое значение.

Значение: ${value === null || value === undefined || value === "" ? "пусто" : value}
Что означает столбец: ${column.explain}

Кампания: ${row.name} (аккаунт «${row.account}», id ${row.campaignId})
Состояние: ${row.state}${row.stateNote ? ` — ${row.stateNote}` : ""}
Размещение: ${row.placement || "не указано"}
Стратегия и бюджет: ${row.strategy || "не указаны"}
Период: ${range?.dateFrom || "?"} — ${range?.dateTo || "?"}

Все числа этой кампании за период:
${числа}

Для сравнения, по всем отобранным кампаниям:
${среднее}

Ответь по-русски, обращаясь к человеку на «вы», без списков из десяти пунктов:
что это значит, почему получилось именно так, что проверить и что сделать.
Если числа слишком малы для вывода — скажи это прямо и не выдумывай причину.`;
}

module.exports = { KNOWLEDGE, SHORT, explainCellPrompt };
