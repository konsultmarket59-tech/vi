const KNOWLEDGE = `## Как устроен Яндекс Директ

Аукцион. В поиске цена клика определяется аукционом VCG: платишь не свою ставку,
а столько, сколько нужно, чтобы удержать позицию. Поэтому цену клика нельзя
«назначить» — она получается. На неё влияют ставка, прогнозный CTR объявления и
коэффициент качества (соответствие запроса, объявления и посадочной страницы).
Отсюда главное следствие: поднятая ставка почти никогда не единственный ответ —
объявление с лучшим CTR получает ту же позицию дешевле.

Места показа. Поиск и Рекламная сеть (РСЯ) — разные среды, их показатели нельзя
сравнивать между собой. В поиске человек уже ищет и CTR измеряется процентами;
в сети реклама попадается ему сама, CTR там доли процента, а отказы выше. Низкий
CTR в сети — норма, низкий CTR в поиске — симптом.

Стратегии.
- Ручное управление: полный контроль, но требует постоянного присмотра.
- Оптимизация кликов: максимум кликов в рамках бюджета, конверсии не учитываются.
- Оптимизация конверсий (с оплатой за клики или за конверсии): Директ сам ищет
  тех, кто конвертируется. Стратегии нужны данные: пока в неделю не набирается
  порядка десяти конверсий, обучение не завершается и расход ведёт себя
  непредсказуемо. Это самая частая причина «стратегия слила бюджет».
- Целевая доля рекламных расходов (ДРР): работает только там, где Метрика
  передаёт доход.
Любое изменение стратегии, ставки или бюджета перезапускает обучение: менять
всё сразу и каждый день — значит не дать системе ни одного законченного цикла.

Обучение и период. Меньше 300 показов или 30 кликов — статистики ещё нет, и
выводы по ней случайны. Решения об отключении принимают по накопленным числам,
а не по одному дню.

Ключевые фразы и соответствие. Фраза без операторов ловит все словоформы и
дополнения. Операторы: + фиксирует предлог или союз, ! фиксирует словоформу,
"" ограничивает фразу ровно этими словами, [] фиксирует порядок слов. Плюс к
этому автотаргетинг, который подбирает запросы сам — и именно он чаще всего
приносит мусорный трафик, если его не ограничивать.

Минус-слова. Живут на трёх уровнях: аккаунт, кампания, группа. Работают только
против будущих показов — уже потраченное не вернётся. Смотреть надо отчёт
«Поисковые запросы»: там видно, по каким реальным запросам показывались, а не
какие фразы добавлены. Классический мусор: «бесплатно», «своими руками»,
«отзывы», «вакансии», «б/у», названия конкурентов, другие города.

Площадки в сети. В РСЯ расход уходит десяткам площадок, и часть из них —
приложения и сайты с случайными кликами. Их видно в отчёте по площадкам; те, что
дали расход без конверсий при заметном числе кликов, отключают в запрещённых
площадках. Отключать площадку по двум кликам бессмысленно — это шум.

Корректировки ставок. По полу и возрасту, устройствам, геолокации, сегментам
Метрики и списку ретаргетинга, времени показа. Корректировка -100 % по сегменту
фактически исключает его. Корректировки перемножаются — несколько сильных
корректировок вместе дают неожиданный результат.

Модерация и статусы. Кампания не показывается, если: она на модерации,
отклонена, остановлена вручную, в архиве, кончились деньги (запрет показов по
оплате) или не наступила дата начала. Прежде чем искать причину в ставках,
проверяют именно это.

Метрика. Конверсии, отказы, глубина просмотра и доход приходят не из Директа, а
из Метрики. Пустые столбцы конверсий почти всегда означают, что счётчик не
привязан к кампании или цели не настроены, а не что конверсий не было. Доход и
ДРР требуют настроенной электронной коммерции.

Атрибуция. Модель атрибуции решает, какому визиту засчитать конверсию.
«Последний значимый переход» — то, что стоит по умолчанию; при длинном цикле
сделки она занижает вклад первых касаний. Сравнивать периоды, посчитанные по
разным моделям, нельзя.

## Как отвечать про конкретное число

1. Сначала сказать, из чего это число складывается и что оно измеряет.
2. Назвать причины такого значения — от самой вероятной к менее вероятной,
   опираясь на остальные числа этой же строки, а не на общие соображения.
3. Отделить то, что видно из данных, от того, что надо проверить руками
   (в Метрике, на сайте, в отчёте поисковых запросов).
4. Закончить тем, что сделать: одно-два конкретных действия, а не список из
   десяти пунктов.
5. Если данных мало — сказать это прямо и не делать вывода. Честное «по 12
   кликам ничего сказать нельзя» полезнее уверенного вымысла.`;

