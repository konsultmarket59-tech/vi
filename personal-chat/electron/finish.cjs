/**
 * Выход из набора проверок с гарантией, что вывод дошёл до читателя.
 *
 * process.exit() и app.exit() обрывают процесс немедленно. Когда stdout —
 * канал (а это ровно случай общего прогона, который читает вывод через
 * `out=$(...)`), запись идёт асинхронно: последние строки, включая итоговую
 * «Все проверки пройдены», могут не успеть уйти. Исправный набор при этом
 * выглядит как молча упавший, и разобраться в таком отчёте нечем — вывода нет.
 *
 * Поэтому выходим не сразу, а после того, как буфер вывода опустеет. Итог
 * печатает вызывающий и делает это ДО уборки: если уборка споткнётся, результат
 * прогона всё равно будет виден.
 */
function finish(failures, exit) {
  const code = failures === 0 ? 0 : 1;
  process.exitCode = code;
  process.stdout.write("", () => exit(code));
}

module.exports = { finish };
