// Переписка с агентом, привязанная к открытому документу (Excel и Word).
//
// Зачем ключ. Открываешь другую таблицу — агент должен говорить о ней, а не
// продолжать вчерашний разговор о файле, которого уже нет на экране. Ключ —
// путь к файлу; при несовпадении переписка начинается с чистого листа.
//
// Почему у несохранённого документа ключ НЕ из имени. Имя у всех новых книг
// одно и то же — «Новая книга.xlsx». По имени второй «новый документ»
// открывал переписку от первого: агент тащил в каждый запрос всю прошлую
// историю, и чем дольше человек работал до этого, тем дольше шёл ответ. Со
// стороны это выглядело как «приложение тормозит», хотя дело было в том, что
// в запрос каждый раз уезжал чужой разговор целиком.
//
// Поэтому у каждого созданного документа есть свой номер, живущий ровно
// столько, сколько сам документ в памяти. Сохранили файл — ключом становится
// путь, и переписка переезжает вместе с ним.

let счётчик = 0;

/** Номер нового документа: у каждого свой, у двух подряд — разные. */
function newSessionId() {
  счётчик += 1;
  return `${Date.now().toString(36)}-${счётчик}`;
}

function documentChatKey(model) {
  if (!model) return "";
  if (model.filePath) return model.filePath;
  if (model.sessionId) return `__new__:${model.sessionId}`;
  // Документ без номера — из старой версии приложения. Общего ключа ему не
  // даём: лучше пустая переписка, чем чужая.
  return `__new__:${model.name || "без имени"}`;
}

module.exports = { newSessionId, documentChatKey };
