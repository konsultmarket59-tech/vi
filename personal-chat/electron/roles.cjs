async function list(root) {
  const dir = rolesDir(root);
  const overrides = new Map();
  let files = [];
  try {
    files = await fs.readdir(dir);
  } catch {
    files = [];
  }
  for (const file of files) {
    if (!file.endsWith(".json")) continue;
    try {
      const raw = await fs.readFile(path.join(dir, file), "utf-8");
      const parsed = JSON.parse(raw);
      if (parsed && parsed.id) overrides.set(parsed.id, { ...parsed, edited: true });
    } catch {
      // Испорченный файл роли — не повод обрушить список ролей целиком.
    }
  }

  const result = PRESETS.map((preset) => normalize(overrides.get(preset.id) || preset, preset));
  const custom = [];
  for (const [id, role] of overrides) {
    if (!PRESET_IDS.has(id)) custom.push(normalize({ ...role, edited: false }, null));
  }
  custom.sort((a, b) => a.name.localeCompare(b.name, "ru"));
  return [...result, ...custom];
}

async function save(root, role) {
  const dir = rolesDir(root);
  await fs.mkdir(dir, { recursive: true });
  const id = PRESET_IDS.has(role.id) ? role.id : safeId(role.id || role.name) || `role-${Date.now()}`;
  const preset = PRESETS.find((p) => p.id === id) || null;
  const saved = normalize({ ...role, id }, preset);
  await fs.writeFile(path.join(dir, `${id}.json`), JSON.stringify(saved, null, 2), "utf-8");
  return { ...saved, edited: true };
}

/**
 * Убирает роль: свою — совсем, встроенную — только правку, возвращая исходную.
 *
 * Встроенную роль нельзя удалить насовсем намеренно: тогда «Браузер» у разных
 * людей превращался бы в разный набор специалистов, и любой совет из документации
 * («спросите экономиста») перестал бы работать.
 */
async function remove(root, id) {
  const file = path.join(rolesDir(root), `${id}.json`);
  await fs.rm(file, { force: true });
  const preset = PRESETS.find((p) => p.id === id);
  return preset ? normalize(preset, preset) : null;
}

/**
 * Собирает системный промпт роли для одного запроса.
 *
 * Порядок частей важен из-за кэша провайдера: он совпадает по началу промпта,
 * поэтому сначала идёт неизменное (общие правила и сама роль), потом контекст
 * проекта, и только в конце — то, что меняется от сообщения к сообщению
 * (открытая страница, состав переговорки).
 */
function buildSystemPrompt({ role, projectPrompt = "", page = null, room = null, mode = "chat" }) {
  const parts = [`Ты — ${role.name}. ${role.tagline || ""}`.trim(), "", role.prompt, "", ROLE_COMMON];

  if (projectPrompt) {
    parts.push(
      "",
      "=== ПРОЕКТ, В КОТОРОМ ИДЁТ РАБОТА ===",
      "Это постоянный контекст: инструкции и материалы проекта человека. Опирайся на него, " +
        "не переспрашивая то, что здесь уже сказано.",
      projectPrompt
    );
  }

  if (room && Array.isArray(room.roles) && room.roles.length > 1) {
    const others = room.roles.filter((r) => r.id !== role.id).map((r) => `${r.emoji} ${r.name} — ${r.tagline}`);
    parts.push(
      "",
      "=== ПЕРЕГОВОРКА ===",
      ROOM_RULES,
      "",
      "Кто ещё в переговорке:",
      ...others.map((line) => `- ${line}`)
    );
  }

  if (mode === "task") {
    parts.push(
      "",
      "=== РЕЖИМ ЗАДАНИЯ ===",
      "Это поручение, а не разговор: человек не сидит рядом и не будет отвечать на уточнения.",
      "Работай сам: ищи в интернете, открывай страницы, сверяй источники между собой — до тех пор, " +
        "пока не сможешь ответить по существу.",
      "Ответ отдай так, чтобы его можно было сразу сохранить в файл:",
      "1. Заголовок первой строкой (# Заголовок).",
      "2. Короткая выжимка — 3–5 строк: что выяснено и что из этого следует.",
      "3. Основная часть: разделы, таблицы (обычной разметкой markdown — из неё собирается Excel).",
      "4. Раздел «Источники»: ссылки с датой обращения.",
      "5. Раздел «Чего не хватило»: что проверить руками и почему.",
      "Не пиши «нужно уточнить и я подожду» — назови допущение, на котором работал."
    );
  }

  if (page && page.url) {
    const text = String(page.text || "").slice(0, 12000);
    parts.push(
      "",
      "=== ОТКРЫТАЯ СТРАНИЦА ===",
      `Человек сейчас смотрит эту страницу в браузере приложения: ${page.title || ""} — ${page.url}`,
      text
        ? "Ниже — её текст в том виде, в каком он виден в окне (может быть обрезан). " +
          "Отвечая о странице, опирайся на него, а не на догадки о сайте.\n\n" +
          text
        : "Текст страницы получить не удалось — если он нужен, скажи об этом."
    );
  }

  return parts.join("\n");
}

module.exports = {
  ROLE_COMMON,
  ROOM_RULES,
  presets,
  list,
  save,
  remove,
  buildSystemPrompt,
  safeId,
  PRESET_IDS,
};
