const PRESET_IDS = new Set(PRESETS.map((r) => r.id));

function rolesDir(root) {
  return path.join(root, "roles");
}

function safeId(id) {
  return String(id || "")
    .toLowerCase()
    .replace(/[^a-zа-я0-9_-]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}

/** Роль в том виде, в каком её ждёт остальное приложение. */
function normalize(role, preset) {
  const base = preset || {};
  return {
    id: role.id || base.id,
    name: (role.name ?? base.name ?? "Без названия").toString().slice(0, 60),
    emoji: (role.emoji ?? base.emoji ?? "🧠").toString().slice(0, 8),
    color: /^#[0-9a-f]{6}$/i.test(role.color || "") ? role.color : base.color || "#4f7cff",
    tagline: (role.tagline ?? base.tagline ?? "").toString().slice(0, 120),
    prompt: (role.prompt ?? base.prompt ?? "").toString(),
    // Пусто — модель из общих настроек. Отдельная модель на роль нужна затем,
    // чтобы дешёвую работу (собрать ссылки) не гонять через дорогую модель, а
    // разбор картинки не отдавать модели, которая картинок не видит.
    model: (role.model ?? base.model ?? "").toString(),
    web: role.web === undefined ? base.web !== false : role.web !== false,
    builtIn: PRESET_IDS.has(role.id || base.id),
    // Роль, изменённую человеком, видно в списке: у неё есть «Вернуть как было».
    edited: Boolean(role.edited),
  };
}

function presets() {
  return PRESETS.map((r) => normalize(r, r));
}

